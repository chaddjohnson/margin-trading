// Builds the demo dataset: a synthetic daily price series and the toy rules' events on it. Deterministic: the same
// generator version and seed always produce the same dataset (and, through serialize.ts, the same bytes).

import {
  DATASET_SCHEMA_ID,
  DATASET_SCHEMA_VERSION,
  type Dataset,
  type EntryEvent,
  type PriceBar
} from '../demo-schema/types.ts';
import { weekdaySessions } from './calendar.ts';
import { OCCUPANCY_SESSIONS, applyExecution, demoExecutionModel } from './execution.ts';
import { syntheticPath } from './prices.ts';
import { DEMO_RULES, buildContext } from './rules.ts';

export const GENERATOR = { name: 'strategy-entry-explorer-demo', version: '1.0.0' };
// Chosen by screening seeds 20261100–20261499 for a path with 4–8.5× growth, a 25–42% maximum drawdown and at least four
// corrections of 10% or more, so the demo has rallies and pullbacks to look at. Nothing was screened on event outcomes.
export const DEMO_SEED = 20261133;
export const DEMO_FIRST_SESSION = '2016-01-04';
export const DEMO_LAST_SESSION = '2026-10-30';
export const DEMO_START_PRICE = 100;
const TIME_ZONE = 'America/New_York';

export function generateDemoDataset(seed: number = DEMO_SEED): Dataset {
  const sessions = weekdaySessions(DEMO_FIRST_SESSION, DEMO_LAST_SESSION, TIME_ZONE);
  const path = syntheticPath(sessions.length, seed, DEMO_START_PRICE);
  const bars: PriceBar[] = sessions.map((s, i) => {
    const p = path[i] as (typeof path)[number];
    return { t: s.t, d: s.d, o: p.o, h: p.h, l: p.l, c: p.c };
  });
  const closes = bars.map((b) => b.c);
  const ctx = buildContext(
    bars.map((b) => b.d),
    closes,
    bars.map((b) => b.l)
  );

  const variations = DEMO_RULES.map((rule) => {
    const events: EntryEvent[] = applyExecution(rule.id, rule.detect(ctx), sessions, closes);
    return {
      id: rule.id,
      code: rule.code,
      name: rule.name,
      family: rule.family,
      summary: rule.summary,
      parameters: rule.parameters,
      events
    };
  });

  return {
    schema: DATASET_SCHEMA_ID,
    schemaVersion: DATASET_SCHEMA_VERSION,
    datasetId: 'demo-synthetic-daily-v1',
    title: 'Demo: synthetic daily prices with illustrative entry events',
    provenance: {
      kind: 'synthetic',
      description:
        `Generated by ${GENERATOR.name} ${GENERATOR.version} with seed ${seed}: a regime-switching geometric random ` +
        `walk with invented parameters, starting at ${DEMO_START_PRICE.toFixed(2)} on ${DEMO_FIRST_SESSION}. No market ` +
        'data was read. Events come from twelve toy demo rules applied to these synthetic closes.',
      generator: { ...GENERATOR, seed },
      disclosures: [
        'Synthetic, fictional prices from a seeded random walk. They are not actual VGT prices and are not derived from any market data.',
        'Entry events come from toy demo rules applied to the synthetic prices. They are not strategy candidates, verified trades or research results.',
        `"Executed" entries are an illustrative subset (one position at a time, a ${OCCUPANCY_SESSIONS}-session occupancy placeholder), not a trading, exit or portfolio simulation.`
      ]
    },
    instrument: {
      symbol: 'VGT',
      label: 'VGT (illustrative label) · synthetic prices',
      isSynthetic: true,
      currency: 'USD',
      priceAdjustment: 'none',
      exchangeTimezone: TIME_ZONE
    },
    priceSeries: {
      interval: '1d',
      timestampConvention: 'bar-close',
      calendar:
        'Synthetic: every Monday–Friday from 2016-01-04 to 2026-10-30; exchange holidays and early closes are not ' +
        'modelled. Each bar is stamped at its 16:00 America/New_York session close (20:00Z or 21:00Z).',
      bars
    },
    executionModel: demoExecutionModel,
    variations
  };
}
