// Parameter-injectable copies of the variant strategy files (and of file 4, their base) for parity with the
// engine. Each copy is the source with a fixed list of substitutions, each required to match exactly once:
// an exported `injected` object read at call time, the session list, every hard-coded constant (matched by
// name and a numeric literal, so the checked-in values may change), and the arming guard honouring a common
// first eligible session. With nothing injected a copy behaves exactly as its source. The originals are never
// modified; copies go to src/trailing-buy-variants/generated/ (git-ignored).
import { createHash } from 'node:crypto';
import path from 'node:path';
import fs from 'fs-extra';

export const variantSourceFiles = {
  bufferedLossNoReentry: 'src/app/allIn-trailingBuy-bufferedLoss-noReentry.ts',
  invalidation: 'src/app/allIn-trailingBuy-invalidation.ts',
  episodeBudget: 'src/app/allIn-trailingBuy-episodeBudget.ts',
  depthRebound: 'src/app/allIn-trailingBuy-depthRebound.ts',
  staged: 'src/app/allIn-trailingBuy-staged.ts',
  progressHold: 'src/app/allIn-trailingBuy-progressHold.ts',
  persistence: 'src/app/allIn-trailingBuy-persistence.ts'
} as const;

export type VariantSourceKey = keyof typeof variantSourceFiles;

export const generatedDir = 'src/trailing-buy-variants/generated';

export const injectableConstants = [
  'tickWindowSize',
  'trailingStopPercentage',
  'maximumHoldDays',
  'marginInterestRate',
  'invalidationBuffer',
  'episodeLossBudget',
  'episodeResetRetrace',
  'reboundDepthSlope',
  'initialFraction',
  'addTrigger',
  'progressThreshold',
  'holdExtensionDays',
  'confirmMinutes'
] as const;

export type InjectableConstant = (typeof injectableConstants)[number];

const injectedDeclaration = `import fs from 'fs-extra';

// Generated by src/trailing-buy-variants/copies.ts from the original strategy file: parameter injection for
// parity with the engine. Do not edit; regenerate with \`npm run trailing-buy-variants -- parity\`.
export const injected: {
  sessions?: MarketSession[];
  armStart?: number;
${injectableConstants.map((name) => `  ${name}?: number;`).join('\n')}
} = {};`;

export const sha256 = (text: string | Buffer) => createHash('sha256').update(text).digest('hex');

export const generateVariantCopy = async (key: VariantSourceKey) => {
  const file = variantSourceFiles[key];
  const source = await fs.readFile(file, 'utf8');
  let copy = source;
  const once = (from: string | RegExp, to: string, label: string) => {
    const matches = typeof from === 'string' ? copy.split(from).length - 1 : (copy.match(from) ?? []).length;

    if (matches !== 1) {
      throw new Error(`${file}: expected exactly one ${label}, found ${matches}`);
    }

    copy = typeof from === 'string' ? copy.replace(from, () => to) : copy.replace(from, to);
  };
  const constants: string[] = [];

  once("import fs from 'fs-extra';", injectedDeclaration, 'fs import');
  once(
    'const allSessions = groupMarketSessions(await loadCsvMinuteBacktestData(symbol, file));',
    'const allSessions = injected.sessions ?? groupMarketSessions(await loadCsvMinuteBacktestData(symbol, file));',
    'session load'
  );
  once(
    'if (index < tickWindowSize || !isDip(bar.close)) {',
    'if (index < Math.max(tickWindowSize, injected.armStart ?? 0) || !isDip(bar.close)) {',
    'arming guard'
  );

  for (const name of injectableConstants) {
    const pattern = new RegExp(`const ${name} = ([0-9.]+);`, 'g');
    const matches = copy.match(pattern) ?? [];

    if (matches.length > 1) {
      throw new Error(`${file}: ${name} is declared ${matches.length} times`);
    }

    if (matches.length === 1) {
      copy = copy.replace(pattern, (_match, literal: string) => `const ${name} = injected.${name} ?? ${literal};`);
      constants.push(name);
    }
  }

  const target = path.join(generatedDir, path.basename(file));

  await fs.ensureDir(generatedDir);
  await fs.writeFile(path.join(generatedDir, '.gitignore'), '*\n');
  await fs.writeFile(target, copy);

  return { key, source: file, sourceHash: sha256(source), target, constants };
};

export const variantSourceHashes = async () =>
  Object.fromEntries(
    await Promise.all(
      (Object.keys(variantSourceFiles) as VariantSourceKey[]).map(async (key) => [
        key,
        sha256(await fs.readFile(variantSourceFiles[key]))
      ])
    )
  ) as Record<VariantSourceKey, string>;
