export const generatedDir = 'src/four-family/generated';

const injectedDeclaration = `import fs from 'fs-extra';

// Generated by src/four-family/copies.ts from the original strategy file: parameter injection for the
// four-family golden master. Do not edit; regenerate with \`npm run four-family -- copies\`.
export const injected: {
  sessions?: MarketSession[];
  tickWindowSize?: number;
  targetPercentChange?: number;
  trailingStopPercentage?: number;
  maximumHoldDays?: number;
  marginInterestRate?: number;
  materialLossThreshold?: number;
  lowerPriceReentry?: number;
  retraceFraction?: number;
  armStart?: number;
} = {};`;

const constant = (name: string, literal: string) => ({
  from: `const ${name} = ${literal};`,
  to: `const ${name} = injected.${name} ?? ${literal};`
});

const common = [
  { from: "import fs from 'fs-extra';", to: injectedDeclaration },
  {
    from: 'const allSessions = groupMarketSessions(await loadCsvMinuteBacktestData(symbol, file));',
    to: 'const allSessions = injected.sessions ?? groupMarketSessions(await loadCsvMinuteBacktestData(symbol, file));'
  },
  constant('tickWindowSize', '90'),
  constant('trailingStopPercentage', '0.08'),
  constant('maximumHoldDays', '15'),
  constant('marginInterestRate', '0.11')
];

const restriction = [
  constant('materialLossThreshold', '0.01'),
  constant('lowerPriceReentry', '0.02'),
  constant('retraceFraction', '0.38')
];

const trailingWarmup = {
  from: 'if (index < tickWindowSize || !isDip(bar.close)) {',
  to: 'if (index < Math.max(tickWindowSize, injected.armStart ?? 0) || !isDip(bar.close)) {'
};

export const substitutions: Record<SourceKey, { from: string; to: string }[]> = {
  trailingBuy: [...common, ...restriction, trailingWarmup],
  bufferedLoss: [...common, ...restriction, trailingWarmup],
  noReentry: [...common, trailingWarmup],
  bufferedLossNoReentry: [...common, trailingWarmup],
  allIn: [
    ...common,
    ...restriction,
    constant('targetPercentChange', '0.1'),
    {
      from: 'let buy = openPositions.length === 0 && signal;',
      to: 'let buy = openPositions.length === 0 && signal && index >= (injected.armStart ?? 0);'
    }
  ]
};

export const sha256 = (text: string | Buffer) => createHash('sha256').update(text).digest('hex');

const countOccurrences = (text: string, needle: string) => text.split(needle).length - 1;

export const generateCopy = async (key: SourceKey) => {
  const source = frozenSourceText(frozenSources[key]);
  let copy = source;

  for (const { from, to } of substitutions[key]) {
    const occurrences = countOccurrences(copy, from);

    if (occurrences !== 1) {
      throw new Error(`${sourceFiles[key]}: expected exactly one "${from}", found ${occurrences}`);
    }

    copy = copy.replace(from, () => to);
  }

  const target = path.join(generatedDir, path.basename(sourceFiles[key]));

  await fs.ensureDir(generatedDir);
  await fs.writeFile(path.join(generatedDir, '.gitignore'), '*\n');
  await fs.writeFile(target, copy);

  return {
    key,
    source: sourceFiles[key],
    sourceHash: sha256(source),
    target,
    substitutions: substitutions[key].length
  };
};

export const generateCopies = async () => Promise.all((Object.keys(sourceFiles) as SourceKey[]).map(generateCopy));

export const sourceHashes = async () =>
  Object.fromEntries(
    (Object.keys(sourceFiles) as SourceKey[]).map((key) => [key, sha256(frozenSourceText(frozenSources[key]))])
  ) as Record<SourceKey, string>;
