import {
  type Data,
  formatDollars,
  formatSignedDollars,
  fullSpec,
  option,
  protocol,
  stageDir,
  writeJson,
  writeText
} from './context.ts';
import type { Trade } from './engine.ts';
import { type Metrics, evaluateCandidate } from './evaluate.ts';
import {
  type Family,
  type IntParams,
  type ParamKey,
  d1Params,
  describeParams,
  familyOf,
  formatValue
} from './families.ts';
import { type Box, runLocalStudy } from './local.ts';
import { makeCaches } from './pool.ts';
import { diffTrades, metricsHeader, metricsRow, segmentTable } from './report.ts';
import {
  type Row,
  evaluateRows,
  feasible,
  makeEvaluator,
  paretoFront,
  product,
  segmentOf,
  writeRows
} from './study.ts';

// The standalone grids (tenths of a point; D1's buffer 2.9% kept, D1's exit set as the control).
export const c1Grid = (): IntParams[] =>
  product({
    alwaysRebound: [3, 5, 10, 15, 20, 30, 40, 50, 60, 80, 100, 120, 150],
    trailingStopPercentage: [50, 60, 73, 80, 100, 120],
    maximumHoldDays: [8, 15, 30]
  });

export const c2Grid = (): IntParams[] =>
  product({
    swingLookback: [5, 10, 15, 20, 30, 40, 60, 90, 120],
    swingRebound: [3, 5, 10, 20, 30, 50, 80],
    swingProximity: [0, 10, 20],
    trailingStopPercentage: [50, 73, 100],
    maximumHoldDays: [8, 15]
  });

export const c1Box: Box = {
  alwaysRebound: [5, 150],
  trailingStopPercentage: [40, 120],
  maximumHoldDays: [4, 40],
  intradayLossBuffer: [0, 50]
};
export const c2Box: Box = {
  swingLookback: [3, 150],
  swingRebound: [3, 100],
  swingProximity: [0, 30],
  trailingStopPercentage: [40, 120],
  maximumHoldDays: [4, 40],
  intradayLossBuffer: [0, 50]
};

const gridSection = (ds: Data['ds'], title: string, family: Family, rows: Row[], keys: ParamKey[], d1: Metrics) => {
  const lines = [
    `### ${title}`,
    '',
    `${rows.length} cells; ${rows.filter((row) => feasible(row.metrics)).length} within the $35,000 ceiling; ${rows.filter((row) => feasible(row.metrics) && row.metrics.net > d1.net).length} beat D1's net within the ceiling; ${new Set(rows.map((row) => row.metrics.signature)).size} distinct trade lists.`,
    ''
  ];
  const front = paretoFront(rows);

  lines.push(
    'Feasible frontier (net vs minute DD, distinct trade lists):',
    '',
    metricsHeader('Cell', 'Dev / reused | 2022 net (losses)')
  );

  for (const row of front.slice(0, 12)) {
    lines.push(
      metricsRow(
        describeParams(family, row.params, keys),
        row.metrics,
        `${formatSignedDollars(segmentOf(row.metrics, 'development')!.net)} / ${formatSignedDollars(segmentOf(row.metrics, 'reused')!.net)} | ${formatSignedDollars(segmentOf(row.metrics, 'r2022')!.net)} (${segmentOf(row.metrics, 'r2022')!.losses})`
      )
    );
  }

  // Marginal views: best net per value of each key.
  for (const key of keys) {
    const values = [...new Set(rows.map((row) => row.params[key]!))].sort((a, b) => a - b);

    lines.push(
      '',
      `Best feasible cell per ${key}:`,
      '',
      `| ${key} | Best net | Minute DD | Entries | W/L | Exposure | Cells over the ceiling |`,
      '|---|---:|---:|---:|---:|---:|---:|'
    );

    for (const value of values) {
      const at = rows.filter((row) => row.params[key] === value);
      const best = at.filter((row) => feasible(row.metrics)).sort((a, b) => b.metrics.net - a.metrics.net)[0];

      lines.push(
        `| ${formatValue(key, value)} | ${best ? formatDollars(best.metrics.net) : 'none feasible'} | ${best ? formatDollars(best.metrics.minuteDrawdown) : ''} | ${best ? best.metrics.entries : ''} | ${best ? `${best.metrics.wins}/${best.metrics.losses}` : ''} | ${best ? `${(best.metrics.exposure * 100).toFixed(0)}%` : ''} | ${at.filter((row) => !feasible(row.metrics)).length}/${at.length} |`
      );
    }
  }

  lines.push('');

  return { lines, front };
};

export const noDip = async (data: Data, args: string[]) => {
  const { ds } = data;
  const evaluator = makeEvaluator(args);
  const caches = makeCaches(ds);
  const dir = stageDir('trackC');
  const full = fullSpec(ds);
  const started = Date.now();
  const samples = Number(option(args, 'samples') ?? 2048);
  const d1Family = familyOf('d1');
  const d1 = evaluateCandidate(ds, caches, d1Family, d1Params(d1Family), full, true);
  const lines: string[] = [
    '# Track C: trailing buys without a required initial dip (generated by `npm run d1-refinement -- no-dip`)',
    '',
    `All runs from ${protocol.eligibilityDate} (the common eligibility session), $100,000 per entry, 11% interest, stop fills, D1's accounting and exit set (trailing stop active only while a fill at the stop nets a profit; maximum-hold loss exit; buffered intraday loss 2.9%). D1 for comparison: ${formatDollars(d1.metrics.net)} / ${formatDollars(d1.metrics.minuteDrawdown)}, ${d1.metrics.entries} entries, exposure ${(d1.metrics.exposure * 100).toFixed(0)}%.`,
    '',
    '## 1. Standalone grids',
    ''
  ];

  evaluator.register(ds);

  const always = familyOf('always');
  const swing = familyOf('swing');
  const c1Rows = await evaluateRows(
    evaluator,
    ds.id,
    always,
    full,
    c1Grid().map((overrides) => d1Params(always, overrides)),
    'c1-grid'
  );
  const c2Rows = await evaluateRows(
    evaluator,
    ds.id,
    swing,
    full,
    c2Grid().map((overrides) => d1Params(swing, overrides)),
    'c2-grid'
  );

  await writeRows(path.join(dir, 'c1_grid.csv'), always, c1Rows);
  await writeRows(path.join(dir, 'c2_grid.csv'), swing, c2Rows);

  const c1Section = gridSection(
    ds,
    'C1: always-armed trailing buy (Ya × stop × hold, buffer 2.9%)',
    always,
    c1Rows,
    ['alwaysRebound', 'trailingStopPercentage', 'maximumHoldDays'],
    d1.metrics
  );
  const c2Section = gridSection(
    ds,
    'C2: swing trailing buy (K × Ys × Z × stop × hold, buffer 2.9%)',
    swing,
    c2Rows,
    ['swingLookback', 'swingRebound', 'swingProximity', 'trailingStopPercentage', 'maximumHoldDays'],
    d1.metrics
  );

  lines.push(...c1Section.lines, ...c2Section.lines);

  // The literal designs at D1's exit set and Y 0.3%.
  lines.push(
    "### The literal designs at D1's exit set",
    '',
    metricsHeader('Design', 'Exposure share invested | Interest / gross')
  );

  const literal = [
    { label: 'C1 literal: Ya 0.3%, stop 7.3%, hold 8', family: always, params: d1Params(always, { alwaysRebound: 3 }) },
    { label: 'C1: Ya 3.0%, stop 7.3%, hold 8', family: always, params: d1Params(always, { alwaysRebound: 30 }) },
    {
      label: 'C2 literal: K 20, Ys 0.3%, Z 0, stop 7.3%, hold 8',
      family: swing,
      params: d1Params(swing, { swingLookback: 20, swingRebound: 3, swingProximity: 0 })
    },
    {
      label: 'C2: K 60, Ys 3.0%, Z 0, stop 7.3%, hold 8',
      family: swing,
      params: d1Params(swing, { swingLookback: 60, swingRebound: 30, swingProximity: 0 })
    }
  ];

  for (const entry of literal) {
    const { metrics } = evaluateCandidate(ds, caches, entry.family, entry.params, full);

    lines.push(
      metricsRow(
        entry.label,
        metrics,
        `${(metrics.exposure * 100).toFixed(0)}% | ${formatDollars(metrics.interest)} / ${formatDollars(metrics.gross)}`
      )
    );
  }

  lines.push(
    metricsRow(
      'D1',
      d1.metrics,
      `${(d1.metrics.exposure * 100).toFixed(0)}% | ${formatDollars(d1.metrics.interest)} / ${formatDollars(d1.metrics.gross)}`
    ),
    ''
  );

  // Local refinement with walk-forward, anchored at the best feasible grid cell of each design (in-sample choice,
  // labelled as such) and at the literal design.
  lines.push(
    '## 2. Bounded local refinement and walk-forward',
    '',
    "Anchors are the best feasible grid cell of each design (an in-sample choice) and, for C1, the literal design. The box covers the mechanism's own parameters and the exit set; X and L do not exist in these architectures.",
    ''
  );

  const bestC1 = paretoFront(c1Rows)[0];
  const bestC2 = paretoFront(c2Rows)[0];
  const studies: { key: string; family: Family; anchor: IntParams; box: Box; label: string }[] = [];

  if (bestC1) {
    studies.push({
      key: 'c1_best',
      family: always,
      anchor: bestC1.params,
      box: c1Box,
      label: `C1 anchored at the best grid cell (${describeParams(always, bestC1.params)})`
    });
  }

  studies.push({
    key: 'c1_literal',
    family: always,
    anchor: d1Params(always, { alwaysRebound: 3 }),
    box: c1Box,
    label: 'C1 anchored at the literal design (Ya 0.3%)'
  });

  if (bestC2) {
    studies.push({
      key: 'c2_best',
      family: swing,
      anchor: bestC2.params,
      box: c2Box,
      label: `C2 anchored at the best grid cell (${describeParams(swing, bestC2.params)})`
    });
  }

  const results = [];

  for (const study of studies) {
    const result = await runLocalStudy(data, evaluator, {
      ...study,
      samples,
      seedLabel: `trackC-${study.key}`,
      dir,
      minEntriesPerYear: 1
    });

    results.push({ study, result });
    lines.push(...result.lines.map((line) => (line.startsWith('## ') || line.startsWith('### ') ? `#${line}` : line)));
  }

  // C3: D1 plus the extra path. The extra path's parameters: the best standalone cells and a small grid.
  lines.push(
    '## 3. C3: D1 plus an independent no-dip path',
    '',
    "D1's eight parameters frozen; the extra path (always or swing) arms only when D1 would not, yields to D1's deep and continuation armings on the minute they occur, and never closes the continuation window. It can displace a D1 trade only by holding the position when D1 would have armed. Trades are compared with D1: preserved (same entry and exit), altered (same entry, different exit: impossible here, since exits don't depend on the path), gained (extra-path entries) and lost (D1 entries displaced).",
    ''
  );

  const deepAlways = familyOf('deepAlwaysPostExit');
  const deepSwing = familyOf('deepSwingPostExit');
  const c3Grid: { family: Family; params: IntParams; label: string }[] = [];

  for (const ya of [10, 30, 50, 80, 100, 150]) {
    c3Grid.push({
      family: deepAlways,
      params: d1Params(deepAlways, { alwaysRebound: ya }),
      label: `D1 + always Ya ${formatValue('alwaysRebound', ya)}`
    });
  }

  for (const k of [20, 40, 60, 90, 120]) {
    for (const ys of [5, 10, 30, 50]) {
      c3Grid.push({
        family: deepSwing,
        params: d1Params(deepSwing, { swingLookback: k, swingRebound: ys, swingProximity: 0 }),
        label: `D1 + swing K ${k} Ys ${formatValue('swingRebound', ys)}`
      });
    }
  }

  if (bestC2) {
    c3Grid.push({
      family: deepSwing,
      params: d1Params(deepSwing, {
        swingLookback: bestC2.params.swingLookback,
        swingRebound: bestC2.params.swingRebound,
        swingProximity: bestC2.params.swingProximity
      }),
      label: `D1 + swing at C2's best cell (K ${bestC2.params.swingLookback} Ys ${formatValue('swingRebound', bestC2.params.swingRebound)} Z ${formatValue('swingProximity', bestC2.params.swingProximity)})`
    });
  }

  lines.push(metricsHeader('C3 variant', 'Preserved / gained / lost vs D1 | Gained net | Lost D1 net | Upgrades'));

  const c3Results: {
    label: string;
    family: string;
    params: IntParams;
    metrics: Metrics;
    preserved: number;
    gained: number;
    lost: number;
    gainedNet: number;
    lostNet: number;
  }[] = [];

  for (const entry of c3Grid) {
    const result = evaluateCandidate(ds, caches, entry.family, entry.params, full, true);
    const diff = diffTrades(ds, d1.detail!.trades, result.detail!.trades);
    const profitOf = (trade: Trade) => result.detail!.accounting.outcomes[result.detail!.trades.indexOf(trade)]!.profit;
    const d1ProfitOf = (trade: Trade) => d1.detail!.accounting.outcomes[d1.detail!.trades.indexOf(trade)]!.profit;
    const gainedNet = diff.gained.reduce((total, trade) => total + profitOf(trade), 0);
    const lostNet = diff.lost.reduce((total, trade) => total + d1ProfitOf(trade), 0);

    c3Results.push({
      label: entry.label,
      family: entry.family.key,
      params: entry.params,
      metrics: result.metrics,
      preserved: diff.preserved.length,
      gained: diff.gained.length,
      lost: diff.lost.length,
      gainedNet,
      lostNet
    });
    lines.push(
      metricsRow(
        entry.label,
        result.metrics,
        `${diff.preserved.length} / ${diff.gained.length} / ${diff.lost.length} | ${formatSignedDollars(gainedNet)} | ${formatSignedDollars(lostNet)} | ${result.metrics.counts.upgrades}`
      )
    );
  }

  // Displaced D1 trades for the best C3 variant.
  const bestC3 = c3Results.filter((row) => feasible(row.metrics)).sort((a, b) => b.metrics.net - a.metrics.net)[0];

  if (bestC3) {
    const result = evaluateCandidate(ds, caches, familyOf(bestC3.family), bestC3.params, full, true);
    const diff = diffTrades(ds, d1.detail!.trades, result.detail!.trades);
    const d1ProfitOf = (trade: Trade) => d1.detail!.accounting.outcomes[d1.detail!.trades.indexOf(trade)]!.profit;
    const profitOf = (trade: Trade) => result.detail!.accounting.outcomes[result.detail!.trades.indexOf(trade)]!.profit;

    lines.push(
      '',
      `Best feasible C3 variant by net: ${bestC3.label} (${formatDollars(bestC3.metrics.net)} / ${formatDollars(bestC3.metrics.minuteDrawdown)}). D1 trades displaced: ${diff.lost.map((trade) => `${diff.dates(trade)} ${formatSignedDollars(d1ProfitOf(trade))}`).join('; ') || 'none'}. Extra-path trades gained: ${diff.gained.length} for ${formatSignedDollars(diff.gained.reduce((total, trade) => total + profitOf(trade), 0))}; worst ${diff.gained.length > 0 ? formatSignedDollars(Math.min(...diff.gained.map(profitOf))) : 'n/a'}; winners ${diff.gained.filter((trade) => profitOf(trade) > 0).length}, losers ${diff.gained.filter((trade) => profitOf(trade) <= 0).length}.`,
      ''
    );
    lines.push(
      segmentTable(
        [
          { label: 'D1', metrics: d1.metrics },
          { label: bestC3.label, metrics: bestC3.metrics }
        ],
        ['full', 'development', 'reused', ...protocol.regimes.map((regime) => regime.key)]
      ),
      ''
    );
  }

  lines.push(`Runtime ${((Date.now() - started) / 1000).toFixed(0)} s on ${evaluator.description}.`);
  await writeText(path.join(dir, 'trackC_summary.md'), lines.join('\n'));
  await writeJson(path.join(dir, 'c3_grid.json'), c3Results);
  await writeJson(path.join(dir, 'grid_fronts.json'), {
    c1: c1Section.front.map((row) => ({
      params: row.params,
      net: row.metrics.net,
      minuteDrawdown: row.metrics.minuteDrawdown,
      entries: row.metrics.entries
    })),
    c2: c2Section.front.map((row) => ({
      params: row.params,
      net: row.metrics.net,
      minuteDrawdown: row.metrics.minuteDrawdown,
      entries: row.metrics.entries
    }))
  });
  console.info(lines.slice(0, 30).join('\n'));
  console.info(`...\nWritten to ${dir}`);
  await evaluator.close();
};
