// Track C: trailing buys without a required initial dip. C1 (always-armed) and C2 (swing) as standalone
// strategies on coarse grids first, then bounded local refinement with walk-forward; C3 adds the better extra
// path to frozen D1 and reports added, displaced and altered trades.
