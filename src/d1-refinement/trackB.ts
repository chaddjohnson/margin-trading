// Track B: the four alternative stop-activation designs (and the latched diagnostic) on frozen D1, threshold
// sweeps, trade-level counterfactuals against D1, interest-rate decision-path checks, and bounded local
// refinement of each policy's own threshold with the interacting stop width and hold.
import path from 'node:path';
import {
  type Data,
  formatDollars,
  formatSignedDollars,
  fullSpec,
  option,
  protocol,
  stageDir,
  writeJson,
  writeText
} from './context.ts';
import { type StopPolicy, type Trade, stopPolicies } from './engine.ts';
import { type Detail, type Metrics, evaluateCandidate } from './evaluate.ts';
import {
  type IntParams,
  type ParamKey,
  d1Params,
  describeParams,
  familyOf,
  formatValue,
  policyNames
} from './families.ts';
import { type Box, runLocalStudy } from './local.ts';
import { makeCaches } from './pool.ts';
import { diffTrades, metricsHeader, metricsRow, price, segmentTable } from './report.ts';
import { type Row, evaluateRows, feasible, makeEvaluator, range, segmentOf, writeRows } from './study.ts';

export const policyFamilyKey = (policy: StopPolicy) => (policy === 'net' ? 'd1' : `d1.${policy}`);

// The predeclared defaults and sweep grids of each policy's own threshold (tenths of a point).
export const thresholdGrids: Partial<Record<StopPolicy, { key: ParamKey; values: number[]; default: number }>> = {
  gross: { key: 'activationGain', values: range(5, 200), default: 80 },
  twoStage: { key: 'earlyStop', values: range(10, 200), default: 100 }
};

// Local boxes: the policy's threshold with the interacting stop width and hold; everything else frozen at D1.
export const trackBBoxes: Record<StopPolicy, Box> = {
  net: { trailingStopPercentage: [50, 100], maximumHoldDays: [6, 16] },
  netLatched: { trailingStopPercentage: [50, 100], maximumHoldDays: [6, 16] },
  gross: { activationGain: [5, 200], trailingStopPercentage: [50, 100], maximumHoldDays: [6, 16] },
  breakeven: { trailingStopPercentage: [50, 100], maximumHoldDays: [6, 16] },
  twoStage: { earlyStop: [10, 200], trailingStopPercentage: [50, 100], maximumHoldDays: [6, 16] },
  always: { trailingStopPercentage: [50, 100], maximumHoldDays: [6, 16] }
};

const majorWinners = (ds: Data['ds'], detail: Detail) =>
  detail.trades
    .map((trade, index) => ({ trade, profit: detail.accounting.outcomes[index]!.profit }))
    .filter(({ profit }) => profit >= 10000)
    .map(({ trade, profit }) => ({
      key: `${trade.entryIndex}|${trade.entryBar}`,
      label: `${ds.dates[trade.entryIndex]} ${formatSignedDollars(profit)}`,
      trade,
      profit
    }));

const fateOf = (ds: Data['ds'], d1Detail: Detail, detail: Detail, winner: { trade: Trade; profit: number }) => {
  const match = detail.trades.find(
    (trade) => trade.entryIndex === winner.trade.entryIndex && trade.entryBar === winner.trade.entryBar
  );

  if (!match) {
    return 'lost (no such entry)';
  }

  const profit = detail.accounting.outcomes[detail.trades.indexOf(match)]!.profit;

  if (match.exitIndex === winner.trade.exitIndex && match.exitPrice === winner.trade.exitPrice) {
    return 'kept';
  }

  return `exit ${match.exitIndex < 0 ? 'open' : ds.dates[match.exitIndex]} ${price(match.exitPrice)} (${match.reason}): ${formatSignedDollars(profit)} (${formatSignedDollars(profit - winner.profit)})`;
};

export const stopVariants = async (data: Data, args: string[]) => {
  const { ds } = data;
  const evaluator = makeEvaluator(args);
  const caches = makeCaches(ds);
  const dir = stageDir('trackB');
  const full = fullSpec(ds);
  const started = Date.now();
  const d1Family = familyOf('d1');
  const d1 = evaluateCandidate(ds, caches, d1Family, d1Params(d1Family), full, true);
  const winners = majorWinners(ds, d1.detail!);
  const lines: string[] = [
    '# Track B: stop-activation alternatives on frozen D1 (generated by `npm run d1-refinement -- stop-variants`)',
    '',
    `All runs: D1's eight parameters frozen (${describeParams(d1Family, d1Params(d1Family))}), full run from ${protocol.eligibilityDate}, 11% interest, stop fills. Only the stop's eligibility rule changes; the stop level (post-entry high × (1 − 7.3%), updated once a day, never lowered), the maximum-hold loss exit, the buffered loss exit, the entries and the accounting are D1's.`,
    '',
    '## 1. Each policy at its predeclared setting',
    '',
    metricsHeader('Policy', 'Stop never active (closed trades) | Switch-offs'),
    metricsRow(
      'D1 (net, as shipped)',
      d1.metrics,
      `${d1.metrics.stopNeverActiveTrades} | ${d1.metrics.stopSwitchOffSessions}`
    )
  ];

  evaluator.register(ds);

  const defaults: { policy: StopPolicy; params: IntParams; label: string; metrics: Metrics; detail: Detail }[] = [];

  for (const policy of stopPolicies.filter((policy) => policy !== 'net')) {
    const family = familyOf(policyFamilyKey(policy));
    const threshold = thresholdGrids[policy];
    const params = d1Params(family, threshold ? { [threshold.key]: threshold.default } : {});
    const label = `${policy}${threshold ? ` (${formatValue(threshold.key, threshold.default)})` : ''}`;
    const result = evaluateCandidate(ds, caches, family, params, full, true);

    defaults.push({ policy, params, label, metrics: result.metrics, detail: result.detail! });
    lines.push(
      metricsRow(
        label,
        result.metrics,
        `${result.metrics.stopNeverActiveTrades} | ${result.metrics.stopSwitchOffSessions}`
      )
    );
  }

  lines.push(
    '',
    `Policies: ${stopPolicies.map((policy) => `**${policy}** = ${policyNames[policy]}`).join('; ')}.`,
    '',
    '## 2. Trade-level counterfactuals against D1',
    '',
    `D1's major winners (≥ $10,000): ${winners.map((winner) => winner.label).join(', ')}.`,
    '',
    '| Policy | Preserved | Altered | Gained | Lost | ' + winners.map((winner) => winner.label).join(' | ') + ' |',
    '|---|---:|---:|---:|---:|' + winners.map(() => '---').join('|') + '|'
  );

  for (const { label, detail } of defaults) {
    const diff = diffTrades(ds, d1.detail!.trades, detail.trades);

    lines.push(
      `| ${label} | ${diff.preserved.length} | ${diff.altered.length} | ${diff.gained.length} | ${diff.lost.length} | ${winners.map((winner) => fateOf(ds, d1.detail!, detail, winner)).join(' | ')} |`
    );
  }

  lines.push(
    '',
    'Altered and gained trades in detail (exits that the new rule changed, and the re-entries those exits made possible):',
    ''
  );

  for (const { label, detail } of defaults) {
    const diff = diffTrades(ds, d1.detail!.trades, detail.trades);
    const profitOf = (trade: Trade) => detail.accounting.outcomes[detail.trades.indexOf(trade)]!.profit;
    const d1ProfitOf = (trade: Trade) => d1.detail!.accounting.outcomes[d1.detail!.trades.indexOf(trade)]!.profit;

    lines.push(
      `- **${label}**: ${diff.altered.map(({ reference, candidate }) => `${ds.dates[reference.entryIndex]} exit ${ds.dates[reference.exitIndex]} ${formatSignedDollars(d1ProfitOf(reference))} → ${candidate.exitIndex < 0 ? 'open' : ds.dates[candidate.exitIndex]} ${candidate.reason} ${formatSignedDollars(profitOf(candidate))}`).join('; ') || 'no altered exits'}${diff.gained.length > 0 ? `; gained ${diff.gained.map((trade) => `${diff.dates(trade)} ${formatSignedDollars(profitOf(trade))}`).join(', ')}` : ''}${diff.lost.length > 0 ? `; lost ${diff.lost.map((trade) => `${diff.dates(trade)} ${formatSignedDollars(d1ProfitOf(trade))}`).join(', ')}` : ''}.`
    );
  }

  // Regime table.
  lines.push(
    '',
    '## 3. By regime',
    '',
    segmentTable(
      [{ label: 'D1', metrics: d1.metrics }, ...defaults.map(({ label, metrics }) => ({ label, metrics }))],
      ['full', 'development', 'reused', ...protocol.regimes.map((regime) => regime.key)]
    ),
    ''
  );

  // Threshold sweeps.
  lines.push('## 4. Threshold sweeps (0.1-point grid, everything else frozen)', '');

  const sweepRows: Record<string, Row[]> = {};

  for (const policy of ['gross', 'twoStage'] as StopPolicy[]) {
    const family = familyOf(policyFamilyKey(policy));
    const grid = thresholdGrids[policy]!;
    const paramsList = grid.values.map((value) => d1Params(family, { [grid.key]: value }));
    const rows = await evaluateRows(evaluator, ds.id, family, full, paramsList, `trackB-${policy}-sweep`);

    sweepRows[policy] = rows;
    await writeRows(path.join(dir, `${policy}_threshold_sweep.csv`), family, rows, [grid.key]);

    const best = rows.filter((row) => feasible(row.metrics)).sort((a, b) => b.metrics.net - a.metrics.net)[0]!;
    const signatures = new Set(rows.map((row) => row.metrics.signature)).size;
    const aboveD1 = rows.filter((row) => feasible(row.metrics) && row.metrics.net > d1.metrics.net);

    lines.push(
      `### ${policy}: ${grid.key} ${formatValue(grid.key, grid.values[0])}–${formatValue(grid.key, grid.values.at(-1))}`,
      '',
      `${rows.length} values, ${signatures} distinct trade lists. Best net ${formatDollars(best.metrics.net)} / ${formatDollars(best.metrics.minuteDrawdown)} at ${formatValue(grid.key, best.params[grid.key])}; ${aboveD1.length} values beat D1's net (${aboveD1.length > 0 ? `${formatValue(grid.key, Math.min(...aboveD1.map((row) => row.params[grid.key]!)))}–${formatValue(grid.key, Math.max(...aboveD1.map((row) => row.params[grid.key]!)))}` : 'none'}).`,
      '',
      `| ${grid.key} | Net | Minute DD | Entries | W/L | 2022 net | Stop never active |`,
      '|---|---:|---:|---:|---:|---:|---:|'
    );

    for (const row of rows.filter((row) => row.params[grid.key]! % 10 === 0 || row === best)) {
      lines.push(
        `| ${formatValue(grid.key, row.params[grid.key])}${row === best ? ' (best)' : ''} | ${formatDollars(row.metrics.net)} | ${formatDollars(row.metrics.minuteDrawdown)} | ${row.metrics.entries} | ${row.metrics.wins}/${row.metrics.losses} | ${formatSignedDollars(segmentOf(row.metrics, 'r2022')!.net)} | ${row.metrics.stopNeverActiveTrades} |`
      );
    }

    lines.push('');
  }

  // Interest sensitivity: decision path.
  lines.push(
    '## 5. Interest-rate sensitivity: expense only, or a different decision path?',
    '',
    'Same parameters at 8%, 11% and 14%. "Same path" means an identical trade list (entries, exits, reasons) at all three rates: the policy\'s exits are then interest-independent and only the expense differs. The entries are never interest-dependent; the maximum-hold and buffered-loss exits are (they test net profit).',
    '',
    '| Policy | 8% | 11% | 14% | Same path at all rates | Trades that differ |',
    '|---|---:|---:|---:|---|---|'
  );

  const sensitivity: { label: string; family: string; params: IntParams }[] = [
    { label: 'D1 (net)', family: 'd1', params: d1Params(d1Family) },
    ...defaults.map(({ label, policy, params }) => ({ label, family: policyFamilyKey(policy), params }))
  ];

  for (const entry of sensitivity) {
    const family = familyOf(entry.family);
    const runs = [...protocol.sensitivityRates, protocol.marginInterestRate]
      .sort((a, b) => a - b)
      .map((rate) => ({
        rate,
        ...evaluateCandidate(ds, caches, family, entry.params, fullSpec(ds, 'stop', rate), true)
      }));
    const base = runs.find((run) => run.rate === protocol.marginInterestRate)!;
    const same = runs.every((run) => run.metrics.signature === base.metrics.signature);
    const differing = new Set<string>();

    for (const run of runs) {
      const diff = diffTrades(ds, base.detail!.trades, run.detail!.trades);

      for (const { reference } of diff.altered) {
        differing.add(ds.dates[reference.entryIndex]!);
      }

      for (const trade of [...diff.gained, ...diff.lost]) {
        differing.add(ds.dates[trade.entryIndex]!);
      }
    }

    lines.push(
      `| ${entry.label} | ${runs.map((run) => `${formatDollars(run.metrics.net)} / ${formatDollars(run.metrics.minuteDrawdown)} / ${run.metrics.entries}e`).join(' | ')} | ${same ? 'yes' : 'no'} | ${[...differing].sort().join(', ')} |`
    );
  }

  // Local refinement per policy.
  lines.push(
    '',
    '## 6. Bounded local refinement per policy (threshold, stop width, hold)',
    '',
    "Sobol 2,048 points per policy inside its box with D1's other parameters frozen; the net policy's box (stop width and hold only) is the control that shows what the same budget does to D1 itself. The walk-forward compares the selection rule's picks with frozen D1 on each validation window.",
    ''
  );

  const studies = [];

  for (const policy of stopPolicies) {
    const family = familyOf(policyFamilyKey(policy));
    const threshold = thresholdGrids[policy];
    const anchor = d1Params(family, threshold ? { [threshold.key]: threshold.default } : {});
    const study = await runLocalStudy(data, evaluator, {
      family,
      anchor,
      box: trackBBoxes[policy],
      samples: Number(option(args, 'samples') ?? 2048),
      seedLabel: `trackB-${policy}`,
      key: `trackB_${policy}`,
      label: `Policy ${policy}: ${policyNames[policy]}`,
      dir
    });

    studies.push({ policy, study });
    lines.push(
      ...study.lines.map((line) => (line.startsWith('## ') ? `#${line}` : line.startsWith('### ') ? `#${line}` : line))
    );
  }

  lines.push(`Runtime ${((Date.now() - started) / 1000).toFixed(0)} s on ${evaluator.description}.`);
  await writeText(path.join(dir, 'trackB_summary.md'), lines.join('\n'));
  await writeJson(
    path.join(dir, 'trackB_defaults.json'),
    defaults.map(({ policy, params, label, metrics }) => ({ policy, params, label, metrics }))
  );
  console.info(lines.slice(0, 40).join('\n'));
  console.info(`...\nWritten to ${dir}`);
  await evaluator.close();
};
