export const regimeLabels = protocol.regimes.map((regime) => regime.key);

export const candidateSection = (
  data: Data,
  candidate: Candidate,
  metrics: Metrics,
  detail: Detail,
  withStop = true
) => {
  const { ds } = data;
  const rows = tradeRows(ds, detail.trades, detail.accounting);
  const lines = [
    `### ${candidate.label}: ${candidate.family.key} (${describeParams(candidate.family, candidate.params)})`,
    '',
    metricsHeader('Candidate'),
    metricsRow(candidate.label, metrics),
    '',
    tradeTable(rows, withStop),
    '',
    attributionTable(rows, episodeMoves(ds))
  ];

  return lines.join('\n');
};

export const baseline = async (data: Data) => {
  const { ds, dataHash } = data;
  const caches = makeCaches(ds);
  const spec = fullSpec(ds);
  const dir = stageDir('baseline');
  const results = comparators().map((candidate) => ({
    candidate,
    ...evaluateCandidate(ds, caches, candidate.family, candidate.params, spec, true)
  }));
  const lines: string[] = [
    '# Baseline parity (generated by `npm run d1-refinement -- baseline`)',
    '',
    `Data: \`${protocol.dataFile}\` (sha256 \`${dataHash}\`), ${ds.sessionCount} sessions ${ds.firstDate} → ${ds.lastDate}; engine runs arm from session ${protocol.eligibilityIndex} (${protocol.eligibilityDate}); $${protocol.investment.toLocaleString('en-US')} per entry, ${protocol.marginInterestRate * 100}% interest, stop fills.`,
    '',
    '## 1. Reported figures against the engine',
    '',
    '| Candidate | Parameters | Reported net / minute DD / entries | Engine net / minute DD / entries | Match |',
    '|---|---|---|---|---|'
  ];

  for (const { candidate, metrics } of results) {
    const target = reported[candidate.label]!;
    const match =
      Math.round(metrics.net) === target.net &&
      Math.round(metrics.minuteDrawdown) === target.minuteDrawdown &&
      metrics.entries === target.entries;

    lines.push(
      `| ${candidate.label} (${candidate.note}) | ${describeParams(candidate.family, candidate.params)} | ${formatDollars(target.net)} / ${formatDollars(target.minuteDrawdown)} / ${target.entries} | ${formatDollars(metrics.net)} / ${formatDollars(metrics.minuteDrawdown)} / ${metrics.entries} | ${match ? 'yes' : '**no**'} |`
    );
  }

  lines.push('', '## 2. Full metrics', '', metricsHeader('Candidate'));

  for (const { candidate, metrics } of results) {
    lines.push(metricsRow(candidate.label, metrics));
  }

  lines.push(
    '',
    'Net/DD is net profit over the minute-sampled drawdown. Worst excursion is the most negative minute mark of any single trade against its own entry, net of interest.',
    '',
    '## 3. By window and regime',
    '',
    segmentTable(
      results.map(({ candidate, metrics }) => ({ label: candidate.label, metrics })),
      ['full', 'development', 'reused', ...regimeLabels]
    ),
    '',
    'Windows: development = through 2023-12-29; reused = 2024-01-01 onwards (inspected by earlier programs, not a holdout). Regime rows give the net of the window (mark-to-market change), its minute drawdown and the entries/wins/losses decided in it.',
    ''
  );

  // D1 against Set 2: the six continuation trades.
  const d1 = results[0]!;
  const set2 = results[1]!;
  const diff = diffTrades(ds, set2.detail!.trades, d1.detail!.trades);
  const d1Rows = tradeRows(ds, d1.detail!.trades, d1.detail!.accounting);

  lines.push(
    '## 4. D1 against Set 2',
    '',
    `Preserved ${diff.preserved.length} of Set 2's ${set2.detail!.trades.length} trades unchanged, altered ${diff.altered.length}, lost ${diff.lost.length}, gained ${diff.gained.length}.`,
    '',
    '| Gained (continuation) trade | Entry | Exit | Reason | Net | Window opened by | Episode |',
    '|---|---|---|---|---:|---|---|'
  );

  for (const trade of diff.gained) {
    const row = d1Rows[d1.detail!.trades.indexOf(trade)]!;
    const opener = d1
      .detail!.trades.filter((other) => other.exitIndex >= 0 && other.exitIndex < trade.activationIndex)
      .at(-1);

    lines.push(
      `| ${row.kind} armed ${row.activationDate} at ${price(row.activationPrice)} (${pct(row.depthAtActivation)} below the post-exit high ${price(row.anchorHigh)}) | ${row.entryTime} ${price(row.entryPrice)} | ${row.isOpen ? 'open' : `${row.exitTime} ${price(row.exitPrice)}`} | ${row.reason} | ${formatSignedDollars(row.profit)} | ${opener ? `${ds.dates[opener.exitIndex]} exit at ${price(opener.exitPrice)}` : ''} | ${row.episode} |`
    );
  }

  const gainedNet = diff.gained.reduce(
    (total, trade) => total + d1.detail!.accounting.outcomes[d1.detail!.trades.indexOf(trade)]!.profit,
    0
  );
  const byYear = new Map<string, number>();

  for (const trade of diff.gained) {
    const year = ds.dates[trade.entryIndex]!.slice(0, 4);

    byYear.set(
      year,
      (byYear.get(year) ?? 0) + d1.detail!.accounting.outcomes[d1.detail!.trades.indexOf(trade)]!.profit
    );
  }

  lines.push(
    '',
    `The continuation trades net ${formatSignedDollars(gainedNet)} (${[...byYear.entries()].map(([year, net]) => `${year}: ${formatSignedDollars(net)}`).join(', ')}); D1 − Set 2 = ${formatSignedDollars(d1.metrics.net - set2.metrics.net)} (the difference beyond the trades themselves is the open position's identical mark). The improvement is 2019–2021 re-entries after profitable exits; the two 2022 continuation trades lost; nothing in 2023.`,
    '',
    '## 5. Deep and continuation setups: competition and priority',
    ''
  );

  // Competition: minutes on which both the deep condition and the continuation condition held while flat with no
  // setup, from the session trace (state at the previous close) and the minute bars.
  const d1Family = familyOf('d1');
  const params = toParams(d1Family, d1Params(d1Family));
  const highs = caches.highs.get(params.tickWindowSize);
  let competing = 0;
  let continuationOnly = 0;
  let deepOnly = 0;
  const competingDates: string[] = [];

  for (let s = protocol.eligibilityIndex + 1; s < ds.sessionCount; s++) {
    const previous = d1.detail!.trace[s - 1];

    if (!previous || previous.entryState !== 'FLAT' || !previous.continuationActive) {
      continue;
    }

    const windowOpen = s > previous.continuationStart && s - previous.continuationStart <= params.continuationWindow;

    if (!windowOpen) {
      continue;
    }

    const start = ds.sBarStart[s]!;
    let armed = false;

    for (let k = 0; k < ds.sBarCount[s]! && !armed; k++) {
      const close = ds.bClose[start + k]!;
      const deep = 1 - close / highs[s]! >= params.targetPercentChange;
      const continuation = close <= previous.continuationHigh * (1 - params.pullback);

      if (deep && continuation) {
        competing++;
        competingDates.push(ds.dates[s]!);
        armed = true;
      } else if (deep) {
        deepOnly++;
        armed = true;
      } else if (continuation) {
        continuationOnly++;
        armed = true;
      }
    }
  }

  lines.push(
    'In the source (`allIn-trailingBuy-postExitContinuation.ts`, the arming loop in `runAllIn`), a completed minute while flat with no setup is tested for the deep condition first (`isDip(bar.close)`), then for the continuation condition; the first that holds arms, and any arming ends the continuation window (`continuationActive = false`). The two setups therefore never coexist: there is one setup at a time and the deep path has precedence on the same minute. The continuation window only matters while the strategy is flat with no setup; an exit session never arms (entries are only considered on sessions that start flat).',
    '',
    `On D1's actual run, first arming minutes inside an open continuation window: ${deepOnly} deep-only, ${continuationOnly} continuation-only, ${competing} where both conditions held on the same minute${competing > 0 ? ` (${competingDates.join(', ')}; the deep path armed)` : ''}. Windows opened: ${d1.metrics.counts.continuationWindows}, expired unused: ${d1.metrics.counts.continuationExpiries}, closed by a continuation arming: ${d1.metrics.entriesByKind.continuation}, closed by a deep arming: ${d1.metrics.counts.continuationWindows - d1.metrics.counts.continuationExpiries - d1.metrics.entriesByKind.continuation}.`,
    '',
    "The window closes under three rules: (1) a continuation arming, (2) a deep arming, (3) the session index reaching `continuationStart + continuationWindow` at a session end (the window spans sessions `continuationStart + 1 .. continuationStart + continuationWindow`). The post-exit high is the exit price on the exit session, then the maximum of the later sessions' highs, updated at each session end; a minute's own session high is not used until the next session, so the arming level is known before the session opens.",
    '',
    '## 6. Fill and interest sensitivity',
    '',
    '| Candidate | Stop fills, 11% | Next-open fills, 11% | Stop fills, 8% | Stop fills, 14% |',
    '|---|---:|---:|---:|---:|'
  );

  for (const { candidate } of results) {
    const cells = [
      fullSpec(ds, 'stop', 0.11),
      fullSpec(ds, 'next-open', 0.11),
      fullSpec(ds, 'stop', 0.08),
      fullSpec(ds, 'stop', 0.14)
    ].map((variant) => {
      const { metrics } = evaluateCandidate(ds, caches, candidate.family, candidate.params, variant);

      return `${formatDollars(metrics.net)} / ${formatDollars(metrics.minuteDrawdown)} / ${metrics.entries}e`;
    });

    lines.push(`| ${candidate.label} | ${cells.join(' | ')} |`);
  }

  lines.push('', '## 7. Trade lists and attribution', '');

  for (const { candidate, metrics, detail } of results) {
    lines.push(candidateSection(data, candidate, metrics, detail!), '');
  }

  await writeText(path.join(dir, 'baseline.md'), lines.join('\n'));
  await writeJson(
    path.join(dir, 'baseline.json'),
    results.map(({ candidate, metrics, detail }) => ({
      label: candidate.label,
      family: candidate.family.key,
      params: candidate.params,
      metrics,
      trades: tradeRows(ds, detail!.trades, detail!.accounting)
    }))
  );
  console.info(lines.slice(0, 40).join('\n'));
  console.info(`\nWritten to ${dir}`);
};

// The shipped stop rule, traced.
const stopTraceTable = (
  data: Data,
  rows: {
    index: number;
    postEntryHigh: number;
    stopPrice: number;
    effectiveStop: number;
    interest: number;
    breakeven: number;
    profitAtStop: number;
    active: boolean;
    latched: boolean;
    open: number;
    low: number;
    exitReason: string;
  }[],
  from?: string,
  to?: string
) => {
  const { ds } = data;
  const lines = [
    '| Session | Open | Low | Post-entry high | Stop level | Net breakeven | Interest | Net at stop | Active | Exit |',
    '|---|---:|---:|---:|---:|---:|---:|---:|---|---|'
  ];

  for (const row of rows) {
    const date = ds.dates[row.index]!;

    if ((from && date < from) || (to && date > to)) {
      continue;
    }

    lines.push(
      `| ${date} | ${price(row.open)} | ${price(row.low)} | ${price(row.postEntryHigh)} | ${price(row.stopPrice)} | ${price(row.breakeven)} | ${formatDollars(row.interest)} | ${formatSignedDollars(row.profitAtStop)} | ${row.active ? 'yes' : 'no'} | ${row.exitReason} |`
    );
  }

  return lines.join('\n');
};

export const stopDiagnostic = async (data: Data) => {
  const { ds } = data;
  const caches = makeCaches(ds);
  const dir = stageDir('diagnostics');
  const d1Family = familyOf('d1');
  const d1 = evaluateCandidate(ds, caches, d1Family, d1Params(d1Family), fullSpec(ds), true);
  const rows = tradeRows(ds, d1.detail!.trades, d1.detail!.accounting);
  const lines: string[] = [
    '# Trailing-stop semantics of the shipped D1 (generated by `npm run d1-refinement -- stop-diagnostic`)',
    '',
    '## 1. The rule, from the source',
    '',
    'In `evaluateSessionExit` (and `evaluateBufferedSessionExit`) of `src/app/allIn-trailingBuy-postExitContinuation.ts`, inherited unchanged from file 4:',
    '',
    '```ts',
    'const profitAt = (price: number) => position.shares * price - position.investment - interest;',
    '// Before the open: the stop is active for this session only if filling at the stop price would be',
    "// profitable after interest through the session. Nothing from the session's own prices is used, and",
    '// the decision is made afresh each session, so growing interest can leave the stop inactive.',
    'const isStopActive = profitAt(stopPrice) > 0;',
    '```',
    '',
    "where `interest` is the simple interest accrued through the session's date (`calculateInterest(position, session.time)`: calendar days from the entry session's date, none on the entry date) and `stopPrice` was set after the previous session as `postEntryHigh * (1 - trailingStopPercentage)`, never lowered. Answers to the B0 questions:",
    '',
    '1. **Eligibility tests the net result of a fill at the stop level, not the current price or a historical state**: `shares × stopPrice − investment − interest(session date) > 0`. It is a strict inequality; a stop exactly at net breakeven is inactive.',
    "2. **No latch.** The test is re-evaluated before every session from the current stop level and the current accrued interest. Because the stop level only rises and interest only grows, the stop can switch off again only through interest: when the level is flat (no new high) long enough for the accrued interest to exceed the gross profit at the stop. It switched off on 1 session of D1's 20 trades (section 2).",
    "3. **The trailing high is the highest observed price**: on the entry session, the fill price, the session close and the highs of the minutes from the fill's minute onwards (`Math.max(fill.price, session.close, ...laterBars.map((bar) => bar.high))`); afterwards each session's `session.high` (the highest minute high, including the closing print). It is updated **once, after each session**, together with the stop level; a session's own high never moves that session's stop.",
    "4. **The level is always maintained; only the check is gated.** `stopPrice` is computed from the entry session onwards whatever the profitability; `isStopActive` gates both the gap check at the open (`session.open <= stopPrice`) and the minute walk (`bar.open <= stopPrice`, then `bar.low <= stopPrice`). Activation and a breach cannot happen in the same bar: activation is a pre-open fact of the session (it depends on the previous session's level and on the date's interest), so a breach on an inactive session is simply not acted on, and the first active session starts with the gap check. There is no intraminute activation.",
    "5. **Interactions.** The interest clock advances by calendar days at each session date, so a weekend adds three days of interest to the breakeven before Monday's check. The maximum-hold exit (`daysHeld >= maximumHoldDays && profitAt(open) < 0`) is checked after the gap check and before the minute walk; an active stop above breakeven and a loss at the open imply a gap, which the stop takes first. The buffered loss acts only from the hold day; against an active stop, the earlier execution wins, and the stop takes a shared opening trade. Gaps: a session opening at or below an active stop fills at the open (possibly far below the stop); an inactive stop is not protected against a gap at all. Execution: the stop fills at the stop level when the minute opened above it (idealized), at the minute's open when it opened through it.",
    '6. **The 2023 sensitivity** is reproduced in section 4: with the trough-recovery entry of 2023-01-18 at 340.06, the 7.3% stop level during the March pullback sat between the 8% and the 11% net breakeven, so the trade was stopped at 8% and survived at 11%. It is a consequence of the per-session net test, not of any latch, and the same rule governs D1.',
    '',
    'None of this is a bug: it is the documented policy of file 4 ("the decision is made afresh each session, so growing interest can leave the stop inactive"). The consequences for risk are that an unprofitable position has no stop at all until the hold day, and that the protection can lapse during a long flat stretch.',
    '',
    "## 2. D1's trades under the rule",
    '',
    tradeTable(rows, true),
    '',
    `Stop never active on ${d1.metrics.stopNeverActiveTrades} of ${d1.metrics.closedTrades} closed trades (every maximum-hold exit); sessions on which an earlier-active stop was inactive again: ${d1.metrics.stopSwitchOffSessions}.`,
    ''
  ];

  // The trade with a switch-off, and a representative trade.
  const traces = d1.detail!.stopTrace;

  d1.detail!.trades.forEach((trade, index) => {
    if (trade.stopSwitchOffSessions > 0) {
      const tradeTrace = traces.filter((row) => row.tradeIndex === index);
      const offRows = tradeTrace.filter(
        (row, position) => !row.active && tradeTrace.slice(0, position).some((earlier) => earlier.active)
      );

      lines.push(
        `### Switch-off: trade ${index + 1} (${trade.kind}, ${ds.dates[trade.entryIndex]} → ${ds.dates[trade.exitIndex]})`,
        '',
        `The stop was active from ${ds.dates[trade.stopFirstActiveIndex]} and inactive again on ${offRows.map((row) => ds.dates[row.index]).join(', ')}: the level had not risen while interest grew past the gross profit at the stop. Trace around the switch-off:`,
        '',
        stopTraceTable(
          data,
          tradeTrace,
          ds.dates[Math.max(trade.entryIndex, offRows[0]!.index - 6)],
          ds.dates[Math.min(trade.exitIndex, offRows.at(-1)!.index + 4)]
        ),
        ''
      );
    }
  });

  const representative = d1.detail!.trades.findIndex(
    (trade) => trade.kind === 'continuation' && trade.reason !== 'maximum hold'
  );

  if (representative >= 0) {
    const trade = d1.detail!.trades[representative]!;

    lines.push(
      `### Representative activation: trade ${representative + 1} (${trade.kind}, ${ds.dates[trade.entryIndex]} → ${ds.dates[trade.exitIndex]})`,
      '',
      stopTraceTable(
        data,
        traces.filter((row) => row.tradeIndex === representative),
        undefined,
        ds.dates[trade.stopFirstActiveIndex + 3]
      ),
      '',
      '(first sessions through the activation)',
      ''
    );
  }

  // Latched counterfactual on D1.
  const latchedFamily = familyOf('d1.netLatched');
  const latched = evaluateCandidate(ds, caches, latchedFamily, d1Params(latchedFamily), fullSpec(ds), true);
  const diff = diffTrades(ds, d1.detail!.trades, latched.detail!.trades);

  lines.push(
    '## 3. Counterfactual: the same rule with a latch',
    '',
    `Making the activation irreversible (policy \`netLatched\`) gives ${formatDollars(latched.metrics.net)} / ${formatDollars(latched.metrics.minuteDrawdown)} against D1's ${formatDollars(d1.metrics.net)} / ${formatDollars(d1.metrics.minuteDrawdown)}: ${diff.preserved.length} trades preserved, ${diff.altered.length} altered, ${diff.gained.length} gained, ${diff.lost.length} lost.`,
    ''
  );

  for (const { reference, candidate } of diff.altered) {
    lines.push(
      `- ${diff.dates(reference)} (${reference.reason}, ${price(reference.exitPrice)}) becomes ${diff.dates(candidate)} (${candidate.reason}, ${price(candidate.exitPrice)}).`
    );
  }

  // The 2023 trough-recovery trade at three rates.
  lines.push('', '## 4. The 2023 trough-recovery trade (B1 of the previous program) at 8%, 11% and 14%', '');

  const troughFamily = referenceFamilies.trough!;
  const b1Params = set2Params(troughFamily, {
    troughRecovery: 170,
    troughRetrace: 0,
    episodeReset: 600,
    resetPolicy: 0,
    episodeExpiry: 250
  });
  const highs = new ReferenceHighCache(ds);
  const b1 = referenceSimulate(
    ds,
    highs.get(74),
    troughFamily.flags,
    referenceToParams(troughFamily, b1Params),
    {
      stopFill: 'stop',
      marginInterestRate: 0.11,
      investment: 100000,
      firstIndex: 0,
      armStart: protocol.eligibilityIndex,
      endIndex: ds.sessionCount - 1
    },
    true
  );
  const entry2023 = b1.trades.find(
    (trade) => trade.kind === 'trough' && ds.dates[trade.entryIndex]!.startsWith('2023')
  );

  if (!entry2023) {
    lines.push("The trough-recovery engine produced no 2023 trade at B1's settings; nothing to replay.");
  } else {
    const params: Params = toParams(d1Family, d1Params(d1Family));

    lines.push(
      `Entry from the recovery-eligibility engine at B1's settings (T 17.0%, reset 60%, expiry 250): ${ds.dates[entry2023.entryIndex]} ${ny(entry2023.entryTime)} at ${price(entry2023.entryPrice)}. The same fill is replayed below under D1's exit rules (stop 7.3%, hold 8, buffer 2.9%, net-profit activation) at three rates; only the interest differs.`,
      '',
      '| Rate | Exit | Reason | Net | Stop first active | Active sessions | Switch-off sessions |',
      '|---|---|---|---:|---|---:|---:|'
    );

    const replays = [0.08, 0.11, 0.14].map((rate) => ({
      rate,
      ...replayPosition(
        ds,
        { entryIndex: entry2023.entryIndex, entryBar: entry2023.entryBar, entryPrice: entry2023.entryPrice },
        params,
        { stopFill: 'stop', marginInterestRate: rate, investment: 100000, endIndex: ds.sessionCount - 1 },
        'net'
      )
    }));

    for (const { rate, trade } of replays) {
      const interest =
        100000 *
        rate *
        ((ds.sTime[trade.exitIndex < 0 ? ds.sessionCount - 1 : trade.exitIndex]! - trade.entryTimestamp) /
          (365 * 86400));
      const net =
        trade.shares * (trade.exitIndex < 0 ? ds.sClose[ds.sessionCount - 1]! : trade.exitPrice) - 100000 - interest;

      lines.push(
        `| ${rate * 100}% | ${trade.exitIndex < 0 ? 'open' : `${ds.dates[trade.exitIndex]} ${ny(trade.exitTime)} ${price(trade.exitPrice)}`} | ${trade.reason} | ${formatSignedDollars(net)} | ${trade.stopFirstActiveIndex >= 0 ? ds.dates[trade.stopFirstActiveIndex] : 'never'} | ${trade.stopActiveSessions} | ${trade.stopSwitchOffSessions} |`
      );
    }

    const marchStart = firstIndexOnOrAfter(ds, '2023-02-24');
    const marchEnd = lastIndexOnOrBefore(ds, '2023-03-20');

    for (const { rate, stopTrace } of replays) {
      lines.push(
        '',
        `### ${rate * 100}%: the stop state from 2023-02-24 to 2023-03-20`,
        '',
        stopTraceTable(
          data,
          stopTrace.filter((row) => row.index >= marchStart && row.index <= marchEnd)
        )
      );
    }

    lines.push(
      '',
      "Reading: the stop level is the same at every rate (it depends only on prices); the net breakeven rises with the rate. In the March 2023 pullback the level sat above the 8% breakeven (active, so the pullback's low reached it and sold) but below the 11% and 14% breakevens (inactive, so the position rode the pullback and later recovered). The trade's survival was decided by which side of the level the interest-adjusted breakeven fell on, a per-session fact, not by any latch."
    );
  }

  // The same five policies on that fill, for orientation.
  if (entry2023) {
    const params: Params = { ...toParams(d1Family, d1Params(d1Family)), activationGain: 0.08, earlyStop: 0.1 };

    lines.push(
      '',
      '## 5. The same 2023 fill under each stop policy at 11%',
      '',
      '| Policy | Exit | Reason | Net | Stop first active |',
      '|---|---|---|---:|---|'
    );

    for (const policy of ['net', 'netLatched', 'gross', 'breakeven', 'twoStage', 'always'] as StopPolicy[]) {
      const { trade } = replayPosition(
        ds,
        { entryIndex: entry2023.entryIndex, entryBar: entry2023.entryBar, entryPrice: entry2023.entryPrice },
        params,
        { stopFill: 'stop', marginInterestRate: 0.11, investment: 100000, endIndex: ds.sessionCount - 1 },
        policy
      );
      const exitIndex = trade.exitIndex < 0 ? ds.sessionCount - 1 : trade.exitIndex;
      const interest = 100000 * 0.11 * ((ds.sTime[exitIndex]! - trade.entryTimestamp) / (365 * 86400));
      const net =
        trade.shares * (trade.exitIndex < 0 ? ds.sClose[ds.sessionCount - 1]! : trade.exitPrice) - 100000 - interest;

      lines.push(
        `| ${policy}${policy === 'gross' ? ' (G 8%)' : policy === 'twoStage' ? ' (E 10%)' : ''} | ${trade.exitIndex < 0 ? 'open' : `${ds.dates[trade.exitIndex]} ${price(trade.exitPrice)}`} | ${trade.reason} | ${formatSignedDollars(net)} | ${trade.stopFirstActiveIndex >= 0 ? ds.dates[trade.stopFirstActiveIndex] : 'never'} |`
      );
    }
  }

  await writeText(path.join(dir, 'stop_semantics.md'), lines.join('\n'));
  await writeJson(path.join(dir, 'd1_stop_trace.json'), {
    trades: rows,
    stopTrace: traces.map((row) => ({ ...row, date: ds.dates[row.index] }))
  });
  console.info(lines.slice(0, 12).join('\n'));
  console.info(`...\nWritten to ${dir}`);
};
