const comparisonTables = async (all: Summary[]) => {
  const body: string[] = [];
  const fixed = all.filter((row) => row.mode === 'fixed' && row.key !== 'F-VGT');
  const control = all.find((row) => row.key === 'F-VGT')!;
  const portfolio = all.filter((row) => row.mode === 'portfolio' && row.key.startsWith('C-'));
  const b = all.find((row) => row.key === 'B')!;

  body.push(
    '## Fixed pool frontier (net against minute-sampled drawdown), every predeclared run',
    '',
    table(
      ['Run', 'Net', 'Minute DD', 'Net ÷ minute DD', 'Beats VGT D1 on net', 'Beats VGT D1 on net ÷ DD'],
      [control, ...fixed].map((row) => [
        row.key,
        money(row.net),
        money(row.minuteDrawdown),
        (row.net / row.minuteDrawdown).toFixed(2),
        row.key === 'F-VGT' ? '—' : row.net > control.net ? 'yes' : 'no',
        row.key === 'F-VGT' ? '—' : row.net / row.minuteDrawdown > control.net / control.minuteDrawdown ? 'yes' : 'no'
      ])
    ),
    '',
    `Of ${fixed.length} fixed allocator runs, ${fixed.filter((row) => row.net > control.net).length} beat VGT D1's net and ${fixed.filter((row) => row.net / row.minuteDrawdown > control.net / control.minuteDrawdown).length} beat its net ÷ minute DD (${(control.net / control.minuteDrawdown).toFixed(2)}).`,
    '',
    '## Portfolio frontier, every predeclared run',
    '',
    table(
      [
        'Run',
        'End equity',
        'vs B',
        'CAGR',
        'Daily DD',
        'Min equity ÷ LMV',
        'Min equity ÷ required (U60)',
        'Borrowing $-days',
        'Lots'
      ],
      [b, ...portfolio].map((row) => [
        row.key,
        money(row.endEquity),
        row.key === 'B' ? '—' : signed(row.endEquity - b.endEquity),
        pct(row.cagr, 2),
        pct(row.dailyDrawdownPercent),
        pct(row.minEquityToLmvDaily),
        ratio(row.minRatio.U60),
        `${(row.borrowingDollarDays / 1e6).toFixed(1)}M`,
        row.fundedLots
      ])
    ),
    '',
    `Of ${portfolio.length} portfolio allocator runs, ${portfolio.filter((row) => row.endEquity > b.endEquity).length} end above B and ${portfolio.filter((row) => row.dailyDrawdownPercent <= b.dailyDrawdownPercent).length} have a daily drawdown no larger than B's (${pct(b.dailyDrawdownPercent, 2)}).`
  );

  await write('strategy_comparison', 'Every predeclared policy × configuration (no winner selected)', body);
};

