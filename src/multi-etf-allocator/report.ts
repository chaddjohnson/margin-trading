type Row = Record<string, string>;

const readCsv = async (file: string): Promise<Row[]> =>
  (await fs.pathExists(file)) ? parse(await fs.readFile(file), { columns: true }) : [];

const n = (value: unknown) => (value === undefined || value === null || value === '' ? NaN : Number(value));

const table = (headers: string[], rows: (string | number)[][]) =>
  [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map((header, index) => (index === 0 ? '---' : header.startsWith('#') ? '---' : '---:')).join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`)
  ].join('\n');

const money = (value: unknown) => formatDollars(n(value));
const signed = (value: unknown) => formatSigned(n(value));
const ratio = (value: unknown, digits = 3) =>
  Number.isFinite(n(value)) ? n(value).toFixed(digits) : n(value) > 0 ? '∞' : 'n/a';
const share = (value: unknown, digits = 1) =>
  Number.isFinite(n(value)) ? pct(n(value), digits) : n(value) > 0 ? '> 100%' : 'n/a';
const shock = (value: unknown) =>
  n(value) === Infinity || String(value) === 'Infinity' ? 'none ≤ 100%' : pct(n(value), 1);

const write = (name: string, title: string, body: string[]) =>
  writeText(stageDir('tables', `${name}.md`), [`# ${title}`, '', ...body].join('\n'));

