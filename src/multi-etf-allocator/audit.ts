// The data audit (PROTOCOL.md §2): for each of the five minute files its hash, rows, sessions, coverage, sparse
// minutes, closing prints, early closes, extended-hours rows, overnight gaps, the calendar alignment of the five
// files, minute-level synchrony between them, the VGT/VOOG distribution ledger against the adjusted daily files
// (the earlier program's re-derivation), and the existence and coverage — never the content — of later daily files.
import fs from 'fs-extra';
import { audit as distributionAudit, loadProgramData } from '../shared-margin-portfolio/data.ts';
import {
  type Security,
  expectedHashes,
  files,
  formatTime,
  log,
  protocol,
  securities,
  stageDir,
  writeJson,
  writeText
} from './context.ts';
import { loadFileSessions } from './data.ts';

const countLines = async (file: string) => {
  const text = await fs.readFile(file, 'utf8');
  let lines = 0;

  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) === 10) {
      lines++;
    }
  }

  return { lines, header: text.slice(0, text.indexOf('\n')) };
};

const median = (values: number[]) => {
  const sorted = [...values].sort((a, b) => a - b);

  return sorted[Math.floor(sorted.length / 2)] ?? NaN;
};

const auditTables = (report: Record<string, any>) => {
  const pctOf = (value: number) => `${(value * 100).toFixed(1)}%`;
  const lines = [
    '# Data audit tables (generated by `npm run multi-etf-allocator -- audit`)',
    '',
    '| File | sha256 (first 16) | Protocol hash | Data rows | Regular bars | Closing prints | Dropped rows (outside the regular session) | Sessions | First | Last | Sessions ≤ 2025-10-13 | 2017-06-15 index | Early closes | Median bars/session | Sessions < 100 bars | Scheduled minutes traded | Largest overnight gap | Split-sized gaps |',
    '|---|---|---|---:|---:|---:|---:|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---:|'
  ];

  for (const row of report.files) {
    lines.push(
      `| ${row.security} | \`${row.sha256.slice(0, 16)}\` | ${row.matchesProtocol ? 'matches' : '**differs**'} | ${row.dataRows.toLocaleString('en-US')} | ${row.regularBars.toLocaleString('en-US')} | ${row.closingPrints} | ${row.droppedRows.toLocaleString('en-US')} | ${row.sessions} | ${row.first} | ${row.last} | ${row.sessionsThroughCommonEnd} | ${row.eligibilityIndex} | ${row.earlyCloseSessions} | ${row.medianBarsPerSession} | ${row.sessionsBelow100Bars} | ${pctOf(row.shareOfScheduledMinutesTraded)} | ${pctOf(row.largestOvernightGap)} | ${row.splitSizedGaps} |`
    );
  }

  lines.push(
    '',
    '## Calendar alignment through 2025-10-13',
    '',
    '| File | Sessions | Date mismatches vs VGT | Schedule mismatches | Sessions after 2025-10-13 |',
    '|---|---:|---:|---:|---|'
  );

  for (const row of report.calendar) {
    lines.push(
      `| ${row.security} | ${row.sessionsThroughCommonEnd} | ${row.dateMismatches} | ${row.scheduleMismatches} | ${row.sessionsAfterCommonEnd.join(', ') || 'none'} |`
    );
  }

  lines.push('', "## Minute synchrony (share of a file's regular minutes in which the other file also traded)", '');

  const names = ['VOOG', 'VGT', 'XBI', 'XRT', 'KRE'];

  lines.push(
    `| Minutes of ↓ / also traded by → | ${names.join(' | ')} |`,
    `|---|${names.map(() => '---:').join('|')}|`
  );

  for (const a of names) {
    lines.push(
      `| ${a} | ${names
        .map((b) =>
          a === b
            ? '—'
            : pctOf(report.synchrony.find((row: any) => row.minutesOf === a && row.alsoTradedBy === b).share)
        )
        .join(' | ')} |`
    );
  }

  lines.push(
    '',
    '## Overnight gaps of at least 8%',
    '',
    '| File | Date | Previous close | Open | Gap |',
    '|---|---|---:|---:|---:|'
  );

  for (const row of report.files) {
    for (const gap of row.overnightGapsAtLeast8Percent) {
      lines.push(`| ${row.security} | ${gap.date} | ${gap.previousClose} | ${gap.open} | ${pctOf(gap.gap)} |`);
    }
  }

  lines.push('', '## Distributions', '');

  for (const row of report.distributions.derivation) {
    lines.push(
      `- ${row.etf}: ${row.steps} raw/adjusted steps, ${row.matchedExDates} matched ledger ex-dates, ${row.amountMismatchesOver1Percent} amounts off by more than 1%, ledger dates without a step: ${row.ledgerWithoutStep.join(', ') || 'none'}; steps without a ledger row: ${row.stepWithoutLedger.join(', ') || 'none'}`
    );
  }

  lines.push(
    `- XBI, XRT, KRE: ${report.distributions.sectorEtfs}`,
    '',
    '## Later daily files (coverage only, not evaluated)',
    ''
  );

  for (const row of report.laterDailyFiles) {
    lines.push(
      row.exists
        ? `- \`${row.file}\`: ${row.rows} rows, ${row.first} → ${row.last}; ${row.rowsAfterLastMinuteSession} rows after 2025-10-16; ${row.granularity}`
        : `- \`${row.file}\`: absent`
    );
  }

  return lines.join('\n');
};

export const auditData = async () => {
  const perFile: Record<string, unknown>[] = [];
  const sessionsBy = new Map<Security, Awaited<ReturnType<typeof loadFileSessions>>['sessions']>();

  for (const security of securities) {
    const file = files.minute(security);
    const { sessions, hash } = await loadFileSessions(security, false);
    const { lines, header } = await countLines(file);
    const bars = sessions.reduce((total, session) => total + session.bars.length, 0);
    const prints = sessions.filter((session) => session.closingPrint !== undefined).length;
    const perSession = sessions.map((session) => session.bars.length);
    const scheduled = sessions.map((session) => (session.closeTime - session.openTime) / 60);
    const gaps: { date: string; previousClose: number; open: number; gap: number }[] = [];

    sessions.forEach((session, s) => {
      const previous = sessions[s - 1];

      if (previous) {
        const gap = session.open / previous.close - 1;

        if (Math.abs(gap) >= 0.08) {
          gaps.push({ date: session.date, previousClose: previous.close, open: session.open, gap });
        }
      }
    });

    const common = sessions.filter((session) => session.date <= protocol.commonEnd);

    perFile.push({
      security,
      file,
      sha256: hash,
      matchesProtocol: hash === expectedHashes[security],
      header,
      dataRows: lines - 1,
      regularBars: bars,
      closingPrints: prints,
      droppedRows: lines - 1 - bars - prints, // extended-hours rows and anything outside the regular session
      sessions: sessions.length,
      first: sessions[0]?.date,
      last: sessions.at(-1)?.date,
      sessionsThroughCommonEnd: common.length,
      eligibilityIndex: sessions.findIndex((session) => session.date === protocol.eligibilityDate),
      earlyCloseSessions: sessions.filter((session) => session.isEarlyClose).length,
      sessionsWithoutClosingPrint: sessions.length - prints,
      medianBarsPerSession: median(perSession),
      minimumBarsPerSession: Math.min(...perSession),
      sessionsBelow100Bars: perSession.filter((count) => count < 100).length,
      shareOfScheduledMinutesTraded: bars / scheduled.reduce((total, minutes) => total + minutes, 0),
      overnightGapsAtLeast8Percent: gaps,
      largestOvernightGap: gaps.reduce((worst, gap) => (Math.abs(gap.gap) > Math.abs(worst) ? gap.gap : worst), 0),
      splitSizedGaps: gaps.filter((gap) => gap.gap <= -0.4 || gap.gap >= 0.8).length
    });
    sessionsBy.set(security, sessions);
  }

  // The common calendar.
  const reference = sessionsBy.get('VGT')!.filter((session) => session.date <= protocol.commonEnd);
  const calendar = securities.map((security) => {
    const sessions = sessionsBy.get(security)!.filter((session) => session.date <= protocol.commonEnd);
    const mismatches = sessions.filter((session, s) => session.date !== reference[s]?.date).length;
    const after = sessionsBy
      .get(security)!
      .filter((session) => session.date > protocol.commonEnd)
      .map((session) => session.date);

    return {
      security,
      sessionsThroughCommonEnd: sessions.length,
      dateMismatches: mismatches + Math.abs(sessions.length - reference.length),
      scheduleMismatches: sessions.filter(
        (session, s) => session.closeTime !== reference[s]?.closeTime || session.openTime !== reference[s]?.openTime
      ).length,
      sessionsAfterCommonEnd: after
    };
  });

  // Minute synchrony: the share of one file's regular minutes in which another file also has a bar.
  const minuteSets = new Map<Security, Set<number>>();

  for (const security of securities) {
    const set = new Set<number>();

    for (const session of sessionsBy.get(security)!) {
      if (session.date <= protocol.commonEnd) {
        for (const bar of session.bars) {
          set.add(bar.time);
        }
      }
    }

    minuteSets.set(security, set);
  }

  const synchrony = securities.flatMap((a) =>
    securities
      .filter((b) => b !== a)
      .map((b) => {
        const setA = minuteSets.get(a)!;
        const setB = minuteSets.get(b)!;
        let both = 0;

        for (const time of setA) {
          if (setB.has(time)) {
            both++;
          }
        }

        return { minutesOf: a, alsoTradedBy: b, share: both / setA.size };
      })
  );

  // VGT/VOOG distributions re-derived from the adjusted daily files (the earlier program's audit, unchanged).
  const programData = await loadProgramData();
  const distributions = await distributionAudit(programData);

  // Later daily files: existence and coverage only (PROTOCOL.md §1). Never parsed beyond the first column.
  const laterFiles = [];

  for (const file of files.laterDaily) {
    if (!(await fs.pathExists(file))) {
      laterFiles.push({ file, exists: false });
      continue;
    }

    const lines = (await fs.readFile(file, 'utf8')).trim().split('\n');
    const datesOnly = lines.map((line) => line.split('|')[0]!).filter((date) => /^\d{4}-\d{2}-\d{2}$/.test(date));

    laterFiles.push({
      file,
      exists: true,
      rows: lines.length,
      first: datesOnly[0],
      last: datesOnly.at(-1),
      rowsAfterLastMinuteSession: datesOnly.filter((date) => date > protocol.sectorReferenceEnd).length,
      granularity: 'daily (one row per date); D1 needs minute bars, so no strategy can be evaluated on it',
      evaluated: false
    });
  }

  const report = {
    auditedAt: formatTime(Date.now() / 1000),
    protocolVersion: protocol.version,
    commonEnd: protocol.commonEnd,
    eligibilityDate: protocol.eligibilityDate,
    files: perFile,
    calendar,
    synchrony,
    distributions: {
      vgtVoogLedger: files.distributions,
      count: distributions.distributions,
      derivation: distributions.derivation.map((row) => ({
        etf: row.etf,
        steps: row.steps,
        matchedExDates: row.matchedExDates,
        amountMismatchesOver1Percent: row.amountMismatchesOver1Percent.length,
        ledgerWithoutStep: row.ledgerWithoutStep,
        stepWithoutLedger: row.stepWithoutLedger
      })),
      sectorEtfs:
        'No documented XBI/XRT/KRE distribution history in the repository (third-party aggregators are partial and not primary documents): funded sector lots are price-only.'
    },
    freshMinuteData: {
      latestMinuteSession: perFile.reduce(
        (latest, row) => ((row.last as string) > latest ? (row.last as string) : latest),
        ''
      ),
      present: false,
      note: 'No minute bar after 2025-10-16 exists in the repository; a genuine forward test needs new minute files (FORWARD_TEST_FREEZE.json).'
    },
    laterDailyFiles: laterFiles
  };

  await writeJson(stageDir('audit', 'data_audit.json'), report);
  await writeText(stageDir('audit', 'DATA_AUDIT_TABLES.md'), auditTables(report));
  log(
    `Audit written: ${perFile.length} files, calendar mismatches ${calendar.reduce((total, row) => total + row.dateMismatches, 0)}`
  );

  return report;
};
