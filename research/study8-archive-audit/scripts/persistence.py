"""Q5 and the test half of Q6 — limited to ALREADY-SEALED test results (no new door, no replay).

Population: the 36 shortlist members of each fold (180 in all), which are the only configurations with sealed test
records (results/test/<FOLD>/test.json). Their training-window figures come from the same fold's qualification
record (confirmation 3 × 128 on the fold's TRAINING door). Never-tested archive configurations are not touched.
"""

import collections
import math

import common as c

BANDS = ['<90%', '90–93%', '93–95%', '95–98%', '98–100%']


def members(fold):
    t = c.test_record(fold)
    y_test = t['window']['yTest']
    holders = {(h['track'], h['id']): h for h in t['holders']}
    rows = []
    for m in t['members']:
        q = c.qualification(m['track'], fold)
        cand = next(x for x in q['candidates'] if x['id'] == m['id'])
        nb = cand['evidence']['decisive']['nb']
        # a holder member's evidence is kept once, in its holder entry (the member carries a `see` pointer)
        ev = holders[(m['track'], m['id'])]['evidence'] if 'see' in m['evidence'] else m['evidence']
        dec = ev['decisive']['nb']
        rows.append({
            'fold': fold, 'track': m['track'], 'id': m['id'], 'holder': bool(m['holder']), 'qualified': m['qualified'],
            'trainShare': nb['share'], 'trainN': nb['n'], 'trainP90': nb['p90Dd'], 'trainRobust': nb['robustPerYear'],
            'trainDd': cand['evidence']['centre']['dd'], 'status': m['gates']['status'], 'failed': m['gates']['failed'],
            'testNet': m['centre']['test'], 'testNetPerYear': m['centre']['test'] / y_test, 'runDd': m['centre']['dd'],
            'testShare': dec['share'], 'testP90': dec['p90Dd'], 'testMedian': m['testMedian'], 'yTest': y_test
        })
    return rows


def within(rows, key_x, key_y):
    by = collections.defaultdict(list)
    for r in rows:
        by[r['track']].append(r)
    xs, ys = [], []
    for track, rs in by.items():
        mx = sum(r[key_x] for r in rs) / len(rs)
        my = sum(r[key_y] for r in rs) / len(rs)
        xs.extend(r[key_x] - mx for r in rs)
        ys.extend(r[key_y] - my for r in rs)
    return c.spearman(xs, ys), len(xs)


def between(rows, key_x, key_y):
    by = collections.defaultdict(list)
    for r in rows:
        by[r['track']].append(r)
    xs = [sum(r[key_x] for r in rs) / len(rs) for rs in by.values()]
    ys = [sum(r[key_y] for r in rs) / len(rs) for rs in by.values()]
    return c.spearman(xs, ys), len(xs)


def fmt_rho(rho, n):
    if rho is None:
        return f'n/a (n={n})'
    lo, hi = c.fisher_ci(rho, n)
    return f'{rho:+.2f} [{lo:+.2f}, {hi:+.2f}] (n={n})' if lo is not None else f'{rho:+.2f} (n={n})'


def band_table(rows):
    out = []
    for band in BANDS:
        rs = [r for r in rows if c.band_of(r['trainShare']) == band]
        if not rs:
            out.append([band, 0, '—', '—', '—', '—', '—', '—', '—'])
            continue
        fails = sum(1 for r in rs if r['status'] == 'fail')
        lo, hi = c.clopper_pearson(fails, len(rs))
        out.append([band, len(rs), f'{fails} ({fails / len(rs):.0%}; 90% CI {lo:.0%}–{hi:.0%})',
                    sum(1 for r in rs if r['holder']), c.money(c.median([r['testNetPerYear'] for r in rs])),
                    c.money(c.median([r['runDd'] for r in rs])), sum(1 for r in rs if r['runDd'] >= c.CEILING),
                    c.pct(c.median([r['testShare'] for r in rs])), c.money(c.median([r['testP90'] for r in rs]))])
    return out


def main():
    all_rows = {fold: members(fold) for fold in c.FOLDS}
    lines = ['# Validation persistence audit — sealed test results only',
             'Generated by `python3 research/study8-archive-audit/scripts/persistence.py`. **Population: the 36 '
             'shortlist members of each fold (180), the only configurations with sealed test records.** Training figures '
             'are the fold\'s own confirmation evidence (3 × 128 neighbours on the fold\'s training door, '
             '`results/qualify/<T>/<F>/qualification.json`); test figures are the sealed test record '
             '(`results/test/<F>/test.json`: T status, test-window centre net, whole-run minute DD, test-family share '
             'and p90 on the run to the test end). No door was opened and no configuration was replayed. **All of '
             '2016-01-04 → 2026-10-29, including every test window, had been inspected by the research programme before '
             'Study 8** (PROTOCOL.md §3.4); these are retrospective procedural statistics, not independent validation.',
             '**Selection and survivorship.** Every member is a survivor of ~15,000 rung-1 evaluations in its track-fold '
             'and was shortlisted *because* its training neighbourhood was broad: training shares are compressed into '
             '0.84–1.00, which attenuates any correlation (range restriction). Members of one track share books and '
             'often near-identical vectors, so the 36 per fold are not independent; folds overlap in time (F20\'s 2022 '
             'is F21\'s first test year) and every fold starts in 2016.']

    lines.append('## Failure rate and outcomes by training-share band (per fold)')
    for fold in c.FOLDS:
        rows = all_rows[fold]
        lines.append(f"### {fold} (test {rows[0]['yTest']:.2f} years)")
        lines.append(c.md_table(['training share band', 'members', 'T-failed (rate; exact 90% CI)', 'of which holders',
                                 'median test-window net / yr', 'median run DD', 'run DD ≥ $35k', 'median test share',
                                 'median test p90'], band_table(rows)))

    pooled = {'F19–F21 (test regime absent from training)': [r for f in ['F19', 'F20', 'F21'] for r in all_rows[f]],
              'F23 + F24 (training includes 2020 and 2022)': [r for f in ['F23', 'F24'] for r in all_rows[f]]}
    lines.append('## Pooled bands')
    for name, rows in pooled.items():
        lines.append(f'### {name}')
        lines.append(c.md_table(['training share band', 'members', 'T-failed (rate; exact 90% CI)', 'of which holders',
                                 'median test-window net / yr', 'median run DD', 'run DD ≥ $35k', 'median test share',
                                 'median test p90'], band_table(rows)))

    lines.append('## Rank correlations (Spearman; approximate 90% interval, Fisher z with variance 1.06/(n − 3))')
    lines.append('Overall = all 36 members of the fold; within-track = after removing each track\'s mean (pooled over '
                 'tracks); between-track = over the six track means (n = 6, very imprecise). A positive sign means a '
                 'higher training value went with a higher test value; for DD a positive sign means a higher training '
                 'share went with a *higher* run DD.')
    corr_rows = []
    pairs = [('trainShare', 'testShare', 'training share → test share'),
             ('trainShare', 'testNetPerYear', 'training share → test-window net/yr'),
             ('trainShare', 'runDd', 'training share → whole-run DD'),
             ('trainP90', 'testP90', 'training p90 DD → test p90 DD'),
             ('trainRobust', 'testNetPerYear', 'training robust/yr → test-window net/yr')]
    for fold in c.FOLDS + ['F23+F24']:
        rows = all_rows[fold] if fold in all_rows else all_rows['F23'] + all_rows['F24']
        for kx, ky, label in pairs:
            rho = c.spearman([r[kx] for r in rows], [r[ky] for r in rows])
            w, nw = within(rows, kx, ky)
            b, nb = between(rows, kx, ky)
            corr_rows.append([fold, label, fmt_rho(rho, len(rows)), fmt_rho(w, nw), fmt_rho(b, nb)])
    lines.append(c.md_table(['fold', 'pair', 'overall', 'within-track', 'between-track'], corr_rows))

    lines.append('## F24 report-only threshold view: sealed outcomes of the F24 members by minimum training share')
    lines.append('Descriptive only. These are the 36 F24 shortlist members; it is NOT a re-selection, and the members '
                 'were not chosen by these thresholds.')
    sens = []
    f24 = all_rows['F24']
    for thr in [0.0, 0.90, 0.93, 0.95, 0.98]:
        rs = [r for r in f24 if r['trainShare'] >= thr]
        fails = sum(1 for r in rs if r['status'] == 'fail')
        sens.append([f'≥ {thr:.2f}' if thr else 'all', len(rs), sum(1 for r in rs if r['holder']), fails,
                     f'{fails / len(rs):.0%}' if rs else '—', c.money(c.median([r['testNet'] for r in rs])),
                     c.money(min(r['testNet'] for r in rs)) if rs else '—', c.money(c.median([r['runDd'] for r in rs])),
                     c.money(max(r['runDd'] for r in rs)) if rs else '—',
                     c.pct(min(r['testShare'] for r in rs)) if rs else '—'])
    lines.append(c.md_table(['min training share', 'members', 'holders', 'T-failed', 'fail rate', 'median test-window net',
                             'worst test-window net', 'median run DD', 'worst run DD', 'lowest test share'], sens))

    lines.append('## F24 members (sealed)')
    tab = []
    for r in sorted(f24, key=lambda r: (r['track'], -r['trainShare'])):
        tab.append([r['track'], f"`{r['id'][:40]}{'…' if len(r['id']) > 40 else ''}`", 'holder' if r['holder'] else '',
                    'yes' if r['qualified'] else 'no', c.pct(r['trainShare']), c.money(r['trainP90']),
                    c.money(r['trainRobust']), r['status'] + (f" ({','.join(r['failed'])})" if r['failed'] else ''),
                    c.money(r['testNet']), c.money(r['runDd']), c.pct(r['testShare']), c.money(r['testP90'])])
    lines.append(c.md_table(['track', 'id', 'role', 'qualified', 'train share', 'train p90', 'train robust/yr',
                             'T status', 'test-window net', 'run DD', 'test share', 'test p90'], tab))
    lines.append('## Inputs')
    lines.append(c.inputs_block())
    c.write('persistence.md', '\n\n'.join(lines))
    c.write_json('persistence.json', {fold: rows for fold, rows in all_rows.items()})
    print('persistence: done')


if __name__ == '__main__':
    main()
