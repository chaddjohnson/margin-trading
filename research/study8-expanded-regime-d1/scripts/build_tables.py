"""Study 8 report tables, generated only from sealed records (never typed by hand).

Usage (repository root): python3 research/study8-expanded-regime-d1/scripts/build_tables.py <part> [<part> …]
Parts: search, qualify, selection, test, folds, study7, tracks. Each writes Markdown tables to
research/study8-expanded-regime-d1/results/tables/<part>-*.md and verifies the body hash of every record it reads.
`test`, `folds` and `study7` read the one-time test records and refuse to run before the F24 test is sealed (they
are report tables; nothing they compute feeds any selection).
"""
import hashlib
import json
import math
import os
import sys

ROOT = 'research/study8-expanded-regime-d1'
RES = f'{ROOT}/results'
OUT = f'{RES}/tables'
TRACKS = ['G', 'V', 'VG', 'VXR', 'VXRG', 'VXRKG']
FOLDS = ['F19', 'F20', 'F21', 'F23', 'F24']
ORDER = ['VGT', 'XBI', 'XRT', 'KRE', 'GDX']
KEYS = ['targetPercentChange', 'trailingBuyPercentage', 'trailingStopPercentage', 'maximumHoldDays', 'tickWindowSize',
        'intradayLossBuffer', 'pullback', 'continuationWindow']


def sealed(path):
    with open(path) as f:
        record = json.load(f)
    body = {k: v for k, v in record.items() if k != 'bodyHash'}
    digest = hashlib.sha256(json.dumps(body, separators=(',', ':'), ensure_ascii=False).encode()).hexdigest()
    if digest != record.get('bodyHash'):
        raise SystemExit(f'{path}: body hash does not verify')
    return record


def num(v):
    if v is None:
        return math.nan
    if isinstance(v, str):
        try:
            return float(v)
        except ValueError:
            return math.nan
    return float(v)


def usd(v, digits=0):
    v = num(v)
    if math.isnan(v):
        return '—'
    s = f'{abs(v):,.{digits}f}'
    return f'−${s}' if v < 0 else f'${s}'


def pct(v, digits=1):
    v = num(v)
    return '—' if math.isnan(v) else f'{100 * v:.{digits}f}%'


def fmt(v, digits=2):
    v = num(v)
    return '—' if math.isnan(v) else f'{v:.{digits}f}'


def table(headers, rows):
    out = ['| ' + ' | '.join(headers) + ' |', '|' + '|'.join('---:' if i else '---' for i in range(len(headers))) + '|']
    for row in rows:
        out.append('| ' + ' | '.join(str(c) for c in row) + ' |')
    return '\n'.join(out) + '\n'


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(f'{OUT}/{name}.md', 'w') as f:
        f.write(f'<!-- generated by scripts/build_tables.py from sealed records; do not edit -->\n{text}')


def short(grid):
    p = lambda v: f'{v / 10:.1f}'
    return (f"X {p(grid['targetPercentChange'])} Y {p(grid['trailingBuyPercentage'])} stop {p(grid['trailingStopPercentage'])} "
            f"hold {grid['maximumHoldDays']} L {grid['tickWindowSize']} buf {p(grid['intradayLossBuffer'])} "
            f"P {p(grid['pullback'])} W {grid['continuationWindow']}")


def books_text(books):
    if isinstance(books, str):
        parsed = {}
        for part in books.split('|'):
            sym, vals = part.split(':')
            parsed[sym] = dict(zip(KEYS, map(int, vals.split('/'))))
        books = parsed
    return '<br>'.join(f'{s}: {short(books[s])}' for s in ORDER if s in books)


def spearman(a, b):
    def ranks(xs):
        order = sorted(range(len(xs)), key=lambda i: xs[i])
        r = [0.0] * len(xs)
        i = 0
        while i < len(order):
            j = i
            while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
                j += 1
            for k in range(i, j + 1):
                r[order[k]] = (i + j) / 2
            i = j + 1
        return r
    if len(a) < 3:
        return math.nan
    ra, rb = ranks(a), ranks(b)
    ma, mb = sum(ra) / len(ra), sum(rb) / len(rb)
    cov = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    va = math.sqrt(sum((x - ma) ** 2 for x in ra))
    vb = math.sqrt(sum((y - mb) ** 2 for y in rb))
    return cov / (va * vb) if va and vb else math.nan


def records(kind):
    out = {}
    for track in TRACKS:
        for fold in FOLDS:
            path = f'{RES}/{kind}/{track}/{fold}/{"search" if kind == "search" else "qualification"}.json'
            if os.path.exists(path):
                out[(track, fold)] = sealed(path)
    return out


# ---------------------------------------------------------------- search (training only)

def feasible_under(f, y, lot_years, scale, cap):
    ce, nb = f['centre'], f['nb']
    pooled = len(ce['bookLots']) > 1
    return (num(ce['dd']) < 35000 and num(nb['share']) >= 0.9 and num(nb['p90Dd']) < 35000
            and ce['lots'] >= math.ceil(1.5 * y * scale) and ce['episodes'] >= math.ceil(0.5 * y * scale)
            and ce['lotYears'] >= lot_years and (not pooled or all(v >= math.ceil(0.4 * y * scale) for v in ce['bookLots'].values()))
            and num(nb['medianPerYear']) >= 10000 and num(nb['p10Net']) > 0 and num(ce['perCapitalYear']) >= 11000
            and num(ce['net']) > 0 and num(ce['top1Share']) <= 0.25 and num(ce['exBestPerYear']) >= 5000
            and (cap is None or num(ce['bestYearShare']) <= cap))


def search():
    recs = records('search')
    rows, islands, short_rows, ctrl_rows, sens_rows = [], [], [], [], []
    tot_points = tot_seconds = tot_archive = 0
    for (track, fold), r in sorted(recs.items(), key=lambda kv: (TRACKS.index(kv[0][0]), FOLDS.index(kv[0][1]))):
        c, t, b = r['counts'], r['triggers'], r['budget']
        tot_points += r['stats']['points']
        tot_seconds += r['seconds']
        tot_archive += c['archive']
        rows.append([track, fold, f"{r['y']:.2f}", f"{r['floors']['lots']}/{r['floors']['episodes']}/{r['floors']['lotYears']}/{r['floors']['bookLots']}",
                     f"{b['newPerIsland']}/{b['population']}", c['screen'], c['screenPlausible'], c['promoted'], c['archive'], c['r1Feasible'],
                     f"{c['r2Feasible']}/{c['r2']}", f"{c['r3Feasible']}/{c['r3']}", c['islandsRun'],
                     'fired' if any(x.get('fired') for x in t['T1']['log']) else 'no', 'fired' if t['T2'].get('fired') else 'no',
                     'fired' if t['T3'].get('fired') else 'no', 'yes' if r['noEligibleRegion'] else 'no',
                     f"{r['stats']['points']:,}", f"{r['seconds'] / 3600:.2f}"])
        for isl in r['islands']:
            mv = isl['unionMinViolation']
            islands.append([track, fold, isl['island'], isl['generations'], isl['newConfigs'], isl['duplicates'], isl['stop'], isl['feasible'],
                            f"{isl['unionHv']:.3e}", f"{mv:.3f}" if isinstance(mv, (int, float)) else mv])
        for s in r['shortlist']:
            r3, sel = s['r3'], s['selection']['pooled']
            short_rows.append([track, fold, s['rank'], s['pick'], s['id'], books_text(s['books']),
                               usd(r3['centre']['perYear']), usd(r3['centre']['dd']), r3['centre']['lots'], r3['centre']['episodes'],
                               f"{pct(r3['nb']['share'])} ({r3['nb']['n']})", usd(r3['nb']['p90Dd']), usd(r3['nb']['medianPerYear']), usd(r3['nb']['p10PerYear']),
                               f"{pct(sel['nb']['share'])} ({sel['nb']['n']})", usd(sel['nb']['p90Dd']), usd(sel['nb']['medianPerYear']), usd(sel['nb']['robustPerYear']),
                               fmt(sel['violation'], 3)])
        for key, cv in r['controls'].items():
            sel = cv['selection']['pooled']
            ctrl_rows.append([track, fold, key, usd(sel['centre']['perYear']), usd(sel['centre']['dd']), sel['centre']['lots'], sel['centre']['episodes'],
                              f"{pct(sel['nb']['share'])} ({sel['nb']['n']})", usd(sel['nb']['p90Dd']), usd(sel['nb']['medianPerYear']),
                              usd(sel['nb']['robustPerYear']), fmt(sel['violation'], 3), ','.join(sorted(sel['parts'].keys())) or '—'])
        # threshold sensitivity (PROTOCOL.md §6; Study 7 §7.4) on the sealed rung-3 records
        y, ly = r['y'], r['floors']['lotYears']
        base_feasible = [f for f in r['rung3'] if feasible_under(f, y, ly, 1, 0.75)]
        base_pick = max(base_feasible, key=lambda f: num(f['nb']['robustPerYear']), default=None)
        for scale in (0.5, 1, 1.5):
            for cap in (0.65, 0.75, 0.85, None):
                feas = [f for f in r['rung3'] if feasible_under(f, y, ly, scale, cap)]
                pick = max(feas, key=lambda f: num(f['nb']['robustPerYear']), default=None)
                changed = (pick or {}).get('id') != (base_pick or {}).get('id')
                sens_rows.append([track, fold, f'×{scale}', 'none' if cap is None else pct(cap, 0), f"{len(feas)}/{len(r['rung3'])}", 'changes' if changed else 'same'])
        lots = [f['centre']['lots'] for f in r['rung3']]
        shares = [num(f['nb']['share']) for f in r['rung3']]
        sens_rows.append([track, fold, 'ρ(lots, share)', '', fmt(spearman(lots, shares)), ''])
    write('search-overview', table(['Track', 'Fold', 'y', 'floors lots/ep/yrs/book', 'GA new/pop', 'screen', 'plausible', 'R1 promoted', 'archive (R1)', 'R1 feasible', 'R2 feas/n', 'R3 feas/n', 'islands', 'T1', 'T2', 'T3', 'no eligible region', 'fresh points', 'CPU-hours'], rows)
          + f"\nTotals: {len(recs)} track-fold jobs; {tot_archive:,} configurations evaluated at rung 1; {tot_points:,} fresh point evaluations; {tot_seconds / 3600:.1f} CPU-hours (one thread per job).\n")
    write('search-islands', table(['Track', 'Fold', 'island', 'generations', 'new', 'duplicates', 'stop', 'feasible (island)', 'union HV after', 'union min violation'], islands))
    write('search-shortlists', table(['Track', 'Fold', '#', 'pick', 'id', 'parameters', 'R3 centre net/yr', 'R3 centre DD', 'lots', 'episodes', 'R3 share (n)', 'R3 p90 DD', 'R3 median/yr', 'R3 p10/yr', 'select share (n)', 'select p90 DD', 'select median/yr', 'select robust/yr', 'select violation'], short_rows))
    write('search-controls', table(['Track', 'Fold', 'control', 'centre net/yr', 'centre DD', 'lots', 'episodes', 'select share (n)', 'select p90 DD', 'select median/yr', 'select robust/yr', 'violation', 'failed constraints'], ctrl_rows))
    write('search-threshold-sensitivity', 'Rung-3 feasible counts under altered activity floors and best-year caps, and whether the top rung-3 configuration by robust profit (the profit pick\'s basis) changes; last row per track-fold: Spearman of lots with share among rung-3 configurations. Report-only.\n\n'
          + table(['Track', 'Fold', 'activity floors', 'best-year cap', 'rung-3 feasible', 'top by robust/yr'], sens_rows))
    print(f'search: {len(recs)} records')


# ---------------------------------------------------------------- qualification (training only)

def qualify():
    recs = records('qualify')
    rows, ctrl, pbo_rows, seq_rows, clip_rows = [], [], [], [], []
    for (track, fold), r in sorted(recs.items(), key=lambda kv: (TRACKS.index(kv[0][0]), FOLDS.index(kv[0][1]))):
        for c in r['candidates']:
            e, q = c['evidence'], c['qualification']
            d, rec = e['decisive'], e['centre']['record']
            alt = e['alternates']
            rows.append([track, fold, c['rank'], c['pick'], c['id'], 'yes' if q['qualified'] else 'no', ','.join(q['failed']) or '—', 'yes' if q['marginal'] else '',
                         usd(rec['net']), usd(rec['dd']), rec['lots'], rec['episodes'],
                         f"{pct(d['nb']['share'])} ({d['nb']['n']})", pct(d['wilsonLower']), usd(d['nb']['p90Dd']), usd(d['nb']['medianPerYear']), usd(d['nb']['p10PerYear']),
                         pct(alt['inbox']['nb']['share']), pct((alt.get('d8') or {}).get('nb', {}).get('share')), pct((alt.get('d16') or {}).get('nb', {}).get('share')),
                         pct((alt.get('half') or {}).get('nb', {}).get('share')), pct((alt.get('wide') or {}).get('nb', {}).get('share'))])
            s = e.get('sequence')
            if s:
                seq_rows.append([track, fold, c['id'], s['centreLots'], fmt(s['medianKeptShare']), fmt(s['medianJaccard']), s['medianDisplaced'], s['medianAdded'],
                                 usd(s['medianAbsDeltaPool']), usd(s['medianAbsInteraction']), 'yes' if s['sequenceDependent'] else 'no'])
            cl = e.get('clipping') or {}
            if cl:
                clip_rows.append([track, fold, c['id'], f"{cl.get('pointsWithClip')}/{cl.get('n')}", len(e.get('nearBound') or []), ', '.join(e.get('atBound') or []) or '—'])
        for key, cv in r['controls'].items():
            e, q = cv['evidence'], cv['qualification']
            d, rec = e['decisive'], e['centre']['record']
            ctrl.append([track, fold, key, usd(rec['net']), usd(rec['dd']), rec['lots'], f"{pct(d['nb']['share'])} ({d['nb']['n']})", usd(d['nb']['p90Dd']),
                         usd(d['nb']['medianPerYear']), usd(d['nb']['robustPerYear']), ','.join(q['failed']) or '—'])
        p = r['pbo']
        pbo_rows.append([track, fold, p.get('configs'), len(p.get('blocks', [])), fmt(p.get('pbo'), 3), fmt(r['decay']['spearman'])])
    write('qualify-candidates', table(['Track', 'Fold', '#', 'pick', 'id', 'qualified', 'failed', 'marginal', 'centre net (train)', 'centre DD', 'lots', 'episodes', 'confirm share (n)', 'Wilson LB', 'p90 DD', 'median/yr', 'p10/yr', 'in-box', 'k=8', 'k=16', '0.5r', '1.5r'], rows))
    write('qualify-controls', table(['Track', 'Fold', 'control', 'centre net (train)', 'centre DD', 'lots', 'confirm share (n)', 'p90 DD', 'median/yr', 'robust/yr', 'failed'], ctrl))
    write('qualify-pbo', table(['Track', 'Fold', 'configs', 'half-year blocks', 'PBO', 'Spearman(selection robust, confirmation robust)'], pbo_rows))
    write('qualify-sequence', table(['Track', 'Fold', 'id', 'centre lots', 'median kept share', 'median Jaccard', 'median displaced', 'median added', 'median |Δ pool|', 'median |interaction|', 'sequence-dependent'], seq_rows))
    write('qualify-clipping', table(['Track', 'Fold', 'id', 'decisive points with a clip', 'coordinates within r of a bound', 'coordinates at a bound'], clip_rows))
    print(f'qualify: {len(rows)} candidates')


def selection():
    r = sealed(f'{ROOT}/FROZEN_SELECTION.json')
    roles = [[x['track'], x['fold'], x['role'], x.get('id') or '(none qualified)', 'yes' if x.get('marginal') else ''] for x in r['roles']]
    ranked = []
    for fold in FOLDS:
        for x in r['rankedByFold'].get(fold, []):
            ranked.append([fold, x['rank'], x['tier'], x['track'], x['role'], x['id'], usd(x['robustPerYear']), usd(x['b1RobustPerYear']),
                           usd(x['trainingSelection']['robustPerYear']), 'yes' if x['marginal'] else ''])
    write('selection-roles', table(['Track', 'Fold', 'Role', 'Holder', 'marginal'], roles))
    write('selection-ranked', table(['Fold', 'Rank', 'Tier', 'Track', 'Role', 'id', 'confirm robust/yr (train)', 'B1 robust/yr (same labels)', 'selection robust/yr', 'marginal'], ranked) if ranked else 'No role holder in any fold.\n')
    print(f'selection: {len(ranked)} role holders')


# ---------------------------------------------------------------- test doors (report only; after the F24 test)

def test_records():
    if not os.path.exists(f'{RES}/test/F24/test.json'):
        raise SystemExit('test tables are built only after the one-time F24 test is sealed')
    return {fold: sealed(f'{RES}/test/{fold}/test.json') for fold in FOLDS if os.path.exists(f'{RES}/test/{fold}/test.json')}


def gates_text(g):
    return g['status'].upper() + (f" ({','.join(g['failed'])})" if g['failed'] else '')


def test():
    tests = test_records()
    for fold, r in tests.items():
        hold, ctrl, mem, risk = [], [], [], []
        for h in r['holders']:
            e, d = h['evidence'], h['deep']
            rec, nb = e['centre']['record'], e['decisive']['nb']
            t, s = d['test'], d.get('series') or {}
            hold.append([h['rank'], h['tier'], h['track'], h['role'], h['id'], gates_text(h['gates']), usd(rec['net']), usd(t['net']), usd(t.get('y2025')), usd(t.get('y2026ytd')),
                         t['newLots'], t['newEpisodes'], usd(rec['dd']), usd(s.get('testWindowMinuteDd', {}).get('maximum') if isinstance(s.get('testWindowMinuteDd'), dict) else s.get('testWindowMinuteDd')),
                         f"{pct(nb['share'])} ({nb['n']})", usd(nb['p90Dd']), usd((e['decisive'].get('test') or {}).get('median')), usd((e['decisive'].get('test') or {}).get('p10')),
                         pct(h['gates']['bestYearShare']), 'pass' if h['s7Equivalent']['passed'] else ','.join(h['s7Equivalent']['failed'])])
            g = d.get('gapRisk') or {}
            risk.append([h['track'], h['id'], g.get('stops'), g.get('gapStops'), g.get('testWindowGapStops'), usd(g.get('gapLossBeyondStop')), usd(g.get('worstGapLossBeyondStop')),
                         usd(t.get('worstLotMae')), usd(d['sensitivities']['nextOpen']['test']), usd(d['sensitivities']['slip25']['test']), usd(d['sensitivities']['cost10']['test']),
                         usd(d['sensitivities']['rate14']['test'])])
        for key, c in r['controls'].items():
            e, d = c['evidence'], c['deep']
            rec, nb = e['centre']['record'], e['decisive']['nb']
            t = d['test']
            ctrl.append([key, gates_text(c['gates']), usd(rec['net']), usd(t['net']), usd(t.get('y2025')), usd(t.get('y2026ytd')), t['newLots'], usd(rec['dd']),
                         f"{pct(nb['share'])} ({nb['n']})", usd(nb['p90Dd']), usd((e['decisive'].get('test') or {}).get('median')),
                         'pass' if c['s7Equivalent']['passed'] else ','.join(c['s7Equivalent']['failed'])])
        for m in r['members']:
            mem.append([m['track'], m['order'], m['pick'], m['id'], 'yes' if m['qualified'] else 'no', 'yes' if m['holder'] else '', usd(m['selectionRobustPerYear']),
                        usd(m['centre']['train']), usd(m['centre']['test']), usd(m['testMedian']), usd(m['centre']['dd']), gates_text(m['gates']),
                        'pass' if m['s7Equivalent']['passed'] else ','.join(m['s7Equivalent']['failed'])])
        head = f"Fold {fold}: test window {r['window']['test']} (yTest {r['window']['yTest']:.3f}; T6 test floors {r['window']['testFloors']['lots']} lots / {r['window']['testFloors']['episodes']} episodes); run years {r['window']['yRun']:.2f}.\n\n"
        write(f'test-{fold}-holders', head + (table(['Rank', 'Tier', 'Track', 'Role', 'id', 'T status', 'run net', 'test net', '2025', '2026 YTD', 'new lots', 'new episodes', 'run minute DD', 'test-window minute DD', 'test share (n)', 'p90 DD (run)', 'test median', 'test p10', 'best-year share', 'Study 7-equivalent gates'], hold) if hold else 'No role holder in this fold.\n'))
        write(f'test-{fold}-controls', head + table(['Control', 'T status', 'run net', 'test net', '2025', '2026 YTD', 'new lots', 'run minute DD', 'test share (n)', 'p90 DD', 'test median', 'Study 7-equivalent gates'], ctrl))
        write(f'test-{fold}-members', head + table(['Track', '#', 'pick', 'id', 'qualified', 'holder', 'selection robust/yr', 'train net', 'test net', 'test median', 'run DD', 'T status', 'Study 7-equivalent'], mem))
        write(f'test-{fold}-risk', head + table(['Track', 'id', 'stop exits', 'gapped stops', 'gapped (test window)', 'loss beyond stop', 'worst gap loss', 'worst test-lot MAE', 'test net next-open', 'test net +25 bps', 'test net 10 bps', 'test net 14%'], risk))
    print(f'test: {len(tests)} folds')


def folds():
    tests = test_records()
    rows, rr = [], []
    for fold, r in tests.items():
        p = r['persistence']
        rows.append([fold, r['window']['test'], f"{r['window']['yTest']:.2f}", f"{p['holders']['notFailed']}/{p['holders']['n']}", pct(p['holders']['rate']),
                     f"{p['shortlist']['notFailed']}/{p['shortlist']['n']}", pct(p['shortlist']['rate']),
                     f"{p['qualifiedMembers']['notFailed']}/{p['qualifiedMembers']['n']}", f"{p['otherMembers']['notFailed']}/{p['otherMembers']['n']}",
                     f"{p['s7Equivalent']['passed']}/{p['s7Equivalent']['n']}", pct(p['positiveTestWindow']['qualified']), pct(p['positiveTestWindow']['other']),
                     p['holderTestLots'], 'yes' if p['insufficientEvidence'] else 'no'])
        x = r['returnRank']
        rr.append([fold, f"{fmt(x['selectionVsTestCentre']['rho'])} (n {x['selectionVsTestCentre']['n']})", f"{fmt(x['selectionVsTestMedian']['rho'])} (n {x['selectionVsTestMedian']['n']})",
                   f"{fmt(x['confirmationVsTestCentre']['rho'])} (n {x['confirmationVsTestCentre']['n']})",
                   '; '.join(f"{k} {fmt(v['rho'])}" for k, v in x['byTrack'].items())])
    write('folds-persistence', 'Descriptive (PROTOCOL.md §8.5). Test windows differ in length and regime, and overlap; persistence is not comparable as independent trials.\n\n'
          + table(['Fold', 'test window', 'yTest', 'holders not failed', 'holder rate', 'members not failed', 'member rate', 'qualified members', 'other members', 'Study 7-equivalent pass', 'positive test (qualified)', 'positive test (other)', 'holder test lots', 'insufficient evidence'], rows))
    write('folds-return-rank', table(['Fold', 'ρ(selection robust, test centre)', 'ρ(selection robust, test median)', 'ρ(confirmation robust, test centre)', 'within track: ρ(−order, test centre)'], rr))
    f24 = tests.get('F24')
    if f24:
        nom = [[n['rank'], n['track'], n['role'], n['id'], n['status']] for n in f24['nominations']]
        write('F24-outcome', f"Outcome class: **{f24['outcome']['class']}**; primary nominee: {f24['outcome']['primaryNominee']['id'] if f24['outcome'].get('primaryNominee') else 'none'}.\n\n"
              + (table(['Rank', 'Track', 'Role', 'id', 'status'], nom) if nom else 'No research nomination.\n'))
    print('folds: done')


