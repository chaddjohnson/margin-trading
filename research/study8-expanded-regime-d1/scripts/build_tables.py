def tracks():
    """Per track: the frozen control(s) against the F24 profit / robust / balanced role holders, on the F24 test run."""
    tests = test_records()
    r = tests['F24']
    control_of = {'G': ['G-PA'], 'V': ['B1'], 'VG': ['VG'], 'VXR': ['VXR'], 'VXRG': ['VXRG'], 'VXRKG': ['B5']}
    rows = []

    def row(label, status, e, d):
        rec, nb = e['centre']['record'], e['decisive']['nb']
        t, p = d['test'], rec['periods']
        tst = e['decisive'].get('test') or {}
        return [label, status, usd(rec['net']), usd(t['net']), usd(t.get('y2025')), usd(t.get('y2026ytd')), usd(rec['dd']), usd(rec['ddDaily']),
                f"{pct(nb['share'])} ({nb['n']})", usd(nb['p90Dd']), usd(nb['medianNet']), usd(nb['p10Net']), usd(tst.get('median')), usd(tst.get('p10')),
                f"{rec['lots']}/{rec['episodes']}", f"{t['newLots']}/{t['newEpisodes']}", usd(p.get('2020')), usd(p.get('2022')), usd(p.get('2024'))]

    for track in TRACKS:
        for key in control_of[track]:
            c = r['controls'][key]
            rows.append(row(f'{track}: frozen {key}', gates_text(c['gates']), c['evidence'], c['deep']))
        for role in ('profit', 'robust', 'balanced'):
            h = next((x for x in r['holders'] if x['track'] == track and x['role'] == role), None)
            if h:
                rows.append(row(f"{track}: #{h['rank']} {role}", gates_text(h['gates']), h['evidence'], h['deep']))
            else:
                rows.append([f'{track}: {role}', '(role empty)'] + [''] * 17)
    write('F24-tracks', 'One continuous run 2016-01-04 → 2026-10-29, 5 bps, 11%; test window 2025-01-02 → 2026-10-29; neighbourhood = the three fresh test families (384). Frozen controls for G and V are G-PA and B1; B5 is the five-book control.\n\n'
          + table(['Configuration', 'T status', 'run net', 'test net', '2025', '2026 YTD', 'run minute DD', 'run daily DD', 'share < $35k (n)', 'p90 DD', 'median net (run)', 'p10 net (run)', 'median test net', 'p10 test net', 'lots/episodes (run)', 'new lots/episodes (test)', '2020', '2022', '2024'], rows))
    print('tracks: done')


