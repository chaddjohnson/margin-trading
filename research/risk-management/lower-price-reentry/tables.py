"""Generate COMPARISON.md (consolidated tables across all configurations and datasets) from results/summary.json."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATASETS = ['VGT_2005_2015', 'QQQ_1999_2015', 'VGT_2016_2026', 'QQQ_2016_2026']
CONFIGS = ['A_baseline', 'B_lower_3pct', 'C_lower_5pct', 'D_lower_8pct']
NAMES = {'A_baseline': 'A (baseline)', 'B_lower_3pct': 'B (−3%)', 'C_lower_5pct': 'C (−5%)', 'D_lower_8pct': 'D (−8%)'}


def f0(x):
    return f'{x:,.0f}' if x is not None else '—'


def f2(x):
    return f'{x:.2f}' if x is not None else '—'


def pct(x):
    return f'{100 * x:.0f}%' if x is not None else '—'


def main():
    recs = {(r['dataset'], r['config']): r for r in json.load(open(HERE / 'results' / 'summary.json'))}
    L = []
    w = L.append
    w('# Lower-price re-entry with recovery reset — consolidated comparison')
    w('')
    w('Generated by `tables.py` from `results/summary.json` (run `run.py` first). Rule: after a losing exit,')
    w('re-enter only at a close 3% / 5% / 8% below the losing exit price, unless the close first recovers to')
    w('within 5% of the losing trade\'s frozen 90-session entry reference high (recovery reset). Details,')
    w('verification and interpretation: `REPORT.md`.')
    w('')

    w('## 1. Headline results')
    w('')
    for ds in DATASETS:
        w(f'### {ds}')
        w('')
        w('| Metric | ' + ' | '.join(NAMES[c] for c in CONFIGS) + ' |')
        w('|---|---:|---:|---:|---:|')
        rows = [
            ('Net profit', lambda m, x, mc: f0(m['net_profit'])),
            ('… realized', lambda m, x, mc: f0(m['realized_profit'])),
            ('… unrealized (open at end)', lambda m, x, mc: f0(m['unrealized_profit'])),
            ('Max daily MTM drawdown', lambda m, x, mc: f0(m['max_drawdown'])),
            ('Profit / max drawdown', lambda m, x, mc: f2(m['profit_to_drawdown'])),
            ('Closed trades', lambda m, x, mc: f"{m['closed_trades']}"),
            ('Winners / losers', lambda m, x, mc: f"{m['winning_trades']} / {m['losing_trades']}"),
            ('Win rate', lambda m, x, mc: pct(m['win_rate'])),
            ('Largest losing trade', lambda m, x, mc: f0(m['largest_losing_trade'])),
            ('Max consecutive losses', lambda m, x, mc: f"{m['max_consecutive_losses']}"),
            ('Margin interest', lambda m, x, mc: f0(m['margin_interest'])),
            ('Margin dollar-days ($M·d)', lambda m, x, mc: f"{m['margin_dollar_days'] / 1e6:,.1f}"),
            ('% sessions invested', lambda m, x, mc: pct(m['pct_sessions_exposed'])),
            ('Longest underwater (days)', lambda m, x, mc: f"{m['longest_underwater_days']}" + ('' if m['longest_underwater_recovered'] else ' (not recovered)')),
            ('Entries blocked (signal sessions)', lambda m, x, mc: f"{x['entries_blocked_sessions']}" if x else '—'),
            ('Lower-price re-entries', lambda m, x, mc: f"{x['lower_price_reentries']}" if x else '—'),
            ('Recovery resets', lambda m, x, mc: f"{x['recovery_resets']}" if x else '—'),
            ('Baseline entries missed', lambda m, x, mc: f"{mt['baseline_entries_missed']}" if mt else '—'),
            ('Baseline entries delayed', lambda m, x, mc: f"{mt['baseline_entries_delayed']}" if mt else '—'),
        ]
        cells = {}
        for c in CONFIGS:
            r = recs[(ds, c)]
            m, x, mt = r['metrics'], r['extra'].get('state_machine'), r['extra'].get('matching')
            for name, fn in rows:
                cells.setdefault(name, []).append(fn(m, x, mt))
        for name, _ in rows:
            w(f'| {name} | ' + ' | '.join(cells[name]) + ' |')
        w('')

    w('## 2. Matched-exposure comparison')
    w('')
    w('Control: a complete baseline run with a fixed position size scaled so its margin dollar-days equal the')
    w('experiment\'s. Positive Δ favours the experiment (for drawdown, negative Δ means the experiment had the')
    w('smaller drawdown).')
    w('')
    w('| Dataset | Config | Control size | Net | Control net | Δ profit | Max DD | Control DD | Δ DD | P/DD | Control P/DD |')
    w('|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
    for ds in DATASETS:
        for c in CONFIGS[1:]:
            mc = recs[(ds, c)]['matched_control']
            w(f"| {ds} | {NAMES[c]} | {f0(mc['control_fixed_size'])} | {f0(mc['experiment_profit'])} | "
              f"{f0(mc['control_profit'])} | {f0(mc['profit_difference'])} | {f0(mc['experiment_max_drawdown'])} | "
              f"{f0(mc['control_max_drawdown'])} | {f0(mc['drawdown_difference'])} | "
              f"{f2(mc['experiment_profit_to_drawdown'])} | {f2(mc['control_profit_to_drawdown'])} |")
    w('')

    w('## 3. Bear-market windows')
    w('')
    w('| Dataset | Window | Config | Period P&L | Max DD in window | Closed | Losing | Largest loss | Interest |')
    w('|---|---|---|---:|---:|---:|---:|---:|---:|')
    for ds in DATASETS:
        for wname in ['2000-2002', '2007-2009', '2022']:
            for c in CONFIGS:
                bw = recs[(ds, c)]['metrics']['bear_windows'].get(wname)
                if bw:
                    w(f"| {ds} | {wname} | {NAMES[c]} | {f0(bw['pnl'])} | {f0(bw['max_drawdown'])} | "
                      f"{bw['trades_closed']} | {bw['losing_trades']} | {f0(bw['largest_loss'])} | {f0(bw['interest'])} |")
    w('')

    w('## 4. Recovery windows (incl. the 2026 window, 2026-03-20..2026-10-06)')
    w('')
    w('| Dataset | Window | Config | Period P&L | Trades entered | P&L of trades entered |')
    w('|---|---|---|---:|---:|---:|')
    for ds in DATASETS:
        wins = recs[(ds, 'A_baseline')]['extra']['recovery_windows_ext'].keys()
        for wname in wins:
            for c in CONFIGS:
                rw = recs[(ds, c)]['extra']['recovery_windows_ext'].get(wname)
                if rw:
                    w(f"| {ds} | {wname} | {NAMES[c]} | {f0(rw['pnl'])} | {rw['trades_entered']} | "
                      f"{f0(rw['pnl_of_trades_entered'])} |")
    w('')

    w('## 5. Major baseline winners (≥ $10k) and repeated losers')
    w('')
    w('From the per-baseline-trade matching (`results/matching/`). "Rebound" = the preceding baseline trade lost.')
    w('')
    w('| Dataset | Config | Major winners | identical / later / missed | Major rebound winners | identical / later / missed | Repeated losers | eliminated | Baseline P&L of repeated losers | Variant window P&L |')
    w('|---|---|---:|---|---:|---|---:|---:|---:|---:|')
    for ds in DATASETS:
        for c in CONFIGS[1:]:
            mt = recs[(ds, c)]['extra']['matching']
            mw, mr, rp = mt['major_winners_10k'], mt['major_rebound_winners_10k'], mt['repeated_losers']
            w(f"| {ds} | {NAMES[c]} | {mw['n']} | {mw['identical']} / {mw['later']} / {mw['eliminated']} | "
              f"{mr['n']} | {mr['identical']} / {mr['later']} / {mr['eliminated']} | "
              f"{rp['n']} | {rp['eliminated']} | {f0(rp['baseline_pnl'])} | {f0(rp['variant_window_pnl'])} |")
    w('')

    w('## 6. State-machine behaviour')
    w('')
    w('| Dataset | Config | Episodes | Re-entries | Resets | Unresolved at end | Blocked sessions | Median restricted (sess.) | Max restricted (sess. / days) | Median re-entry vs loss exit | Median re-entry vs losing entry |')
    w('|---|---|---:|---:|---:|---:|---:|---:|---|---:|---:|')
    for ds in DATASETS:
        for c in CONFIGS[1:]:
            x = recs[(ds, c)]['extra']['state_machine']
            byres = x['episodes_by_resolution']
            med = x['reentry_discount_vs_loss_exit_median']
            med2 = x['reentry_vs_losing_entry_median']
            w(f"| {ds} | {NAMES[c]} | {x['losing_exits']} | {byres.get('lower_price_reentry', 0)} | "
              f"{byres.get('recovery_reset', 0)} | {byres.get('unresolved_at_end', 0)} | "
              f"{x['entries_blocked_sessions']} | {x['sessions_restricted_median']:.0f} | "
              f"{x['sessions_restricted_max']:.0f} / {x['days_restricted_max']:.0f} | "
              f"{100 * med:.1f}% | {100 * med2:.1f}% |")
    w('')
    w('Dual-trigger sessions (close satisfying both the lower-price trigger and the reset) and reset-priority')
    w('blocks: **zero** in every configuration and dataset, as the arithmetic in `strategies.py` predicts.')
    w('')
    (HERE / 'COMPARISON.md').write_text('\n'.join(L) + '\n')
    print(f'wrote {HERE / "COMPARISON.md"} ({len(L)} lines)')


if __name__ == '__main__':
    main()
