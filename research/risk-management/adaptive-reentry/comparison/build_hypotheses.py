"""Coordinator: consolidate every family's append-only registry.jsonl into HYPOTHESES.md (the complete
pre-registered experiment registry, in registration order per family, including configs that failed)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
FAMILY_DIRS = ['loss-classification', 'adaptive-discounts', 'recovery-resets', 'recovery-opportunities',
               'state-memory', 'execution-feasibility', 'combinations', 'validation']


def main():
    L = ['# Consolidated hypothesis and configuration registry',
         '',
         'Every configuration evaluated in Phase 2, as registered BEFORE its first evaluation (the',
         'runner refuses unregistered configs; registries are append-only, so abandoned and failed',
         'candidates remain on record). Generated by comparison/build_hypotheses.py from the family',
         "registries' registry.jsonl files. Sensitivity grids registered as single entries list their",
         'points inline.', '']
    total = 0
    for fam in FAMILY_DIRS:
        p = ROOT / fam / 'registry.jsonl'
        if not p.exists():
            continue
        entries = [json.loads(line) for line in p.read_text().splitlines() if line.strip()]
        total += len(entries)
        L.append(f'## {fam} ({len(entries)} entries)')
        L.append('')
        for e in entries:
            params = json.dumps(e.get('params', {}))
            L.append(f"- **{e['name']}** ({e.get('registered_at', '?')}) — {e.get('description', '')}")
            L.append(f"  - Hypothesis: {e.get('hypothesis', '')}")
            L.append(f'  - Params: `{params}`')
        L.append('')
    L.append(f'**Total registered entries: {total}.** Every one of these draws on the same four heavily')
    L.append('reused datasets; see COMPARISON.md and validation/ROBUSTNESS.md for the multiple-testing')
    L.append('accounting. No entry here is validated by its in-sample rank alone.')
    (ROOT / 'HYPOTHESES.md').write_text('\n'.join(L) + '\n')
    print(f'HYPOTHESES.md written ({total} entries across {sum(1 for f in FAMILY_DIRS if (ROOT / f / "registry.jsonl").exists())} registries)')


if __name__ == '__main__':
    main()
