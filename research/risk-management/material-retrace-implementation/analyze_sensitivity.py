"""Sensitivity tables for the 4 x 5 material-cutoff x retrace-fraction grid (3% fixed) from
results/python/summary.json. Writes results/analysis/sensitivity.md and sensitivity.json.

Per dataset: net / max DD / P-DD / exposure grids; neighbor differences (smoothness); the largest
single-step discontinuity and the first trade at which the two neighbors diverge; net excluding each
configuration's largest winning trade; bear-window P&L per grid point (frozen datasets); matched-exposure
deltas (is a change "just" less exposure?). No optimum is selected.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
PY = HERE / 'results' / 'python'
OUT = HERE / 'results' / 'analysis'
CUTS = [0.0025, 0.005, 0.0075, 0.01]
FRACS = [0.34, 0.38, 0.42, 0.46, 0.50]
DATASETS = ['VGT_2016_2025', 'VGT_2005_2015', 'QQQ_1999_2015', 'VGT_2016_2026', 'QQQ_2016_2026']


def gname(c, f):
    return f'grid_c{c * 10000:04.0f}_r{f * 100:.0f}'


def grid_table(get, fmtf, title):
    L = [f'**{title}**', '', '| cutoff \\ retrace | ' + ' | '.join(f'{f:.2f}' for f in FRACS) + ' |', '|---|' + '---:|' * len(FRACS)]
    for c in CUTS:
        cells = []
        for f in FRACS:
            v = get(c, f)
            s = fmtf(v)
            if c == 0.005 and f == 0.38:
                s = f'**{s}**'
            cells.append(s)
        L.append(f'| {100 * c:.2f}% | ' + ' | '.join(cells) + ' |')
    L.append('')
    return L


def first_divergence(ds, a, b):
    ta = pd.read_csv(PY / 'trades' / f'{ds}__{a}.csv')
    tb = pd.read_csv(PY / 'trades' / f'{ds}__{b}.csv')
    ka = list(zip(ta['entry_date'].astype(str), ta['exit_date'].fillna('open').astype(str), ta['profit'].round(2)))
    kb = list(zip(tb['entry_date'].astype(str), tb['exit_date'].fillna('open').astype(str), tb['profit'].round(2)))
    for i, (x, y) in enumerate(zip(ka, kb)):
        if x != y:
            return f'{a}: {x[0]}->{x[1]} {x[2]:+,.0f} | {b}: {y[0]}->{y[1]} {y[2]:+,.0f}'
    if len(ka) != len(kb):
        return f'identical until trade {min(len(ka), len(kb))}, then counts differ ({len(ka)} vs {len(kb)})'
    return 'trade-identical'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    recs = {(r['config'], r['dataset']): r for r in json.load(open(PY / 'summary.json'))}
    L = ['# Sensitivity grid tables (generated by analyze_sensitivity.py; production point in bold)', '']
    out = {}
    for ds in DATASETS:
        L.append(f'## {ds}')
        L.append('')
        ref = recs[('new', ds)]['metrics']
        l3 = recs[('lower3', ds)]['metrics']
        L.append(f"Previous 3% rule: net {l3['net_profit']:,.0f}, max DD {l3['max_drawdown']:,.0f}. Production point (0.50%, 0.38): net {ref['net_profit']:,.0f}, max DD {ref['max_drawdown']:,.0f}.")
        L.append('')
        m = lambda c, f, k: recs[(gname(c, f), ds)]['metrics'][k]
        mc = lambda c, f, k: recs[(gname(c, f), ds)]['matched_control'][k]
        L += grid_table(lambda c, f: m(c, f, 'net_profit'), lambda v: f'{v:,.0f}', 'Net profit')
        L += grid_table(lambda c, f: m(c, f, 'max_drawdown'), lambda v: f'{v:,.0f}', 'Max drawdown')
        L += grid_table(lambda c, f: m(c, f, 'profit_to_drawdown'), lambda v: f'{v:.2f}', 'Profit / max drawdown')
        L += grid_table(lambda c, f: mc(c, f, 'exposure_vs_baseline'), lambda v: f'{v:.3f}', 'Exposure vs baseline (dollar-days ratio)')
        L += grid_table(lambda c, f: mc(c, f, 'profit_difference'), lambda v: f'{v:+,.0f}', 'Net vs matched-exposure baseline control')
        L += grid_table(lambda c, f: mc(c, f, 'drawdown_difference'), lambda v: f'{v:+,.0f}', 'Max DD vs matched-exposure baseline control (negative = smaller)')
        # largest-winner exclusion
        def ex_best(c, f):
            tr = pd.read_csv(PY / 'trades' / f'{ds}__{gname(c, f)}.csv')
            return m(c, f, 'net_profit') - tr['profit'].max()
        L += grid_table(ex_best, lambda v: f'{v:,.0f}', 'Net excluding the single largest winning trade')
        bears = recs[(gname(0.005, 0.38), ds)]['metrics']['bear_windows']
        for w in bears:
            L += grid_table(lambda c, f, w=w: recs[(gname(c, f), ds)]['metrics']['bear_windows'][w]['pnl'], lambda v: f'{v:+,.0f}', f'Bear window {w} P&L')
        # smoothness: neighbor steps in net
        steps = []
        for ci, c in enumerate(CUTS):
            for fi, f in enumerate(FRACS):
                if fi + 1 < len(FRACS):
                    steps.append((abs(m(c, f, 'net_profit') - m(c, FRACS[fi + 1], 'net_profit')), gname(c, f), gname(c, FRACS[fi + 1])))
                if ci + 1 < len(CUTS):
                    steps.append((abs(m(c, f, 'net_profit') - m(CUTS[ci + 1], f, 'net_profit')), gname(c, f), gname(CUTS[ci + 1], f)))
        steps.sort(reverse=True)
        nets = np.array([[m(c, f, 'net_profit') for f in FRACS] for c in CUTS])
        L.append(f'Neighbor-step statistics (|Δnet| between adjacent grid points, {len(steps)} steps): median {np.median([s[0] for s in steps]):,.0f}, '
                 f'max {steps[0][0]:,.0f}; grid range {nets.min():,.0f} .. {nets.max():,.0f}; '
                 f'{int((nets > l3["net_profit"]).sum())}/20 points above the previous 3% rule on net.')
        L.append('')
        L.append('Largest discontinuities and the first diverging trade:')
        L.append('')
        for d, a, b in steps[:3]:
            L.append(f'- Δ {d:,.0f} between {a} and {b}: {first_divergence(ds, a, b)}')
        L.append('')
        out[ds] = dict(net=nets.tolist(), steps=[(float(d), a, b) for d, a, b in steps[:5]])
    (OUT / 'sensitivity.md').write_text('\n'.join(L) + '\n')
    json.dump(out, open(OUT / 'sensitivity.json', 'w'), indent=1)
    print(f'wrote {OUT / "sensitivity.md"}')


if __name__ == '__main__':
    main()
