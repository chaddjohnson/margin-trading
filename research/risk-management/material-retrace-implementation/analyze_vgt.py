"""VGT 2016 .. 2025-12-31 analysis of the production strategy and the five reference strategies.

Uses the Python reference outputs in results/python/ (trade-identical to the TypeScript run — asserted
by regression_test.py — because the frozen metrics module's window statistics need the daily
calendar_days column that only the Python daily CSV carries). Writes results/analysis/vgt_2016_2025.md
(tables) and results/analysis/vgt_2016_2025.json.

Sections: headline metrics; calendar-year breakdown (year P&L = change in cumulative MTM P&L across the
year; year drawdown = peak-to-trough INSIDE the year starting from the pre-year level, which is not the
full-period drawdown); episode windows; trade-level attribution of the production strategy's
differences from the existing 3% rule to the material-loss exemption, the retracement reset, or their
interaction; restriction/reset event log.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
RM = HERE.parent
sys.path.insert(0, str(RM / 'baseline'))
from metrics import window_stats  # noqa: E402

PY = HERE / 'results' / 'python'
OUT = HERE / 'results' / 'analysis'
DS = 'VGT_2016_2025'
CONFIGS = ['baseline', 'lower3', 'material05', 'retrace38', 'g8', 'new']
LABELS = {'baseline': 'Original baseline', 'lower3': 'Previous 3%', 'material05': 'Material-loss only',
          'retrace38': 'Retracement reset only', 'g8': 'Original G8 (1%)', 'new': 'New combined strategy'}
EPISODES = {
    'Dec 2018 correction & recovery': ('2018-10-01', '2019-06-30'),
    'Feb-Apr 2020 crash': ('2020-02-01', '2020-09-30'),
    '2022 technology bear market': ('2022-01-01', '2022-12-31'),
    'Jan 2023 recovery': ('2023-01-01', '2023-08-31'),
    'Oct 2023 correction': ('2023-08-01', '2024-04-30'),
    'Apr 2024 correction': ('2024-04-01', '2024-08-31'),
    'Mar-Apr 2025 correction & recovery': ('2025-02-15', '2025-12-31'),
}


def load_res(cfg):
    tr = pd.read_csv(PY / 'trades' / f'{DS}__{cfg}.csv')
    d = pd.read_csv(PY / 'daily' / f'{DS}__{cfg}.csv')
    d['date'] = pd.to_datetime(d['date']).dt.date
    return dict(trades=tr, daily=d)


def fmt(x):
    return f'{x:,.0f}'


def yearly(res):
    d = res['daily']
    years = sorted({dt.year for dt in d['date']})
    rows = []
    for y in years:
        w = (f'{y}-01-01', f'{y}-12-31')
        s = window_stats(res, w)
        tr = res['trades']
        closed = tr[tr['exit_date'].notna()]
        ex = pd.to_datetime(closed['exit_date']).dt.year
        c = closed[ex == y]
        rows.append(dict(year=y, pnl=s['pnl'], closed=int(len(c)), wins=int((c['profit'] > 0).sum()),
                         losses=int((c['profit'] < 0).sum()), interest=s['interest'], max_dd_in_year=s['max_drawdown'],
                         avg_borrowed=s['avg_borrowed']))
    return pd.DataFrame(rows)


def trade_key(tr):
    return set(zip(tr['entry_date'].astype(str), tr['exit_date'].fillna('open').astype(str)))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    recs = {r['config']: r for r in json.load(open(PY / 'summary.json')) if r['dataset'] == DS}
    res = {c: load_res(c) for c in CONFIGS}
    L = [f'# VGT 2016 .. 2025-12-31 — analysis tables (generated by analyze_vgt.py)', '']
    first, last = str(res['new']['daily']['date'].iloc[0]), str(res['new']['daily']['date'].iloc[-1])
    L.append(f'Data range used: {first} .. {last} ({len(res["new"]["daily"])} sessions). No 2026 observation is loaded.')
    L.append('')
    # headline
    L.append('## Headline metrics')
    L.append('')
    cols = ['net_profit', 'realized_profit', 'unrealized_profit', 'max_drawdown', 'profit_to_drawdown', 'closed_trades',
            'winning_trades', 'losing_trades', 'largest_losing_trade', 'max_consecutive_losses', 'margin_interest',
            'avg_borrowed_all_sessions', 'margin_dollar_days', 'pct_sessions_exposed', 'longest_underwater_days',
            'mdd_peak_date', 'mdd_trough_date']
    L.append('| metric | ' + ' | '.join(LABELS[c] for c in CONFIGS) + ' |')
    L.append('|---|' + '---:|' * len(CONFIGS))
    for col in cols:
        vals = []
        for c in CONFIGS:
            v = recs[c]['metrics'][col]
            if isinstance(v, float):
                vals.append(f'{v:.2f}' if col in ('profit_to_drawdown', 'pct_sessions_exposed') else (f'{v / 1e6:,.1f}M' if col == 'margin_dollar_days' else fmt(v)))
            else:
                vals.append(str(v))
        L.append(f'| {col} | ' + ' | '.join(vals) + ' |')
    L.append('')
    L.append('| matched-exposure control | ' + ' | '.join(LABELS[c] for c in CONFIGS) + ' |')
    L.append('|---|' + '---:|' * len(CONFIGS))
    for key in ['control_fixed_size', 'control_profit', 'control_max_drawdown', 'profit_difference', 'drawdown_difference', 'exposure_vs_baseline']:
        L.append(f'| {key} | ' + ' | '.join((f"{recs[c]['matched_control'][key]:.3f}" if key == 'exposure_vs_baseline' else fmt(recs[c]['matched_control'][key])) for c in CONFIGS) + ' |')
    L.append('')
    # yearly for new strategy and for baseline/lower3 reference
    out_json = {}
    for c in ['new', 'baseline', 'lower3', 'g8']:
        y = yearly(res[c])
        out_json[f'yearly_{c}'] = y.to_dict(orient='records')
        L.append(f'## Calendar-year breakdown — {LABELS[c]}')
        L.append('')
        L.append('| year | MTM P&L | closed | W | L | interest | max DD within year | avg borrowed |')
        L.append('|---|---:|---:|---:|---:|---:|---:|---:|')
        for _, r in y.iterrows():
            L.append(f"| {r['year']} | {fmt(r['pnl'])} | {r['closed']} | {r['wins']} | {r['losses']} | {fmt(r['interest'])} | {fmt(r['max_dd_in_year'])} | {fmt(r['avg_borrowed'])} |")
        L.append(f"| total | {fmt(y['pnl'].sum())} | {y['closed'].sum()} | {y['wins'].sum()} | {y['losses'].sum()} | {fmt(y['interest'].sum())} | — | — |")
        L.append('')
    # episodes
    L.append('## Episode windows (window P&L = change in cumulative MTM P&L; trades entered inside the window)')
    L.append('')
    L.append('| episode | window | ' + ' | '.join(LABELS[c] for c in CONFIGS) + ' |')
    L.append('|---|---|' + '---:|' * len(CONFIGS))
    ep_json = {}
    for name, w in EPISODES.items():
        vals = []
        ep_json[name] = {}
        for c in CONFIGS:
            s = window_stats(res[c], w)
            ep_json[name][c] = s
            vals.append(f"{fmt(s['pnl'])} ({s['trades_entered']}t)")
        L.append(f'| {name} | {w[0]}..{w[1]} | ' + ' | '.join(vals) + ' |')
    L.append('')
    out_json['episodes'] = ep_json
    # trades inside each episode, per strategy
    for name, w in EPISODES.items():
        L.append(f'### Trades entered in: {name}')
        L.append('')
        for c in CONFIGS:
            tr = res[c]['trades']
            en = pd.to_datetime(tr['entry_date']).dt.date
            a, b = pd.Timestamp(w[0]).date(), pd.Timestamp(w[1]).date()
            sub = tr[(en >= a) & (en <= b)]
            items = '; '.join(f"{r['entry_date']}@{r['entry_price']:.2f}->{r['exit_date'] if pd.notna(r['exit_date']) else 'open'}@{r['exit_price']:.2f} {r['reason']} {r['profit']:+,.0f}" for _, r in sub.iterrows())
            L.append(f'- **{LABELS[c]}**: {items if items else "no entries"}')
        L.append('')
    # attribution
    k = {c: trade_key(res[c]['trades']) for c in CONFIGS}
    only_new = k['new'] - k['lower3']
    gone = k['lower3'] - k['new']
    L.append('## Trade-level attribution vs the previous 3% rule')
    L.append('')
    L.append('Trades of the new strategy absent from the previous 3% rule, tagged by which single-mechanism reference also has them:')
    L.append('')
    tr_new = res['new']['trades']
    for _, r in tr_new.iterrows():
        key = (str(r['entry_date']), str(r['exit_date']) if pd.notna(r['exit_date']) else 'open')
        if key in only_new:
            tags = [LABELS[c] for c in ['material05', 'retrace38', 'g8'] if key in k[c]]
            L.append(f"- {key[0]}@{r['entry_price']:.2f} -> {key[1]}@{r['exit_price']:.2f} {r['reason']} {r['profit']:+,.0f} — shared with: {', '.join(tags) if tags else 'neither (interaction)'}")
    L.append('')
    L.append('Trades of the previous 3% rule absent from the new strategy:')
    L.append('')
    for _, r in res['lower3']['trades'].iterrows():
        key = (str(r['entry_date']), str(r['exit_date']) if pd.notna(r['exit_date']) else 'open')
        if key in gone:
            tags = [LABELS[c] for c in ['material05', 'retrace38', 'g8'] if key not in k[c]]
            L.append(f"- {key[0]}@{r['entry_price']:.2f} -> {key[1]}@{r['exit_price']:.2f} {r['reason']} {r['profit']:+,.0f} — also absent from: {', '.join(tags) if tags else 'none'}")
    L.append('')
    # event log from the python states/events of new
    ev = pd.read_csv(PY / 'events' / f'{DS}__new.csv')
    st = pd.read_csv(PY / 'states' / f'{DS}__new.csv')
    L.append('## Restriction episodes of the new strategy')
    L.append('')
    L.append('| armed (exit) | reason | loss | price return | loss exit | ref high | episode low | resolution | on | sessions |')
    L.append('|---|---|---:|---:|---:|---:|---:|---|---|---:|')
    for _, r in ev.iterrows():
        L.append(f"| {r['exit_date']} | {r['exit_reason']} | {r['loss']:,.0f} | {100 * r['price_return']:.2f}% | {r['loss_exit_price']:.4f} | {r['ref_high']:.4f} | {r['min_close_in_episode']:.4f} | {r['resolution']} | {r['resolution_date']} | {r['sessions_restricted']:.0f} |")
    L.append('')
    nr = st[st['reason'].str.startswith('loss_not_restricted')]
    L.append('Losing exits that did NOT arm a restriction (material-loss exemption):')
    L.append('')
    for _, r in nr.iterrows():
        L.append(f"- {r['date']}: {r['reason']} (close {r['close']:.4f})")
    L.append('')
    out_json['events'] = ev.to_dict(orient='records')
    out_json['exempt_losses'] = nr[['date', 'reason', 'close']].to_dict(orient='records')
    (OUT / 'vgt_2016_2025.md').write_text('\n'.join(L) + '\n')
    json.dump(out_json, open(OUT / 'vgt_2016_2025.json', 'w'), indent=1, default=str)
    print(f'wrote {OUT / "vgt_2016_2025.md"}')


if __name__ == '__main__':
    main()
