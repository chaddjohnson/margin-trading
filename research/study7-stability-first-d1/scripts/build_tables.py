#!/usr/bin/env python3
"""Study 7 report tables, generated only from sealed records (never typed by hand).

Usage (repository root): python3 research/study7-stability-first-d1/scripts/build_tables.py <part> [<part> …]
Parts: phaseB, phaseD, selection, final, phaseA. Each writes Markdown tables to research/study7-stability-first-d1/
results/tables/<part>-*.md and verifies the body hash of every record it reads. phaseA must not be built before
FROZEN_SELECTION.json is sealed (PROTOCOL.md §4.2 reading embargo); the script refuses otherwise.
"""
import glob
import hashlib
import json
import math
import os
import sys

ROOT = 'research/study7-stability-first-d1'
RES = f'{ROOT}/results'
OUT = f'{RES}/tables'
TRACKS = ['G', 'VG', 'VXR', 'VXRG', 'VC']
FOLDS = ['F19', 'F20', 'M', 'L']


def sealed(path):
    with open(path) as f:
        record = json.load(f)
    body = {k: v for k, v in record.items() if k != 'bodyHash'}
    digest = hashlib.sha256(json.dumps(body, separators=(',', ':'), ensure_ascii=False).encode()).hexdigest()
    if digest != record.get('bodyHash'):
        raise SystemExit(f'{path}: body hash does not verify')
    return record


def num(v):
    if v is None:
        return math.nan
    if isinstance(v, str):
        try:
            return float(v)
        except ValueError:
            return math.nan
    return float(v)


def usd(v, digits=0):
    v = num(v)
    if math.isnan(v):
        return '—'
    s = f'{abs(v):,.{digits}f}'
    return f'−${s}' if v < 0 else f'${s}'


def pct(v, digits=1):
    v = num(v)
    return '—' if math.isnan(v) else f'{100 * v:.{digits}f}%'


def table(headers, rows):
    out = ['| ' + ' | '.join(headers) + ' |', '|' + '|'.join('---:' if i else '---' for i in range(len(headers))) + '|']
    for row in rows:
        out.append('| ' + ' | '.join(str(c) for c in row) + ' |')
    return '\n'.join(out) + '\n'


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(f'{OUT}/{name}.md', 'w') as f:
        f.write(f'<!-- generated by scripts/build_tables.py from sealed records; do not edit -->\n{text}')


KEYS = ['targetPercentChange', 'trailingBuyPercentage', 'trailingStopPercentage', 'maximumHoldDays', 'tickWindowSize',
        'intradayLossBuffer', 'pullback', 'continuationWindow']


def short(grid):
    p = lambda v: f'{v / 10:.1f}'
    return (f"X {p(grid['targetPercentChange'])} Y {p(grid['trailingBuyPercentage'])} stop {p(grid['trailingStopPercentage'])} "
            f"hold {grid['maximumHoldDays']} L {grid['tickWindowSize']} buf {p(grid['intradayLossBuffer'])} "
            f"P {p(grid['pullback'])} W {grid['continuationWindow']}")


def books_text(books):
    order = ['VGT', 'XBI', 'XRT', 'KRE', 'GDX']
    if isinstance(books, str):
        parsed = {}
        for part in books.split('|'):
            sym, vals = part.split(':')
            parsed[sym] = dict(zip(KEYS, map(int, vals.split('/'))))
        books = parsed
    return '<br>'.join(f'{s}: {short(books[s])}' for s in order if s in books)


def search_records():
    out = {}
    for track in TRACKS + ['V']:
        for fold in FOLDS:
            path = f'{RES}/phaseB/{track}/{fold}/search.json'
            if os.path.exists(path):
                out[(track, fold)] = (path, sealed(path))
    return out


# ---------------------------------------------------------------- Phase B

def phase_b():
    recs = search_records()
    rows, islands, short_rows, ctrl_rows, sens_rows = [], [], [], [], []
    tot_points = tot_seconds = tot_archive = 0
    for (track, fold), (path, r) in sorted(recs.items(), key=lambda kv: (TRACKS.index(kv[0][0]) if kv[0][0] in TRACKS else 9, FOLDS.index(kv[0][1]))):
        c = r['counts']
        t = r['triggers']
        tot_points += r['stats']['points']
        tot_seconds += r['seconds']
        tot_archive += c['archive']
        rows.append([track, fold, f"{r['y']:.2f}", f"{r['floors']['lots']}/{r['floors']['episodes']}/{r['floors']['lotYears']}/{r['floors']['bookLots']}",
                     c['screen'], c['screenPlausible'], c['promoted'], c['archive'], c['r1Feasible'], f"{c['r2Feasible']}/{c['r2']}",
                     f"{c['r3Feasible']}/{c['r3']}", c['islandsRun'],
                     'fired' if any(x.get('fired') for x in t['T1']['log']) else 'no', 'fired' if t['T2'].get('fired') else 'no',
                     'fired' if t['T3'].get('fired') else 'no', 'yes' if r['noEligibleRegion'] else 'no',
                     f"{r['stats']['points']:,}", f"{r['stats']['cacheHits']:,}", f"{r['seconds'] / 60:.1f}"])
        for isl in r['islands']:
            islands.append([track, fold, isl['island'], isl['generations'], isl['newConfigs'], isl['duplicates'], isl['stop'], isl['feasible'],
                            f"{isl['unionHv']:.3e}", f"{isl['unionMinViolation']:.3f}" if isinstance(isl['unionMinViolation'], (int, float)) else isl['unionMinViolation']])
        for s in r['shortlist']:
            r3 = s['r3']
            sel = s['selection']['pooled']
            short_rows.append([track, fold, s['rank'], s['pick'], s['id'], books_text(s['books']),
                               usd(r3['centre']['perYear']), usd(r3['centre']['dd']), r3['centre']['lots'], r3['centre']['episodes'],
                               f"{pct(r3['nb']['share'])} ({r3['nb']['n']})", usd(r3['nb']['p90Dd']), usd(r3['nb']['medianPerYear']), usd(r3['nb']['p10PerYear']),
                               f"{pct(sel['nb']['share'])} ({sel['nb']['n']})", usd(sel['nb']['p90Dd']), usd(sel['nb']['medianPerYear']), usd(sel['nb']['p10PerYear']),
                               f"{num(sel['violation']):.3f}"])
        for key, cv in r['controls'].items():
            sel = cv['selection']['pooled']
            ctrl_rows.append([track, fold, key, usd(sel['centre']['perYear']), usd(sel['centre']['dd']), sel['centre']['lots'], sel['centre']['episodes'],
                              f"{pct(sel['nb']['share'])} ({sel['nb']['n']})", usd(sel['nb']['p90Dd']), usd(sel['nb']['medianPerYear']),
                              usd(sel['nb']['p10PerYear']), f"{num(sel['violation']):.3f}", ','.join(sorted(sel['parts'].keys())) or '—'])
        # §7.4 threshold sensitivity on the sealed rung-3 records
        fl = r['floors']
        y = r['y']
        for scale in (0.5, 1, 1.5):
            for cap in (0.65, 0.75, 0.85, None):
                n = 0
                for f in r['rung3']:
                    ce, nb = f['centre'], f['nb']
                    ok = (num(ce['dd']) < 35000 and num(nb['share']) >= 0.9 and num(nb['p90Dd']) < 35000
                          and ce['lots'] >= math.ceil(1.5 * y * scale) and ce['episodes'] >= math.ceil(0.5 * y * scale)
                          and ce['lotYears'] >= fl['lotYears'] and all(v >= math.ceil(0.4 * y * scale) for v in ce['bookLots'].values() if len(ce['bookLots']) > 1)
                          and num(nb['medianPerYear']) >= 10000 and num(nb['p10Net']) > 0 and num(ce['perCapitalYear']) >= 11000
                          and num(ce['net']) > 0 and num(ce['top1Share']) <= 0.25 and num(ce['exBestPerYear']) >= 5000
                          and (cap is None or num(ce['bestYearShare']) <= cap))
                    n += ok
                sens_rows.append([track, fold, f'×{scale}', 'none' if cap is None else pct(cap, 0), f"{n}/{len(r['rung3'])}"])
    write('phaseB-overview', table(['Track', 'Fold', 'y', 'floors lots/ep/yrs/book', 'screen', 'plausible', 'R1 promoted', 'archive (R1)', 'R1 feasible', 'R2 feas/n', 'R3 feas/n', 'islands', 'T1', 'T2', 'T3', 'no eligible region', 'fresh points', 'cache hits', 'minutes'], rows)
          + f"\nTotals: {len(recs)} track-fold jobs; {tot_archive:,} configurations evaluated at rung 1; {tot_points:,} fresh point evaluations; {tot_seconds / 3600:.2f} CPU-hours (single-thread per job).\n")
    write('phaseB-islands', table(['Track', 'Fold', 'island', 'generations', 'new', 'duplicates', 'stop', 'feasible (island)', 'union HV after', 'union min violation'], islands))
    write('phaseB-shortlists', table(['Track', 'Fold', '#', 'pick', 'id', 'parameters', 'R3 centre net/yr', 'R3 centre DD', 'lots', 'episodes', 'R3 share (n)', 'R3 p90 DD', 'R3 median/yr', 'R3 p10/yr', 'select share (n)', 'select p90 DD', 'select median/yr', 'select p10/yr', 'select violation'], short_rows))
    write('phaseB-controls', table(['Track', 'Fold', 'control', 'centre net/yr', 'centre DD', 'lots', 'episodes', 'select share (n)', 'select p90 DD', 'select median/yr', 'select p10/yr', 'violation', 'failed constraints'], ctrl_rows))
    write('phaseB-threshold-sensitivity', table(['Track', 'Fold', 'activity floors', 'best-year cap', 'rung-3 feasible'], sens_rows))
    print(f'phaseB: {len(recs)} records')


# ---------------------------------------------------------------- Phase D

def phase_d():
    rows, ctrl, pbo_rows, seq_rows = [], [], [], []
    for track in TRACKS:
        for fold in FOLDS:
            path = f'{RES}/phaseD/{track}/{fold}/validation.json'
            if not os.path.exists(path):
                continue
            r = sealed(path)
            for c in r['candidates']:
                e, q = c['evidence'], c['qualification']
                d = e['decisive']
                rows.append([track, fold, c['rank'], c['pick'], c['id'], 'yes' if q['qualified'] else 'no', ','.join(q['failed']) or '—', 'yes' if q['marginal'] else '',
                             usd(e['centre']['record']['net']), usd(e['centre']['record']['dd']), e['centre']['record']['lots'],
                             f"{pct(d['nb']['share'])} ({d['nb']['n']})", pct(d['wilsonLower']), usd(d['nb']['p90Dd']), usd(d['nb']['medianPerYear']), usd(d['nb']['p10PerYear']),
                             usd((d.get('test') or {}).get('median')), pct(e['alternates']['inbox']['nb']['share']), pct((e['alternates'].get('d8') or {}).get('nb', {}).get('share')),
                             pct(e['alternates']['wide']['nb']['share'])])
                s = e.get('sequence')
                if s:
                    seq_rows.append([track, fold, c['id'], s['centreLots'], f"{num(s['medianKeptShare']):.2f}", f"{num(s['medianJaccard']):.2f}", s['medianDisplaced'], s['medianAdded'],
                                     usd(s['medianAbsDeltaPool']), usd(s['medianAbsInteraction']), 'yes' if s['sequenceDependent'] else 'no'])
            for key, cv in r['controls'].items():
                e, q = cv['evidence'], cv['qualification']
                d = e['decisive']
                ctrl.append([track, fold, key, usd(e['centre']['record']['net']), usd(e['centre']['record']['dd']), f"{pct(d['nb']['share'])} ({d['nb']['n']})", usd(d['nb']['p90Dd']),
                             usd(d['nb']['medianPerYear']), usd((d.get('test') or {}).get('median')), ','.join(q['failed']) or '—'])
            p = r['pbo']
            pbo_rows.append([track, fold, p.get('configs'), len(p.get('blocks', [])), f"{num(p.get('pbo')):.3f}", f"{num(r['decay']['spearman']):.2f}"])
    write('phaseD-candidates', table(['Track', 'Fold', '#', 'pick', 'id', 'qualified', 'failed', 'marginal', 'centre net (run)', 'centre DD', 'lots', 'confirm share (n)', 'Wilson LB', 'p90 DD', 'median/yr', 'p10/yr', 'test median', 'in-box share', 'k=8 share', '1.5r share'], rows))
    write('phaseD-controls', table(['Track', 'Fold', 'control', 'centre net (run)', 'centre DD', 'confirm share (n)', 'p90 DD', 'median/yr', 'test median', 'failed'], ctrl))
    write('phaseD-pbo', table(['Track', 'Fold', 'configs', 'half-year blocks', 'PBO', 'Spearman(train robust, test median)'], pbo_rows))
    write('phaseD-sequence', table(['Track', 'Fold', 'id', 'centre lots', 'median kept share', 'median Jaccard', 'median displaced', 'median added', 'median |Δ pool|', 'median |interaction|', 'sequence-dependent'], seq_rows))
    print(f'phaseD: {len(rows)} candidates')


def selection():
    path = f'{ROOT}/FROZEN_SELECTION.json'
    r = sealed(path)
    roles = [[x['track'], x['path'], x['role'], x.get('id') or '(none qualified)'] for x in r['roles']]
    ranked = [[x['rank'], x['class'], x['tier'], x['track'], x['path'], x['role'], x['id'], usd(x['robustPerYear']), usd(x['b1RobustPerYear']), 'yes' if x['marginal'] else ''] for x in r['ranked']]
    write('selection-roles', table(['Track', 'Path', 'Role', 'Holder'], roles))
    write('selection-ranked', table(['Rank', 'Class', 'Tier', 'Track', 'Path', 'Role', 'id', 'confirm robust/yr (→2023)', 'B1 robust/yr', 'marginal'], ranked) if ranked else 'No role holder (no candidate qualified).\n')
    print(f'selection: {len(r["ranked"])} role holders')


def final():
    r = sealed(f'{RES}/final/final.json')
    rows = []
    for n in r['nominations']:
        e = n['evidence']
        d = e['decisive']
        rows.append([n['rank'], n['class'], n['tier'], n['track'], n['path'], n['role'], n['id'], 'NOMINATED' if n['nominated'] else 'blocked: ' + ','.join(n['blocked']), 'yes' if n['marginal'] else '',
                     usd(e['centre']['record']['net']), usd(e['centre']['record']['dd']), usd(e['centre']['record']['periods'].get('FX')),
                     f"{pct(d['nb']['share'])} ({d['nb']['n']})", usd(d['nb']['p90Dd']), usd(d['nb']['medianPerYear'])])
    ctrl = []
    for key, c in r['controls'].items():
        e = c['evidence']
        d = e['decisive']
        rec = e['centre']['record']
        ctrl.append([key, usd(rec['net']), usd(rec['realized']), usd(rec['unrealized']), usd(rec['dd']), usd(rec['ddDaily']), rec['lots'], usd(rec['periods'].get('FX')),
                     f"{pct(d['nb']['share'])} ({d['nb']['n']})", usd(d['nb']['p90Dd']), usd(d['nb']['medianNet']), usd(d['nb']['p10Net']), pct(e['alternates']['inbox']['nb']['share'])])
    write('final-nominations', table(['Rank', 'Class', 'Tier', 'Track', 'Path', 'Role', 'id', 'final flag', 'marginal', 'FULL net', 'FULL minute DD', 'FX net', 'final share (n)', 'p90 DD', 'median/yr'], rows) if rows else 'No role holder reached the final door.\n')
    write('final-controls', table(['Control', 'FULL net', 'realized', 'unrealized', 'minute DD', 'daily DD', 'lots', 'FX net', 'final share (n)', 'p90 DD', 'median net', 'p10 net', 'in-box share'], ctrl))
    print('final: done')


def phase_a():
    if not os.path.exists(f'{ROOT}/FROZEN_SELECTION.json'):
        raise SystemExit('Phase A reading embargo: FROZEN_SELECTION.json is not sealed yet')
    rows, dims, dec = [], [], []
    for path in sorted(glob.glob(f'{RES}/phaseA/*-W*.json')):
        if path.endswith('baseline_manifest.json'):
            continue
        r = sealed(path)
        key, window = r['key'], r['window']
        c = r['centre']
        sets = r['sets']
        j1 = sets['joint#1']['summary']
        pooled = [sets[f'joint#{i}']['summary'] for i in range(1, 6)]
        rows.append([key, window, usd(c['net']), usd(c['realized']), usd(c['unrealized']), usd(c['dd']), usd(c['ddDaily']), c['lots'], c['episodes'], usd(c['heldDays'] and c['net'] / (c['heldDays'] / 365)),
                     f"{pct(j1['share'])} ({j1['n']})", ' / '.join(pct(p['share'], 0) for p in pooled), usd(j1['p90Dd']), usd(j1['medianNet']), usd(j1['p10Net']),
                     pct(sets['joint-inbox#1']['summary']['share']), pct(sets['joint-half#1']['summary']['share']), pct(sets['joint-wide#1']['summary']['share'])])
        d = [key, window]
        for name in ('joint#1', 'd8#1', 'd16#1', 'norm#1'):
            s = sets.get(name)
            d.append(f"{pct(s['summary']['share'])} / {usd(s['summary']['p90Dd'])}" if s else '—')
        books = [k for k in sets if k.startswith('book-') and k.endswith('#1')]
        d.append('; '.join(f"{k[5:-2]} {pct(sets[k]['summary']['share'], 0)}" for k in books) or '—')
        dims.append(d)
        if r.get('decomposition'):
            x = r['decomposition']
            dec.append([key, window, x['points'], x['breaches'], '; '.join(f"{s} {pct(v, 0)}" for s, v in x['importance'].items()),
                        usd(x['ownVsFunding']['medianAbsDeltaPool']), usd(x['ownVsFunding']['medianAbsInteraction']),
                        (f"{x['sequence']['medianKeptShare']:.2f} / {x['sequence']['medianJaccard']:.2f}" if x.get('sequence') else '—')])
    write('phaseA-centres', table(['Config', 'Window', 'net', 'realized', 'unrealized', 'minute DD', 'daily DD', 'lots', 'episodes', 'net per capital-yr', 'joint N1 rep1 share (n)', 'reps 1–5 share', 'p90 DD', 'median net', 'p10 net', 'in-box', '0.5r', '1.5r'], rows))
    write('phaseA-dimension', table(['Config', 'Window', 'joint (share / p90)', 'count-matched k=8', 'k=16', 'norm-matched', 'per-book shares'], dims))
    write('phaseA-decomposition', table(['Config', 'Window', 'points', 'breaches', 'book importance (breaches removed by reset)', 'median |Δ pool net|', 'median |interaction|', 'median kept share / Jaccard (rep 1)'], dec))
    print(f'phaseA: {len(rows)} records')


if __name__ == '__main__':
    parts = {'phaseB': phase_b, 'phaseD': phase_d, 'selection': selection, 'final': final, 'phaseA': phase_a}
    for part in sys.argv[1:]:
        parts[part]()
