#!/usr/bin/env python3
"""Builds the study's root reports from report_templates/*.md by inlining {{table:<name>}} from results/tables/
(generated from the sealed records by scripts/report_tables.py). Edit the templates, never the generated files.
Usage (repository root): python3 research/study5-gdx-d1-b5-three-etf-2026-10/scripts/build_reports.py"""
import os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
for name in sorted(os.listdir(os.path.join(ROOT, 'report_templates'))):
    text = open(os.path.join(ROOT, 'report_templates', name)).read()
    def inline(match):
        return open(os.path.join(ROOT, 'results', 'tables', match.group(1))).read().rstrip('\n')
    text = re.sub(r'\{\{table:([A-Za-z0-9_.-]+)\}\}', inline, text)
    banner = f'<!-- generated by scripts/build_reports.py from report_templates/{name}; edit the template -->\n'
    open(os.path.join(ROOT, name), 'w').write(banner + text)
    print('built', name)
