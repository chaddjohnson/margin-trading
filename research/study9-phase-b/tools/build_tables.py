def execution():
    # per-ETF participation and fill mechanics from the sealed per-lot diagnostics ledger, plus the five worst
    # drawdown episodes, overnight gaps and per-book effects (report-only; nothing here feeds any gate)
    r = sealed(f'{RES}/diagnostics/diagnostics.json')
    mins = r['medianMinuteDollars']
    part, epis = [], []
    for x in r['rows']:
        for s in engine_order(list(x['liquidity']['byEtf'])):
            lots = [l for l in x['lots'] if l['symbol'] == s]
            fills = [v for l in lots for v in (l['entryBarDollars'], l['exitBarDollars']) if v is not None]
            feasible = sorted(min(100000.0, 0.1 * v) for v in fills)
            ex = [l['exitExecution'] for l in lots]
            part.append([x['who'], s, len(lots), len(fills), f"{100000 / mins[s]['training']:.2f}× / {100000 / mins[s]['test']:.2f}×",
                         sum(v < 100000 for v in fills), sum(v < 1000000 for v in fills),
                         usd(feasible[len(feasible) // 2]) if feasible else '—', usd(feasible[len(feasible) // 10]) if feasible else '—',
                         ex.count('opening trade'), ex.count('minute open through stop'), sum(l['exitReason'] == 'trailing stop gap' for l in lots),
                         usd(sum(l['gapLossBeyondStop'] for l in lots)), sum(l['sparseHeldSessions'] > 0 for l in lots), sum(l['sparseHeldSessions'] for l in lots),
                         sum(l['inTest'] for l in lots)])
        k = x['risk']
        epis.append([x['who'], usd(k['dd']), usd(k['ddDaily']),
                     '<br>'.join(f"{e['depth']:,.0f}: peak {e['peak']} → trough {e['trough']} → {'recovered ' + e['recovery'] if (e.get('recovery') or '')[:1].isdigit() else 'not recovered by 2026-10-29'}; {e['lots']} lots ("
                                 + ', '.join(f"{a} {usd(b)}" for a, b in e['bySymbol'].items()) + ')' for e in k['episodes'][:5]),
                     '; '.join(f"{g['symbol']} {g['date']} {usd(g['gap'])}" for g in k['worstOvernightGaps'][:5]),
                     '; '.join(f"{a} {usd(b['net'])} ({b['lots']} lots, worst episode {usd(b['worstEpisodeContribution'])})" for a, b in k['perBook'].items())])
    agg = {}
    for x in r['rows']:
        if x['kind'] != 'holder':
            continue
        for s in x['liquidity']['byEtf']:
            lots = [l for l in x['lots'] if l['symbol'] == s]
            fills = [v for l in lots for v in (l['entryBarDollars'], l['exitBarDollars']) if v is not None]
            if not fills:
                continue
            a = agg.setdefault(s, {'holders': 0, 'below100': [], 'below1m': [], 'feasible': [], 'lots': 0, 'sparseLots': 0, 'sparse': 0, 'gaps': 0, 'beyond': 0.0})
            a['holders'] += 1
            a['below100'].append(sum(v < 100000 for v in fills) / len(fills))
            a['below1m'].append(sum(v < 1000000 for v in fills) / len(fills))
            f = sorted(min(100000.0, 0.1 * v) for v in fills)
            a['feasible'].append(f[len(f) // 2])
            a['lots'] += len(lots)
            a['sparseLots'] += sum(l['sparseHeldSessions'] > 0 for l in lots)
            a['sparse'] += sum(l['sparseHeldSessions'] for l in lots)
            a['gaps'] += sum(l['exitReason'] == 'trailing stop gap' for l in lots)
            a['beyond'] += sum(l['gapLossBeyondStop'] for l in lots)
    summary = [[s, a['holders'], f"${mins[s]['training']:,.0f} / ${mins[s]['test']:,.0f}", f"{pct(min(a['below100']))}–{pct(max(a['below100']))}",
                f"{pct(min(a['below1m']))}–{pct(max(a['below1m']))}", f"{usd(min(a['feasible']))}–{usd(max(a['feasible']))}", a['lots'],
                f"{a['sparseLots']} ({pct(a['sparseLots'] / a['lots'])})", a['sparse'], a['gaps'], usd(a['beyond'] / a['gaps']) if a['gaps'] else '—']
               for s, a in sorted(agg.items(), key=lambda kv: mins[kv[0]]['training'])]
    write('diag-participation', 'Per funded lot of the whole run (2016-01-04 → 2026-10-29, 5 bps, 11%). The engine fills the whole $100k at the '
          'first printed trade after the decision (no partial fills, queue or impact); a fill bar is that minute bar (price × volume). '
          '"$100k ÷ median minute $" uses all regular-session minutes of the training / test window. "Feasible at 10%" is min($100k, 10% of '
          'the fill bar\'s dollar volume): what a 10% participation cap would have allowed on that one bar (report-only; not simulated). '
          '"Opening-trade exits" filled at a session\'s first trade through the stop; "minute open through stop" at an intraday minute that '
          'opened through it. A sparse session has fewer than 300 regular-session minute bars.\n\n'
          + '**Per ETF across the 32 F24 role holders** (lot counts add over holders, which share many lots; ranges are over the '
          'holders that hold the ETF):\n\n'
          + table(['ETF', 'holders', 'median minute $ (train / test)', 'fills on a bar < $100k', 'fills on a bar < $1M', 'median feasible at 10%',
                   'lots', 'lots holding sparse sessions', 'sparse sessions held', 'gapped stops', 'mean loss beyond stop per gap'], summary)
          + '\n**Per configuration and ETF:**\n\n'
          + table(['Configuration', 'ETF', 'lots', 'fills', '$100k ÷ median minute $ (train / test)', 'fill bar < $100k', 'fill bar < $1M',
                   'median feasible at 10%', 'p10 feasible at 10%', 'opening-trade exits', 'minute open through stop', 'gapped stops',
                   'loss beyond stop', 'lots holding sparse sessions', 'sparse sessions held', 'test-window lots'], part))
    write('diag-episodes', 'The five worst cumulative minute-drawdown episodes (peak → trough → recovery, New York time; lots and the '
          'P&L of each book during the episode), the five worst overnight gaps on held lots and the per-book net and worst-episode '
          'contribution, whole run 2016-01-04 → 2026-10-29.\n\n'
          + table(['Configuration', 'run minute DD', 'run daily DD', 'five worst episodes', 'worst overnight gaps', 'per book'], epis))
    t = sealed(f'{RES}/test/F24/test.json')
    keys = ['cost0', 'cost2', 'cost10', 'cost20', 'rate8', 'rate14', 'nextOpen', 'slip10', 'slip25', 'arm2017-12-15', 'arm2018-06-15']
    labels = ['0 bps', '2 bps', '10 bps', '20 bps', '8%', '14%', 'next-open stop', '+10 bps stop slip', '+25 bps stop slip', 'arm 2017-12-15', 'arm 2018-06-15']
    def srow(name, status, x):
        sv = x['deep']['sensitivities']
        return [name, status, f"{usd(x['deep']['test']['net'])} / {usd(x['evidence']['centre']['record']['dd'])}",
                *[f"{usd(sv[k]['test'])} / {usd(sv[k]['dd'])}" for k in keys], 'pass' if x['gates']['gates'].get('T4') else 'FAIL' if 'gates' in x else '—']
