def tracks():
    """Per track: the F24 profit / robust / balanced / extra holders beside VG #2, VG #1, B1 and B5, on the F24 test run."""
    tests = test_records()
    r = tests['F24']
    rows = []

    def row(label, status, e, d):
        rec, nb = e['centre']['record'], e['decisive']['nb']
        t, p = d['test'], rec['periods']
        tst = e['decisive'].get('test') or {}
        return [label, status, usd(rec['net']), usd(t['net']), usd(t.get('y2025')), usd(t.get('y2026ytd')), usd(rec['dd']), usd(rec['ddDaily']),
                f"{pct(nb['share'])} ({nb['n']})", pct(e['decisive'].get('wilsonLower')), usd(nb['p90Dd']), usd(nb['medianNet']), usd(nb['p10Net']),
                usd(tst.get('median')), usd(tst.get('p10')), f"{rec['lots']}/{rec['episodes']}", f"{t['newLots']}/{t['newEpisodes']}",
                usd(p.get('2020')), usd(p.get('2022')), usd(p.get('2024'))]

