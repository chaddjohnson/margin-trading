// Priority 4 report-only ANNUAL / TRAIN / INTERVAL table (zero evaluations): per fold, the pooled primaries, the EXP
// primary's all-OFF projection, the benchmarks and (C24) the informed primaries — training-door centre (qualification
// record), calendar-year marked net of the continuous run and the interval P&L / reset DD (interval / validation record).
//   cd research/vg-l0-staged-stop && node tools/…/annual.ts > reports/tables/annual-train-validate.md (run from the study dir)
import fs from 'node:fs';
const usd = (v) => (v == null ? '—' : `${v < 0 ? '−' : ''}$${Math.abs(Math.round(v)).toLocaleString('en-US')}`);
console.log('<!-- generated by tools/vg-l0-staged-stop/annual.ts from the sealed qualification and interval / validation records (no evaluation); years = change of the marked net of the continuous run within each calendar year -->');
for (const c of ['C19', 'C21', 'C24']) {
  const r = JSON.parse(fs.readFileSync(`results/intervals/${c}.json`, 'utf8'));
  const q = new Map(JSON.parse(fs.readFileSync(`results/qualification/${c}.json`, 'utf8')).evidence.map((e) => [e.id, e]));
  const expPrimary = r.rows.find((y) => y.roles.some((o) => o.kind.includes('pooled P0 primary') && o.arm === 'EXP'));
  const expLane = expPrimary.roles.find((o) => o.lane)?.lane;
  const subj = r.rows.filter(
    (x) =>
      x.roles.some((o) => /pooled P0 primary|benchmark|informed I\d primary|report decomposition/.test(o.kind)) ||
      x.roles.some((o) => o.kind === 'representative all-OFF projection' && o.arm === 'EXP' && o.lane === expLane)
  );
  const yrs = Object.keys(subj[0].years);
  console.log(`\n### ${c} interval ${r.interval.join(' … ')}\n`);
  console.log(`| Subject | pattern | training-door centre net | training DD | qualified | ${yrs.join(' | ')} | interval P&L | interval DD (reset) |`);
  console.log(`|${Array(7 + yrs.length).fill('---').join('|')}|`);
  for (const x of subj) {
    const e = q.get(x.id);
    const isOffProj = x.roles.some((o) => o.kind === 'representative all-OFF projection' && o.lane === expLane);
    const name = x.roles.some((o) => o.kind === 'benchmark') ? x.label.replace(/^EXP .*$/, x.label) : x.label + (isOffProj ? ' (EXP primary all-OFF projection)' : '');
    console.log(
      `| ${name} | ${x.stagedPattern} | ${usd(e?.centre?.net)} | ${usd(e?.centre?.dd)} | ${e ? (e.qualified ? 'yes' : 'no') : '—'} | ${yrs.map((y) => usd(x.years[y])).join(' | ')} | ${usd(x.sliceNet)} | ${usd(x.sliceDd)} |`
    );
  }
}
