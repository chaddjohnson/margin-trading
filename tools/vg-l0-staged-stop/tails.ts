// Priority 4 report-only RISK-TAIL TABLES (PROTOCOL.md §13) — zero evaluations: reads the sealed qualification,
// selection and decomposition records only, written after the freeze; it selects nothing. Per cutoff, for the named
// subjects (the benchmarks, both arms' pooled P0 primaries and the EXP primary's all-OFF projection, at C24 the informed
// types' pooled primaries and the decomposition rows on D24): the training-door centre, the confirmation family's
// (3 × 128) marked-DD tail (p90, p95, worst-10 % mean, worst), breach share above $35,000 with its Wilson 95 % interval,
// the p10 / worst net; the risk envelope (trade principal loss and banked-capital DD, marked and liquidation basis) at the
// centre and across the confirmation family; and the seven stresses (net and marked DD).
//   node --no-maglev --experimental-transform-types tools/vg-l0-staged-stop/tails.ts --out <md> [--json <json>]
import fs from 'node:fs';
import { cutoffKeys } from '../../src/vg-l0-staged-stop/context.ts';
import { selectionFile } from '../../src/vg-l0-staged-stop/doors.ts';
import { decompositionFile, qualificationFile } from '../../src/vg-l0-staged-stop/stages.ts';
import { readSealed } from '../../src/vg-l0-staged-stop/records.ts';

const args = process.argv.slice(2);
const opt = (k: string) => (args.includes(`--${k}`) ? args[args.indexOf(`--${k}`) + 1]! : undefined);
const out = opt('out');

if (!out) throw new Error('--out <md> [--json <json>]');

type Dist = { median: number; p90: number; p95: number; worst: number; worst10Mean: number };
type Ev = {
  id: string;
  label: string;
  stagedPattern: string;
  qualified: boolean;
  origins: { arm: string; role: string }[];
  centre: { net: number; dd: number; lots: number };
  confirmTail: {
    p90Dd: number;
    p95Dd: number;
    worst10Mean: number;
    worstDd: number;
    breachShare: number;
    breachInterval: [number, number];
    p10Net: number;
    worstNet: number;
    n: number;
  };
  envelope: {
    centre: {
      bankedDdMarked: number;
      bankedDdLiquidation: number;
      principalLossMarked: number;
      principalLossLiquidation: number;
    };
    confirm: { principalLoss: { marked: Dist; liquidation: Dist }; bankedDd: { marked: Dist; liquidation: Dist } };
  };
  stress: Record<string, { net: number; dd: number }>;
};
type Pooled = { primary: { id: string; label: string } | null };
type Sel = {
  pooled: Record<'CTRL' | 'EXP', Pooled>;
  laneValues: { EXP: { representative: { id: string } | null; offProjection: { id: string } | null }[] };
  informed?: { type: string; pooled: Partial<Record<'CTRL' | 'EXP', Pooled>> }[] | null;
};

const usd = (v: number | null | undefined) =>
  v === null || v === undefined || Number.isNaN(v)
    ? '—'
    : `${v < 0 ? '−' : ''}$${Math.abs(Math.round(v)).toLocaleString('en-US')}`;
const pct = (v: number, d = 1) => `${(100 * v).toFixed(d)} %`;
const cell = (v: string) => v.replaceAll(' | ', ' · ').replaceAll('|', '/');
const table = (head: string[], rows: string[][]) =>
  [
    `| ${head.join(' | ')} |`,
    `|${head.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)
  ].join('\n');
const sections: string[] = [
  `<!-- generated by tools/vg-l0-staged-stop/tails.ts from the sealed qualification / selection / decomposition records (no evaluation) -->`,
  ''
];
const json: Record<string, unknown> = {};

const render = (title: string, subjects: { role: string; e: Ev }[]) => {
  const name = (s: { role: string; e: Ev }) => `${s.e.label} (${s.role})`;
  const stresses = [...new Set(subjects.flatMap((s) => Object.keys(s.e.stress ?? {})))];

  sections.push(
    `## ${title}`,
    '',
    '### Training-door centre and the confirmation family (3 × 128): marked-DD tail, breaches above $35,000, net tail',
    '',
    table(
      [
        'Subject',
        'pattern',
        'qualified',
        'centre net',
        'centre DD',
        'p90 DD',
        'p95 DD',
        'worst-10 % mean DD',
        'worst DD',
        'breach share (Wilson 95 %)',
        'p10 net',
        'worst net'
      ],
      subjects.map((s) => {
        const t = s.e.confirmTail;

        return [
          name(s),
          s.e.stagedPattern,
          s.e.qualified ? 'yes' : 'no',
          usd(s.e.centre.net),
          usd(s.e.centre.dd),
          usd(t.p90Dd),
          usd(t.p95Dd),
          usd(t.worst10Mean),
          usd(t.worstDd),
          `${pct(t.breachShare)} (${pct(t.breachInterval[0])}–${pct(t.breachInterval[1])})`,
          usd(t.p10Net),
          usd(t.worstNet)
        ];
      })
    ),
    '',
    '### Risk envelope: trade principal loss (PL) and banked-capital DD (BD); centre and confirmation family p90 / p95 / worst',
    '',
    table(
      [
        'Subject',
        'PL marked',
        'PL liq.',
        'BD marked',
        'BD liq.',
        'PL liq. p90 / p95 / worst',
        'BD liq. p90 / p95 / worst'
      ],
      subjects.map((s) => {
        const c = s.e.envelope.centre;
        const pl = s.e.envelope.confirm.principalLoss.liquidation;
        const bd = s.e.envelope.confirm.bankedDd.liquidation;

        return [
          name(s),
          usd(c.principalLossMarked),
          usd(c.principalLossLiquidation),
          usd(c.bankedDdMarked),
          usd(c.bankedDdLiquidation),
          `${usd(pl.p90)} / ${usd(pl.p95)} / ${usd(pl.worst)}`,
          `${usd(bd.p90)} / ${usd(bd.p95)} / ${usd(bd.worst)}`
        ];
      })
    ),
    '',
    '### Stresses (net; marked DD)',
    '',
    table(
      ['Subject', ...stresses],
      subjects.map((s) => [
        name(s),
        ...stresses.map((k) => (s.e.stress?.[k] ? `${usd(s.e.stress[k]!.net)} (${usd(s.e.stress[k]!.dd)})` : '—'))
      ])
    ),
    ''
  );
  json[title] = subjects.map((s) => ({
    role: s.role,
    label: s.e.label,
    id: s.e.id,
    stagedPattern: s.e.stagedPattern,
    qualified: s.e.qualified,
    centre: s.e.centre,
    confirmTail: s.e.confirmTail,
    envelope: s.e.envelope,
    stress: s.e.stress
  }));
};

for (const c of cutoffKeys) {
  if (!fs.existsSync(qualificationFile(c)) || !fs.existsSync(selectionFile(c))) continue;

  const ev = new Map(readSealed<{ evidence: Ev[] }>(qualificationFile(c)).evidence.map((e) => [e.id, e]));
  const sel = readSealed<Sel>(selectionFile(c));
  const subjects: { role: string; e: Ev }[] = [];
  const add = (role: string, id: string | undefined | null) => {
    const e = id ? ev.get(id) : undefined;

    if (e && !subjects.some((s) => s.e.id === e.id && s.role === role)) subjects.push({ role, e });
  };

  // a benchmark's evidence id can coincide with an informed all-OFF projection (same configuration): name it by the
  // benchmark origin, not by the first origin's label
  for (const e of ev.values()) {
    const b = e.origins.find((o) => o.role === 'benchmark') as { label?: string } | undefined;

    if (b) subjects.push({ role: 'benchmark', e: { ...e, label: b.label ?? e.label } });
  }
  add('CTRL pooled P0 primary', sel.pooled.CTRL.primary?.id);
  add('EXP pooled P0 primary', sel.pooled.EXP.primary?.id);

  const lv = sel.laneValues.EXP.find((v) => v.representative?.id === sel.pooled.EXP.primary?.id);

  add('EXP primary all-OFF projection', lv?.offProjection?.id);
  for (const t of sel.informed ?? []) {
    add(`informed ${t.type} CTRL primary`, t.pooled.CTRL?.primary?.id);
    add(`informed ${t.type} EXP primary`, t.pooled.EXP?.primary?.id);
  }
  render(`${c} (training door)`, subjects);
}

if (fs.existsSync(decompositionFile)) {
  const d = readSealed<{ rows: { label: string; kind: string; id: string }[]; evidence: Ev[] }>(decompositionFile);

  render(
    'C24 decomposition rows (D24)',
    d.rows.map((r) => ({ role: r.kind, e: { ...d.evidence.find((x) => x.id === r.id)!, label: r.label } }))
  );
}

fs.writeFileSync(out, `${sections.join('\n')}\n`);
if (opt('json')) fs.writeFileSync(opt('json')!, `${JSON.stringify(json, null, 1)}\n`);
console.log(`tails: ${Object.keys(json).length} sections → ${out}`);
