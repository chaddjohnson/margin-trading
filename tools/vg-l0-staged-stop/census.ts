// Priority 4 report-only FULL-POPULATION CENSUS (PROTOCOL.md §13) — zero evaluations: reads the sealed search, extension
// and qualification records only, written after the freeze; it selects nothing. Per cutoff and arm, over every lane's
// final result (the extension block's result replaces a re-run lane's base result, as in the selection):
//   population   screened / plausible / promoted / rung-1 centres / feasible centres, by staged pattern (`st:` class)
//   best centres the patterns of each lane's ten best centres by net (ON = a staged identity `st1-…`) and of its shortlist
//   qualification the union's members, qualified members and the best qualified centre net by staged pattern
//   node --no-maglev --experimental-transform-types tools/vg-l0-staged-stop/census.ts --out <md>
import fs from 'node:fs';
import { armKeys, cutoffKeys } from '../../src/vg-l0-staged-stop/context.ts';
import { searchFile } from '../../src/vg-l0-staged-stop/doors.ts';
import { extendFile, qualificationFile } from '../../src/vg-l0-staged-stop/stages.ts';
import { readSealed } from '../../src/vg-l0-staged-stop/records.ts';

const args = process.argv.slice(2);
const out = args.includes('--out') ? args[args.indexOf('--out') + 1]! : undefined;

if (!out) throw new Error('--out <md>');

type Cls = { screened: number; plausible: number; promoted: number; centres: number; feasible: number };
type Lane = {
  key: string;
  byClass: Record<string, Cls>;
  topByNet: { id: string; feasible: boolean }[];
  shortlist: { id: string }[];
};
type Rec = { lanes: Record<string, Lane[]> };

const usd = (v: number) =>
  Number.isFinite(v) ? `${v < 0 ? '−' : ''}$${Math.abs(Math.round(v)).toLocaleString('en-US')}` : '—';
const n = (v: number) => v.toLocaleString('en-US');
const table = (head: string[], rows: string[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join(
    '\n'
  );
const patternOf = (cls: string) => cls.match(/\|st:([^|]+)$/)?.[1] ?? 'off';
const isOn = (id: string) => id.startsWith('st1-');
const text: string[] = [
  '<!-- generated by tools/vg-l0-staged-stop/census.ts from the sealed search / extension / qualification records (no evaluation) -->',
  ''
];

for (const c of cutoffKeys) {
  if (!fs.existsSync(searchFile(c))) continue;

  const base = readSealed<Rec>(searchFile(c));
  const ext = fs.existsSync(extendFile(c)) ? readSealed<Partial<Rec>>(extendFile(c)) : null;
  const finalLanes = (a: string) => base.lanes[a]!.map((l) => ext?.lanes?.[a]?.find((x) => x.key === l.key) ?? l);

  text.push(`## ${c}`, '');

  const popRows: string[][] = [];
  const bestRows: string[][] = [];

  for (const a of armKeys) {
    const lanes = finalLanes(a);
    const agg: Record<string, Cls> = {};

    for (const l of lanes)
      for (const [k, v] of Object.entries(l.byClass)) {
        const p = patternOf(k);

        agg[p] ??= { screened: 0, plausible: 0, promoted: 0, centres: 0, feasible: 0 };
        for (const f of ['screened', 'plausible', 'promoted', 'centres', 'feasible'] as const) agg[p]![f] += v[f] ?? 0;
      }

    const tot = Object.values(agg).reduce((s, v) => s + v.centres, 0);

    for (const [p, v] of Object.entries(agg).sort((x, y) => y[1].centres - x[1].centres))
      popRows.push([
        a,
        p,
        n(v.screened),
        n(v.plausible),
        n(v.promoted),
        n(v.centres),
        `${((100 * v.centres) / Math.max(1, tot)).toFixed(1)} %`,
        n(v.feasible),
        v.centres ? `${((100 * v.feasible) / v.centres).toFixed(1)} %` : '—'
      ]);

    const top = lanes.flatMap((l) => l.topByNet.slice(0, 10));
    const topFeas = top.filter((t) => t.feasible);
    const short = lanes.flatMap((l) => l.shortlist);
    const best = lanes.map((l) => l.topByNet[0]).filter((t): t is { id: string; feasible: boolean } => !!t);

    bestRows.push([
      a,
      String(lanes.length),
      `${top.filter((t) => isOn(t.id)).length} / ${top.length}`,
      `${topFeas.filter((t) => isOn(t.id)).length} / ${topFeas.length}`,
      `${best.filter((t) => isOn(t.id)).length} / ${best.length}`,
      `${short.filter((t) => isOn(t.id)).length} / ${short.length}`
    ]);
  }
  text.push(
    '### Search population by staged pattern (every lane, final result)',
    '',
    table(
      [
        'Arm',
        'staged pattern',
        'screened',
        'plausible',
        'promoted',
        'rung-1 centres',
        'share of centres',
        'feasible centres',
        'feasible share'
      ],
      popRows
    ),
    '',
    '### Best centres using S1 (ON / all)',
    '',
    table(
      [
        'Arm',
        'lanes',
        "lanes' ten best centres by net",
        '… of which feasible',
        "each lane's best centre",
        'shortlisted members'
      ],
      bestRows
    ),
    ''
  );

  if (fs.existsSync(qualificationFile(c))) {
    const q = readSealed<{
      evidence: {
        stagedPattern: string;
        qualified: boolean;
        centre: { net: number };
        origins: { arm: string; role: string }[];
      }[];
    }>(qualificationFile(c));
    const groups: Record<string, { members: number; qualified: number; best: number }> = {};

    for (const e of q.evidence) {
      const arm = [...new Set(e.origins.map((o) => o.arm))].join('+');
      const k = `${arm}|${e.stagedPattern}`;

      groups[k] ??= { members: 0, qualified: 0, best: -Infinity };
      groups[k]!.members += 1;
      if (e.qualified) {
        groups[k]!.qualified += 1;
        groups[k]!.best = Math.max(groups[k]!.best, e.centre.net);
      }
    }
    text.push(
      '### Qualification union by origin arm and staged pattern',
      '',
      table(
        ['Origin', 'staged pattern', 'members', 'qualified', 'best qualified centre net'],
        Object.entries(groups)
          .sort((x, y) => x[0].localeCompare(y[0]))
          .map(([k, v]) => [...k.split('|'), String(v.members), String(v.qualified), usd(v.best)])
      ),
      ''
    );
  }
}

fs.writeFileSync(out, `${text.join('\n')}\n`);
console.log(`census → ${out}`);
