// Priority 4 report-only A/B/C DECOMPOSITION TABLE (brief §9; PROTOCOL.md §12) — zero evaluations: joins the sealed
// decomposition record (D24 centre, risk envelope, confirmation tail) with the sealed validation record (the same
// configurations' continuous FULL run: whole-run net / DD / envelope and the 2025-01-02 → 2026-10-30 interval) and the
// report-only lot diagnostics of FULL (time funded, lots, turnover, staged / gap / placement exits, giveback). Per
// frozen incumbent I and finalist F: A = I (staged OFF); B = I with F's staged genes (no re-optimization); C = F as
// jointly optimized; C-OFF = F projected to staged OFF. Selects nothing.
//   node --no-maglev --experimental-transform-types tools/vg-l0-staged-stop/abc.ts --out <md>
import fs from 'node:fs';
import { decompositionFile } from '../../src/vg-l0-staged-stop/stages.ts';
import { readSealed } from '../../src/vg-l0-staged-stop/records.ts';

const args = process.argv.slice(2);
const out = args.includes('--out') ? args[args.indexOf('--out') + 1]! : undefined;

if (!out) throw new Error('--out <md>');

const P = 'research/vg-l0-staged-stop';
type Env = { bankedDdLiquidation: number; principalLossLiquidation: number };
const dec = readSealed<{
  rows: { label: string; kind: string; id: string }[];
  evidence: { id: string; centre: { net: number; dd: number }; envelope: { centre: Env }; confirmTail: { p90Dd: number } }[];
}>(decompositionFile);
const val = readSealed<{
  rows: { id: string; sliceNet: number; sliceDd: number; wholeNet: number; wholeDd: number; wholeEnvelope: Env }[];
}>(`${P}/results/intervals/C24.json`);
const lots = JSON.parse(fs.readFileSync(`${P}/reports/diagnostics/lots-C24-FULL-all.json`, 'utf8')) as {
  subjects: {
    id: string;
    portfolio: { timeFunded: number; lots: number; turnover: number };
    staged: { armedLots: number; stagedExitLots: number; placementExits: number; gapExitLots: number } | null;
    giveback: { retainedShare: number };
  }[];
};
const usd = (v: number | undefined) =>
  v === undefined || !Number.isFinite(v) ? '—' : `${v < 0 ? '−' : ''}$${Math.abs(Math.round(v)).toLocaleString('en-US')}`;
const ev = new Map(dec.evidence.map((e) => [e.id, e]));
const vr = new Map(val.rows.map((r) => [r.id, r]));
const lr = new Map(lots.subjects.map((s) => [s.id, s]));
const byLabel = new Map(dec.rows.map((r) => [r.label, r]));
const finalists = dec.rows.filter((r) => r.kind === 'finalist').map((r) => r.label);
const head = [
  'Row',
  'D24 net',
  'D24 marked DD',
  'D24 confirm p90 DD',
  'D24 PL liq.',
  'D24 BD liq.',
  'FULL whole-run net',
  'FULL marked DD',
  'FULL PL liq.',
  'FULL BD liq.',
  'validation P&L (2025-01 → 2026-10)',
  'validation DD (reset)',
  'time funded',
  'lots',
  'turnover',
  'staged exits (gap / placement)',
  'retained share of ex-post peak'
];
const line = (tag: string, label: string) => {
  const r = byLabel.get(label);

  if (!r) return [`${tag}: ${label}`, ...head.slice(1).map(() => 'n/a')];

  const e = ev.get(r.id)!;
  const v = vr.get(r.id);
  const l = lr.get(r.id);

  return [
    `${tag}: ${label}`,
    usd(e.centre.net),
    usd(e.centre.dd),
    usd(e.confirmTail.p90Dd),
    usd(e.envelope.centre.principalLossLiquidation),
    usd(e.envelope.centre.bankedDdLiquidation),
    usd(v?.wholeNet),
    usd(v?.wholeDd),
    usd(v?.wholeEnvelope.principalLossLiquidation),
    usd(v?.wholeEnvelope.bankedDdLiquidation),
    usd(v?.sliceNet),
    usd(v?.sliceDd),
    l ? `${(100 * l.portfolio.timeFunded).toFixed(1)} %` : '—',
    l ? String(l.portfolio.lots) : '—',
    l ? usd(l.portfolio.turnover) : '—',
    l?.staged ? `${l.staged.stagedExitLots} (${l.staged.gapExitLots} / ${l.staged.placementExits})` : '0',
    l ? `${(100 * l.giveback.retainedShare).toFixed(1)} %` : '—'
  ];
};
const table = (rows: string[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const text = [
  '<!-- generated by tools/vg-l0-staged-stop/abc.ts from the sealed decomposition (D24) and validation (FULL) records and the report-only lots-C24-FULL-all diagnostic (every validation row, CPU = sealed GPU 195/195) (no evaluation) -->',
  ''
];

for (const inc of ['New L0', 'N/original']) {
  text.push(`### Incumbent ${inc}`, '');

  const rows: string[][] = [line('A', `${inc} (OFF)`)];

  for (const f of finalists) {
    const short = f.replace(/: EXP .*$/, '');

    rows.push(
      line('B', `${inc} + ${short}'s staged genes`),
      line('C', f),
      line('C-OFF', `${f} [all OFF]`)
    );
  }
  text.push(table(rows), '');
}
fs.writeFileSync(out, `${text.join('\n')}\n`);
console.log(`abc → ${out}`);
