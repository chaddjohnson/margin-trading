#!/usr/bin/env python3
# SEARCH_AND_CONVERGENCE_REPORT.md (brief §9 item 9) = the hand-written narrative reports/narrative/SEARCH.md followed by
# sections generated here from analyze.ts's tables (reports/tables/search-summary.json, lanes.csv) and gpu-jobs.py's
# reports/tables/gpu-jobs.json. Report-only; reads JSON/CSV only.
#   python3 -I tools/msft-d1-growth/search-report.py
import collections
import csv
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
STUDY = os.path.join(REPO, 'research', 'msft-d1-growth')
T = os.path.join(STUDY, 'reports', 'tables')
NARR = os.path.join(STUDY, 'reports', 'narrative', 'SEARCH.md')
OUT = os.path.join(STUDY, 'SEARCH_AND_CONVERGENCE_REPORT.md')
CEILING = 250_000_000
NL0_CAP = {'broad': 6, 'refine': 8}


def n(x):
    return f'{x:,}' if isinstance(x, int) else (f'{x:,.1f}' if isinstance(x, float) else str(x))


summary = json.load(open(os.path.join(T, 'search-summary.json'), encoding='utf-8'))['rows']
lanes = list(csv.DictReader(open(os.path.join(T, 'lanes.csv'), encoding='utf-8')))
jobs = json.load(open(os.path.join(T, 'gpu-jobs.json'), encoding='utf-8'))

md = ['---', '', '_Sections A–F below are generated by `tools/msft-d1-growth/search-report.py` from `reports/tables/` '
      '(analyze.ts, gpu-jobs.py; report-only)._', '']

# A. per cutoff and arm
md += ['## A. Effort, coverage and stopping per cutoff and arm', '',
       '"Requested" = official evaluations the lanes asked for (archive hits included); "fresh" = evaluated on the GPU; '
       'islands per lane as count of lanes; *beyond NL0* = lanes that ran more islands than NL0\'s own cap (6 broad, '
       '8 refinement) because a performance component (> 5 %) still fired (tier 1); *at 16* = lanes stopped by the hard '
       'island cap (budget-bound). Replicate spread = across the arm\'s cells, the median of (max − min) ÷ median of the '
       'replicates\' best feasible centre nets.', '',
       '| Cutoff | Arm | Lanes broad / replicate rounds / refine | Replicates | Rounds (✓ fired) | Requested | Fresh | GPU wall (s) | '
       'Islands per lane | Beyond NL0 | At 16 | Stop reasons | Cells with a feasible fit | Replicate spread | Label |',
       '|---|---|---:|---:|---|---:|---:|---:|---|---:|---:|---|---:|---:|---|']
lane_idx = collections.defaultdict(list)
for r in lanes:
    lane_idx[(r['cutoff'], r['arm'])].append(r)
for s in summary:
    ls = lane_idx[(s['cutoff'], s['arm'])]
    rx = sum(1 for r in ls if r['part'].startswith('rx'))
    br = sum(1 for r in ls if r['part'] == 'broad')
    rf = sum(1 for r in ls if r['part'] == 'refine')
    beyond = sum(1 for r in ls if int(r['islands']) > NL0_CAP['refine' if r['part'] == 'refine' else 'broad'])
    at16 = sum(1 for r in ls if int(r['islands']) >= 16)
    rounds = ' '.join(f"{x['k']}{'✓' if x['fired'] else '✗'}" for x in s['rounds']) or '—'
    isl = ', '.join(f'{k}: {v}' for k, v in sorted(s['islands'].items(), key=lambda kv: int(kv[0])))
    stops = '; '.join(f'{k[:60]} {v}' for k, v in s['stops'].items())
    spread = s.get('replicateSpread', {}).get('medianRelativeRange')
    md.append(f"| {s['cutoff']} | {s['arm']} | {br} / {rx} / {rf} | {s['replicates']} | {rounds} | {n(s['requested'])} | {n(s['fresh'])} | "
              f"{n(float(s['wallSeconds']))} | {isl} | {beyond} | {at16} | {stops} | {s['cellsWithFeasible']} / {s['cells']} | "
              f"{'—' if spread is None else f'{spread * 100:.0f} %'} | {s['budgetLimitedLabel']} |")

# B. totals
by_cut = collections.Counter()
by_arm = collections.Counter()
wall = collections.Counter()
for s in summary:
    by_cut[s['cutoff']] += s['requested']
    by_arm[s['arm']] += s['requested']
    wall[s['cutoff']] += float(s['wallSeconds'])
tot = sum(by_cut.values())
md += ['', '## B. Totals of the search lanes', '',
       '| Cutoff | Requested | Search GPU wall (h) |', '|---|---:|---:|']
for c in sorted(by_cut):
    md.append(f'| {c} | {n(by_cut[c])} | {wall[c] / 3600:.2f} |')
md.append(f'| **all** | **{n(tot)}** ({tot / CEILING * 100:.1f} % of the 250 M hard ceiling) | **{sum(wall.values()) / 3600:.2f}** |')
md += ['', '| Arm | Requested over all cutoffs | Share |', '|---|---:|---:|']
for a in ['D', 'G', 'J', 'S']:
    if by_arm[a]:
        md.append(f'| {a} | {n(by_arm[a])} | {by_arm[a] / tot * 100:.1f} % |')
md.append('| C | 0 (no search: pairs of the D and G finalists) | — |')

# C. official GPU jobs by kind (every evaluation: lanes, qualification, slices, validation)
kinds = collections.OrderedDict()
for j in jobs['jobs']:
    name = j['job']
    parts = name.split('-', 1)
    kind = parts[1] if len(parts) > 1 else name
    for pre in ('D-', 'G-', 'J-', 'S-', 'C-'):
        if kind.startswith(pre):
            kind = kind[len(pre):]
    kind = kind.rstrip('0123456789') if kind.startswith('rx') else kind
    k = kinds.setdefault(kind, {'jobs': 0, 'submitted': 0, 'kernel': 0.0, 'wall': 0.0, 'cpu': 0, 'failed': 0})
    k['jobs'] += 1
    k['submitted'] += j['submitted']
    k['kernel'] += j['kernelSeconds']
    k['wall'] += j['wallSeconds']
    k['cpu'] += j['cpuScored']
    k['failed'] += j['failed']
t = jobs['totals']
md += ['', '## C. Official GPU jobs by kind (every official evaluation of the study)', '',
       '| Kind | Jobs | Evaluations submitted (all GPU-returned) | Kernel (h) | Wall (h) | CPU-scored | Failed |',
       '|---|---:|---:|---:|---:|---:|---:|']
ORDER = ['broad', 'rx', 'refine', 'qualify-broad', 'qualify-refine', 'qualify-fixed', 'slice', 'validation']
for kind, k in sorted(kinds.items(), key=lambda kv: ORDER.index(kv[0]) if kv[0] in ORDER else len(ORDER)):
    md.append(f"| {kind} | {k['jobs']} | {n(k['submitted'])} | {k['kernel'] / 3600:.2f} | {k['wall'] / 3600:.2f} | {k['cpu']} | {k['failed']} |")
md.append(f"| **all** | **{t['jobs']}** ({t['jobsComplete']} complete) | **{n(t['submitted'])}** (GPU-returned {n(t['gpuReturned'])}) | "
          f"**{t['kernelSeconds'] / 3600:.2f}** | **{t['wallSeconds'] / 3600:.2f}** | **{t['cpuScored']}** | **{t['failed']}** |")
md += ['', f"Capacity retries (an evaluation re-submitted on the GPU with a larger result buffer, ≤ 4 times; never the CPU): "
       f"{t['capacityRetries']}. Device {', '.join(t['devices'])}; binary {', '.join(t['binaries'])}…; acceptance "
       f"{', '.join(t['acceptance'])}…; attestations {t['attestations']} ({t['attestationChecks']} checks, {t['attestationChecksFailed']} failed); "
       f"parity mini-sets {t['parityIdentical']}/{t['paritySubjects']} identical."]

# D. replicate spread per cell (the seed dependence of each cell's best)
md += ['', '## D. Seed dependence: the best feasible centre net of each cell across its replicates', '',
       'Each replicate is an independent seed (`deriveSeed(\'msft-d1-growth\', …)`, replicate numbers from R101). A wide '
       'range means different seeds found materially different optima in the same cell: "converged by the frozen rules" '
       'is a statement about the stopping rules, not proof that the global optimum was found.', '',
       '| Cutoff | Arm | Cells | Median relative range | Widest cell (min / median / max) |', '|---|---|---:|---:|---|']
for s in summary:
    cells = s.get('replicateSpread', {}).get('cells', {})
    if not cells:
        continue
    def rel(v):
        return (v['max'] - v['min']) / v['median'] if v.get('median') else 0
    wk, wv = max(cells.items(), key=lambda kv: rel(kv[1]))
    md.append(f"| {s['cutoff']} | {s['arm']} | {len(cells)} | {s['replicateSpread']['medianRelativeRange'] * 100:.0f} % | "
              f"`{wk}` ${wv['min']:,.0f} / ${wv['median']:,.0f} / ${wv['max']:,.0f} |")

# E. seeds (replicate numbers) per cutoff and arm
md += ['', '## E. Replicates (seeds) used', '', '| Cutoff | Arm | Broad / round replicates | Refinement replicates |', '|---|---|---|---|']
for (c, a), ls in sorted(lane_idx.items()):
    b = sorted({int(r['replicate']) for r in ls if r['part'] != 'refine'})
    rf = sorted({int(r['replicate']) for r in ls if r['part'] == 'refine'})
    fmt = lambda xs: (f'R{xs[0]}–R{xs[-1]}' if xs and xs == list(range(xs[0], xs[-1] + 1)) else ', '.join(f'R{x}' for x in xs)) if xs else '—'
    md.append(f'| {c} | {a} | {fmt(b)} | {fmt(rf)} |')

# F. lanes that did not stop on "triggers not met"
odd = [r for r in lanes if r['stop'] != 'triggers not met']
md += ['', '## F. Lanes with another stop reason', '']
if odd:
    md += ['| Lane | Part | Islands | Stop |', '|---|---|---:|---|']
    md += [f"| `{r['lane']}` | {r['part']} | {r['islands']} | {r['stop']} |" for r in odd]
else:
    md.append('None: every lane stopped because its triggers were no longer met.')

narrative = open(NARR, encoding='utf-8').read().rstrip() if os.path.exists(NARR) else '# Search budget and convergence\n\n_(narrative pending)_'
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(narrative + '\n\n' + '\n'.join(md) + '\n')
print(f'wrote {OUT} ({len(md)} generated lines)')
