// Report tables and charts of Priority 3A (research/vg-d1-growth-diagnostic/results/tables/*.md, charts/*.svg), built
// only from the study's sealed records (each verified against results/seals.jsonl first). Formatting only: nothing is
// evaluated, selected or ranked here.
