      table(['Subject', 'Family', 'n', 'Centre net', 'Median net', 'p10 net', 'Robust', 'Retention', 'Centre DD', 'Median DD', 'p90 DD', 'Inflation', 'p95 DD', 'Worst-10% mean DD', 'Worst DD', 'Breaches > $35k [Wilson 95%]', 'Mean excess', 'Distinct ledgers', 'Centre ledger', 'Clipped', 'Net > 0'], rows)
