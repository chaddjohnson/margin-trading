// Markdown report tables for Priority 5A (vg-growth-funding-lifecycle), generated only from the sealed records (after
// `npm run vg-life -- verify`). Text and tables only (standard 2.0.0 §7.7): no chart, image or visual artifact.
//   node --experimental-transform-types --disable-warning=ExperimentalWarning tools/vg-growth-funding-lifecycle/tables.ts
import fs from 'node:fs';
import path from 'node:path';
import { resultsDir } from '../../src/vg-growth-funding-lifecycle/context.ts';
import { readJson, usd, verifySeals } from '../../src/vg-growth-funding-lifecycle/records.ts';
import { stageFiles } from '../../src/vg-growth-funding-lifecycle/stages.ts';

const v = verifySeals();

if (v.failed.length) throw new Error(`sealed records changed: ${v.failed.join(', ')}`);

const out = path.join(resultsDir, 'tables');

fs.mkdirSync(out, { recursive: true });

type Any = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

const exists = (f: string) => fs.existsSync(f);
const V: Any = readJson(stageFiles.V);
const C: Any = readJson(stageFiles.C);
const N: Any | null = exists(stageFiles.N) ? readJson(stageFiles.N) : null;
const S: Any | null = exists(stageFiles.S) ? readJson(stageFiles.S) : null;
const P: Any | null = exists(stageFiles.P) ? readJson(stageFiles.P) : null;
const F: Any | null = exists(stageFiles.F) ? readJson(stageFiles.F) : null;
const modes = ['L0', 'L1', 'L2'] as const;
const core = ['D', 'E', 'C4', 'C85', 'A', 'B', 'GP4', 'GP85', 'V4', 'V85'];
const standalone = ['SG', 'S4', 'S85'];
const mechanism = ['IP', 'XP', 'SP'];
const nbKeys = ['E', 'C4', 'C85', 'A', 'B', 'GP4', 'GP85', 'V4', 'V85'];
const pct = (x: number, d = 1) => (Number.isFinite(x) ? `${(x * 100).toFixed(d)}%` : '—');
const ddPct = (x: number) => `${((x / 100_000) * 100).toFixed(1)}%`;
const day = (t: number | string | null) =>
  t === null || t === undefined || (typeof t === 'number' && !Number.isFinite(t))
    ? '—'
    : typeof t === 'number'
      ? new Date(t * 1000).toISOString().slice(0, 10)
      : String(t).slice(0, 10);
const signed = (x: number) => (x > 0 ? `+${usd(x)}` : usd(x));
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map((h, i) => (i === 0 || /^[A-Za-z]/.test(h) && i < 2 ? '---' : '---:')).join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const write = (name: string, title: string, body: string) =>
  fs.writeFileSync(
    path.join(out, name),
    `# ${title}\n\nGenerated by \`tools/vg-growth-funding-lifecycle/tables.ts\` from the sealed records (verified: ${v.ok} seals). Dollars on one fixed $100,000 principal budget; DD = maximum minute drawdown of the marked net; DD % = DD ÷ $100,000. L0 = current virtual-book lifecycle (exact control); L1 = Growth responds to actual funding (fresh canonical opportunities only); L2 = L1 + one retained refused base opportunity (20 sessions, 5% extension; an experimental policy).\n\n${body}\n`
  );
const label = (k: string) => C.centres[k]?.label ?? k;
const growthNames = (k: string) =>
  Object.values(C.centres[k]?.growth ?? {})
    .map((g: Any) => g.name)
    .join(' + ') || '—';

// ----- verification -----

{
  const c = V.checks;
  const v1 = Object.entries(c.V1).map(([k, x]) => [k, String(x)]);
  const v4 = Object.entries(c.V4).map(([k, x]: [string, Any]) => [k, x.equal ? 'equal' : 'DIFFERS', `${x.rounds[0]} / ${x.rounds[1]}`]);
  const v5 = Object.entries(c.V5).map(([k, x]: [string, Any]) => [k, x.funding && x.requests && x.lots ? 'equal before 2023-12-29' : 'DIFFERS']);

  write(
    'verification.md',
    'Stage V — verification gates (sealed before any dependent stage)',
    [
      `**Result: ${V.passed ? 'PASSED' : 'FAILED'}** (${V.failures.length} failures). Simulations: ${V.counts.development} fresh development (consistency rounds ${V.counts.rounds}, Growth re-simulations ${V.counts.growthSims}, book-parity runs ${V.counts.bookRuns}).`,
      '## V1 — L0 centres against the sealed records',
      table(['Subject', 'Result'], v1),
      '## V2 — archived Priority 3 draws replayed (first 16 confirmation draws)',
      table(['Subject', 'Replayed', 'Equal'], Object.entries(c.V2).map(([k, x]: [string, Any]) => [k, x.replayed, x.equal])),
      '## V3 — invariance (no Growth book, or a Growth book alone)',
      table(['Subject and arm', 'Result'], Object.entries(c.V3).map(([k, x]) => [k, String(x)])),
      '## V4 — the fixed point without the occupancy guess (rounds with / without the guess)',
      table(['Subject and arm', 'Record, detail and requests', 'Rounds'], v4),
      '## V5 — shortened prefix: D23 against D24 up to 2023-12-29',
      table(['Subject and arm', 'Funding records, requests, lots and exits'], v5),
      '## V6 — the lifecycle engine in L0 mode against the canonical Growth book',
      `${Object.values(c.V6).filter(Boolean).length} of ${Object.keys(c.V6).length} distinct Growth configurations identical (trades and standalone figures).`
    ].join('\n\n')
  );
}

// ----- centres (development) -----

const centreRows = (keys: string[], src: Any, period: 'dev' | 'full') =>
  keys.flatMap((k) =>
    modes.map((m) => {
      const x = src[k]?.modes?.[m];

      if (!x) return [k, m, '—'];

      const r = x.rec;
      const sum = x.summary;

      return [
        m === 'L0' ? `**${k}**` : '',
        m,
        usd(r.net),
        usd(r.realized),
        usd(r.unrealized),
        usd(r.dd),
        ddPct(r.dd),
        `${day(r.ddPeakT)} → ${day(r.ddTroughT)} → ${day(r.ddRecoveryT)}`,
        r.lots,
        `${r.wins}/${r.losses}`,
        r.partials,
        r.episodes,
        `${sum.pool.held}/${sum.pool.sessions}`,
        usd(r.interest),
        usd(r.costs),
        (x.detail?.ledger ?? []).filter((l: Any) => l.open).map((l: Any) => `${l.book} ${day(l.entry)}`).join(', ') || 'flat',
        period === 'dev' && m !== 'L0' ? signed(x.delta.net) : ''
      ];
    })
  );
const centreHead = ['Subject', 'Arm', 'Net', 'Realized', 'Unrealized', 'DD', 'DD %', 'DD peak → trough → recovery', 'Lots', 'W/L', 'Partials', 'Episodes', 'Closes held', 'Interest', 'Costs', 'Open at end', 'Δ net vs L0'];

write(
  'centres.md',
  'Development centres (2016-01-04 → 2024-12-31, D24) by subject and lifecycle',
  [
    `VG #2 native bridge (Study 8 arming 2017-06-15, L0): ${usd(C.native.rec.net)} / DD ${usd(C.native.rec.dd)} / ${C.native.rec.lots} lots / ${C.native.refusals} D1 refusals (Study 8 target $260,223.13 / $17,280.74 / 36 / 14). Harmonized D: ${usd(C.centres.D.modes.L0.rec.net)} / ${usd(C.centres.D.modes.L0.rec.dd)}.`,
    '## Core matrix',
    table(['Key', 'Subject', 'Growth books'], core.map((k) => [k, label(k), growthNames(k)])),
    table(centreHead, centreRows(core, C.centres, 'dev')),
    '## Standalone books (each alone on its own $100,000; never summed)',
    table(centreHead, centreRows(standalone, C.centres, 'dev')),
    "## Priority 3's primaries (mechanism controls)",
    table(centreHead, centreRows(mechanism, C.centres, 'dev'))
  ].join('\n\n')
);

// ----- participation and funding (development centres) -----

const partRows = (keys: string[], src: Any) =>
  keys.flatMap((k) =>
    modes.flatMap((m) => {
      const x = src[k]?.modes?.[m];

      if (!x) return [];

      return Object.entries(x.summary.books).map(([b, s]: [string, Any]) => {
        const kinds = Object.entries(s.byKind)
          .map(([kk, y]: [string, Any]) => `${kk} ${y.granted}/${y.refused}${y.waiting ? `/${y.waiting}w` : ''}`)
          .join('; ');
        const ret = Object.entries(s.retained)
          .map(([e, n]) => `${e} ${n}`)
          .join(', ');
        const sources: Record<string, number> = {};

        for (const l of x.detail?.ledger ?? []) if (l.book === b) sources[l.source ?? '?'] = (sources[l.source ?? '?'] ?? 0) + 1;

        return [
          k,
          m,
          b,
          s.records,
          s.granted,
          s.refused,
          s.waiting,
          kinds || '—',
          ret || '—',
          Object.entries(sources).map(([a, n]) => `${a} ${n}`).join(', ') || '—',
          s.lots,
          usd(s.booked),
          m === 'L0' ? `${s.virtualHolds.trades} / ${s.virtualHolds.closes} / ${s.virtualHolds.idleCloses}` : '0 (none exist)'
        ];
      });
    })
  );
const partHead = ['Subject', 'Arm', 'Book', 'Pool records', 'Granted', 'Refused', 'L2 waiting', 'By kind (granted/refused/waiting)', 'Retained outcomes (L2)', 'Funded lots by source', 'Lots', 'Booked', 'Unfunded virtual holds: trades / closes / idle closes'];
const poolRows = (keys: string[], src: Any) =>
  keys.flatMap((k) =>
    modes.map((m) => {
      const x = src[k]?.modes?.[m];
      const p = x.summary.pool;
      const d1 = x.rec.fam.D1;

      return [k, m, p.held, p.reservedOnly, p.idle, pct(p.idle / p.sessions), `${d1.decisions}/${d1.refused}`, usd(d1.booked), usd(x.rec.fam.G.booked), x.summary.rounds];
    })
  );

write(
  'participation.md',
  'Participation, requests, refusals and pool time (development centres)',
  [
    'L0 pool records are the Growth books\' virtual trades (a refused one keeps its virtual position); L1/L2 records are actual requests (a refused one leaves the book flat), and L2 adds reassessments of the retained opportunity ("waiting" = every check passed but the slot was occupied). Unfunded virtual holds: the refused virtual trades, the session closes inside their holds, and how many of those closes had no funded lot and no reservation (idle overlap).',
    '## Growth books',
    table(partHead, partRows([...core, ...standalone, ...mechanism], C.centres)),
    '## Pool time and D1',
    table(['Subject', 'Arm', 'Closes held', 'Reserved only', 'Idle', 'Idle %', 'D1 decisions / refused', 'D1 booked', 'Growth booked', 'Consistency rounds'], poolRows([...core, ...mechanism], C.centres))
  ].join('\n\n')
);

// ----- first divergence from L0 -----

{
  const rows: (string | number)[][] = [];

  for (const k of [...core, ...mechanism, ...Object.keys(C.centres).filter((x) => /^[GI]\d\d$/.test(x))])
    for (const m of ['L1', 'L2']) {
      const d = C.centres[k].modes[m].divergence;

      if (d.identical) {
        rows.push([k, m, 'identical funded ledger', '', '', '', '']);
        continue;
      }
      rows.push([
        k,
        m,
        d.kind,
        d.reference ? `${d.reference.book} ${d.reference.kind} ${day(d.reference.entry)} (${usd(d.reference.net)})` : '—',
        d.changed ? `${d.changed.book} ${d.changed.kind} ${day(d.changed.entry)} (${usd(d.changed.net)})` : '—',
        `${d.displaced.length} displaced (${usd(d.displaced.reduce((a: number, x: Any) => a + x.net, 0))}); ${d.admitted.length} admitted (${usd(d.admitted.reduce((a: number, x: Any) => a + x.net, 0))})`,
        `${usd(d.afterReference)} → ${usd(d.afterChanged)}`
      ]);
    }

  write(
    'divergence.md',
    'First divergence from L0 and the subsequent funded portfolio (development centres)',
    [
      'The funded ledgers in entry order are compared lot by lot (book, entry instant, exits). "Displaced" = L0 lots absent under the arm (any later point); "admitted" = lots the arm funds that L0 did not. Sums are booked nets of those lots; the last column is the booked net of every lot from the first divergence on (L0 → arm). These are complete reruns; nothing is attributed by subtraction.',
      table(['Subject', 'Arm', 'First divergence', 'L0 lot there', 'Arm lot there', 'Displaced / admitted after it', 'Booked from the divergence on'], rows)
    ].join('\n\n')
  );
}

// ----- the four VGT refusal episodes of Priority 3A -----

{
  const ends: Record<string, string> = {
    'GP85 2016-07-06': '2018-10-12',
    'GP85 2020-04-13': '2022-01-20',
    'GP4 2016-06-28': '2018-02-05',
    'B 2020-04-13': '2022-01-20'
  };
  const parts: string[] = [];

  for (const e of C.episodes as Any[]) {
    const key = `${e.subject} ${e.date}`;
    const until = ends[key]!;
    const lines: string[] = [`### ${e.subject}: Growth·VGT refused on ${e.date}`, `Priority 3A (L0): ${e.note}.`];

    for (const m of modes) {
      const x = C.centres[e.subject].modes[m];
      const reqs = (x.detail.requests[e.book] ?? []).filter((q: Any) => q.date >= e.date && q.date <= until);
      const fund = x.detail.funding.filter((f: Any) => f.book === e.book && day(f.t) === e.date);
      const lots = x.detail.ledger.filter((l: Any) => day(l.entry) >= e.date && day(l.entry) <= until);
      const ret = (x.detail.retained[e.book] ?? []).filter((r: Any) => r.refusedDate === e.date);

      lines.push(`**${m}.** The pool's answer on ${e.date}: ${fund.map((f: Any) => `${f.kind} ${f.outcome}${f.occupant ? ` (occupant ${f.occupant})` : ''}`).join('; ') || 'no Growth·VGT record that day'}.`);
      if (m !== 'L0')
        lines.push(
          `Growth·VGT requests ${e.date} → ${until}: ${reqs.length ? reqs.map((q: Any) => `${q.date} ${q.source ?? q.kind} ${q.outcome} @ ${q.price}`).join('; ') : 'none'}.`
        );
      if (m === 'L2')
        lines.push(
          `Retained opportunity: ${ret.length ? ret.map((r: Any) => `${r.id} (${r.origin}; cap ${r.cap}; bound ${r.bound}) — ${r.evaluations} reassessments, ${r.waits} waiting, blocked ${JSON.stringify(r.blocked)}, end ${r.end} on ${r.endDate}: ${r.endReason}`).join('; ') : 'none created'}.`
        );
      lines.push(
        `Funded lots entered ${e.date} → ${until}: ${lots.length ? lots.map((l: Any) => `${l.book} ${l.source ?? l.kind} ${day(l.entry)} @ ${l.entryRaw} → ${l.exits.map((f: Any) => `${f.date} ${f.reason}${f.partial ? ' (partial)' : ''}`).join(', ') || 'open'} (${usd(l.net)})`).join('; ') : 'none'}.`
      );
    }
    for (const m of ['L1', 'L2']) {
      const a = C.centres[e.subject].modes.L0.detail.ledger.filter((l: Any) => day(l.entry) >= e.date && day(l.entry) <= until);
      const b = C.centres[e.subject].modes[m].detail.ledger.filter((l: Any) => day(l.entry) >= e.date && day(l.entry) <= until);
      const ka = new Set(a.map((l: Any) => `${l.book}@${l.entry}`));
      const kb = new Set(b.map((l: Any) => `${l.book}@${l.entry}`));
      const disp = a.filter((l: Any) => !kb.has(`${l.book}@${l.entry}`));
      const adm = b.filter((l: Any) => !ka.has(`${l.book}@${l.entry}`));

      lines.push(
        `**${m} against L0 in this window:** displaced ${disp.length ? disp.map((l: Any) => `${l.book} ${day(l.entry)} (${usd(l.net)})`).join(', ') : 'none'}; admitted ${adm.length ? adm.map((l: Any) => `${l.book} ${day(l.entry)} (${usd(l.net)})`).join(', ') : 'none'}.`
      );
    }
    parts.push(lines.join('\n\n'));
  }

  write('episodes.md', "The 2016 and 2020 VGT refusal episodes of Priority 3A, traced under L0, L1 and L2 (development)", parts.join('\n\n'));
}

// ----- neighbourhoods -----

if (N) {
  const rows: (string | number)[][] = [];
  const paired: (string | number)[][] = [];

  for (const k of nbKeys)
    for (const fam of ['confirm', 'small', 'wide']) {
      const f = N.subjects[k].families[fam];

      for (const m of modes) {
        const nb = f.modes[m].nb;
        const t = f.modes[m].tail;

        rows.push([
          m === 'L0' ? `**${k}** ${fam}` : '',
          m,
          f.n,
          usd(C.centres[k].modes[m].rec.net),
          usd(nb.median),
          usd(nb.p10),
          usd(nb.robust),
          usd(C.centres[k].modes[m].rec.dd),
          usd(nb.medianDd),
          usd(nb.p90Dd),
          usd(t.p95Dd),
          usd(t.worst10Mean),
          usd(nb.worstDd),
          `${pct(nb.breachShare)} [${pct(t.breachInterval[0])}, ${pct(t.breachInterval[1])}]`,
          usd(nb.meanExcess),
          `${t.breachLedgers}`,
          nb.distinct,
          nb.sameAsCentre,
          nb.clipped,
          pct(t.positiveShare, 0),
          m === 'L0' ? f.modes[m].source : 'fresh'
        ]);
      }
      for (const [cmp, lab] of [
        ['L1vsL0', 'L1 − L0'],
        ['L2vsL0', 'L2 − L0'],
        ['L2vsL1', 'L2 − L1']
      ]) {
        const p = f.paired[cmp];

        paired.push([fam === 'confirm' && cmp === 'L1vsL0' ? `**${k}**` : '', fam, lab, p.n, signed(p.net.median), signed(p.net.p10), signed(p.net.p90), signed(p.net.mean), `${p.net.better}/${p.net.worse}`, signed(p.dd.median), signed(p.dd.p90), `${p.dd.higher}/${p.dd.lower}`, p.sameLedger]);
      }
    }

  write(
    'neighbourhoods.md',
    "Matched development neighbourhoods (Priority 3's 384-draw instrument and its half / 1.5× radius families)",
    [
      "The same effective parameter draws are evaluated under L0, L1 and L2 (L0 from Priority 3's archives, E's L0 fresh). Robust = ½ median + ½ p10. Breach = a draw's DD above $35,000 (Wilson 95% interval: a finite-draw approximation; the Latin-hypercube draws are dependent). These are perturbation frequencies on 2016–2024, not probabilities of future losses. Dimensionality differs by subject (active inputs: E 35, C4 37, C85 38, A 56, B 57, GP4 40, GP85 41, V4 29, V85 30).",
      table(['Subject / family', 'Arm', 'n', 'Centre net', 'Median net', 'p10 net', 'Robust', 'Centre DD', 'Median DD', 'p90 DD', 'p95 DD', 'Worst-10% mean DD', 'Worst DD', 'Breaches > $35k [Wilson 95%]', 'Mean excess', 'Breach ledgers', 'Distinct ledgers', 'Centre ledger', 'Clipped', 'Net > 0', 'L0 source'], rows),
      '## Paired changes against the same draws',
      table(['Subject', 'Family', 'Change', 'n', 'Median Δ net', 'p10 Δ net', 'p90 Δ net', 'Mean Δ net', 'Better / worse', 'Median Δ DD', 'p90 Δ DD', 'DD higher / lower', 'Identical ledgers'], paired),
      `D (reference): Priority 3's archived L0 families, identical under L1 and L2 (stage V3). Archived L0 draws read: ${N.counts.archiveReads}; missing from the archive: ${N.missingFromArchive.length}.`
    ].join('\n\n')
  );
}

