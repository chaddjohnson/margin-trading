        c.jobs.map((j) => [j.cutoff, j.part, j.track, j.lanes, n0(j.proposals), n0(j.requested), n0(j.uniqueFresh), n0(j.archiveHits), n0(j.retries), j.islands, `${j.refinementStarts} / ${n0(j.refinementMoves)}`, Object.entries(j.stops).map(([k, v]) => `${k} ${v}`).join('; '), j.budgetBound, j.resourceGuard, j.minutes, j.evaluationsPerSecond, j.peakCgroupGiB])
