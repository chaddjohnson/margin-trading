// ----- the head-to-head comparison (brief §6) -----
if (exists('validation', 'validation.json') && diagnosticExists('finalists')) {
  const fz = frozenSelection();
  const v = validation();
  const fin = readDiagnostic<{ rows: Record<string, any>[] }>('finalists');
  const ev = new Map(allEvidence(finalKey).map((e) => [e.label, e]));
  const sel = selection(finalKey);
  const seq = exists('folds', 'sequential.json') ? sequential() : null;
  const pathOf = (label: string) => {
    const procs = fz.procedures.filter((p) => p.primary === label && ['L', 'B', 'F'].includes(p.population));

    return procs.map((p) => {
      const s = seq?.procedures.find((x) => x.population === p.population && x.selector === p.selector);

      return s ? `${p.population}/${p.selector}: ${usd(s.path.net)} / ${usd(s.path.sequentialDd)}` : '';
    }).filter(Boolean).join('; ');
  };
  const row = (label: string, provenance: string, status: string) => {
    const e = label === 'control: New L0' ? sel.control : ev.get(label);
    const vr = label === 'control: New L0' ? (v.newL0 as any) : v.rows.find((r) => r.label === label);

    return [
      label,
      provenance,
      e ? usd(e.centre.net) : null,
      e ? usd(e.centre.dd) : null,
      e ? e.centre.lots : null,
      pathOf(label) || 'no independent chronological test',
      vr ? `${usd(vr.validationPnl)} / ${usd(vr.resetValidationDd)}` : null,
      vr ? `${usd(vr.net)} / ${usd(vr.dd)}` : null,
      e ? `${usd(e.confirm.p90Dd)} / ${usd(e.confirmTail.p95Dd)} / ${usd(e.confirmTail.worst10Mean)} / ${usd(e.confirm.worstDd)}` : null,
      e ? usd(e.risk.mae.worst) : null,
      e ? pct(e.risk.occupancy) : null,
      e ? usd(e.centre.interest) : null,
      status
    ];
  };
  const a2fz = a2<{ finalists: { label: string; centreNet: number; centreDd: number }[]; procedures: { population: string; selector: string; primary: string | null }[] }>('FROZEN_SELECTION.json');
  const a2v = a2<{ rows: { label: string; net: number; dd: number; validationPnl: number; resetValidationDd: number }[] }>('results/validation/validation.json');
  const a2seq = a2<{ procedures: { population: string; selector: string; path: SeqPath }[] }>('results/folds/sequential.json');
  const a2row = (p: string, s: string) => {
    const pr = a2fz.procedures.find((x) => x.population === p && x.selector === s)?.primary;
    const f = a2fz.finalists.find((x) => x.label === pr);
    const vr = a2v.rows.find((x) => x.label === pr);
    const sq = a2seq.procedures.find((x) => x.population === p && x.selector === s);

    return [`Assignment 2 ${p}/${s}: ${pr}`, 'Growth-frozen and conditional (Assignment 2)', usd(f?.centreNet), usd(f?.centreDd), null, sq ? `${usd(sq.path.net)} / ${usd(sq.path.sequentialDd)}` : null, vr ? `${usd(vr.validationPnl)} / ${usd(vr.resetValidationDd)}` : null, vr ? `${usd(vr.net)} / ${usd(vr.dd)}` : null, 'different instrument', null, null, null, 'research-only (no chronological support)'];
  };
  const head = ['Candidate', 'Provenance', 'Training net 2016–2024', 'Training DD', 'Lots', 'Chronological path 2020–2024 (net / DD)', '2025–2026 (examined) P&L / reset DD', 'Full history net / DD', 'Conf. p90 / p95 / worst-10% mean / worst DD', 'Worst lot MAE', 'Occupancy', 'Interest', 'Status'];
  const statusOf = (label: string) =>
    v.successor.filter((s) => s.primary === label).map((s) => `${s.population}/${s.selector}: ${s.finalStatus.split(':')[0]}`).join('; ') || (fz.finalists.find((x) => x.label === label)?.why ?? []).join('; ').slice(0, 140);
  const primaries = fz.procedures.filter((p) => p.primary && p.selector !== 'RA2');
  const seen = new Set<string>();
  const rows = [row('control: New L0', 'frozen reference (informed; chosen with later data)', 'reference'), a2row('F', 'original'), a2row('F', 'RA1'), a2row('L', 'original')];

  for (const p of primaries) {
    if (seen.has(p.primary!)) continue;
    seen.add(p.primary!);
    rows.push(row(p.primary!, ['L', 'B', 'F'].includes(p.population) ? `Track I ${p.population}/${p.selector} (independent)` : `Track ${p.population === 'N' ? 'N' : 'I ∪ N'} ${p.population}/${p.selector} (incumbent-informed; no independent chronological test)`, statusOf(p.primary!)));
  }
  for (const f of fz.finalists) {
    if (seen.has(f.label) || !(f.why.some((w) => w.includes('lower-drawdown') || w.includes('structurally distinct') || w.includes('incumbent')))) continue;
    seen.add(f.label);
    rows.push(row(f.label, f.why.join('; ').slice(0, 100), statusOf(f.label)));
  }
  write('finalists', 'C24 finalists against New L0 and Assignment 2 (brief §6)', md(head, rows));

  const abl = fin.rows.map((r) => [`**${r.label}**`, '', ...Object.entries(r.development as Record<string, any>).map(([k, x]) => `- ${k}: development ${typeof x === 'string' ? x : `${usd(x.net)} / ${usd(x.dd)} / ${x.lots} lots, occupancy ${pct(x.occupancy)}, interest ${usd(x.interest)}`}${r.full && typeof r.full === 'object' && r.full[k] ? `; full history ${usd(r.full[k].net)} / ${usd(r.full[k].dd)}` : ''}`), ''].join('\n'));

  write('ablations', 'Causal ablations of the finalists (attribution only; never a nomination)', abl.join('\n'));
  write(
    'exposure',
    'Cutoff exposure, holdings and the 2025–2026 give-back of the finalists (standard §5.9; report-only)',
    md(
      ['Finalist', 'Open lot at 2024-12-31', 'Multiple', 'Open-lot share', 'Conservative net', 'Worst lot MAE', 'Holdings (book: lots, median / p90 / max days, interest)', 'Open at cutoffs', '2025–26 slice net / DD', 'Give-back', 'Training nbhd on 2025–26: breach share [Wilson]'],
      fin.rows.map((r) => [
        r.label,
        r.cutoffExposure.openLot ? `${r.cutoffExposure.openLot.book} from ${r.cutoffExposure.openLot.entry}` : 'none open',
        r.cutoffExposure.openLot ? r2(r.cutoffExposure.openLot.multiple) : null,
        r.cutoffExposure.openShare === null ? '—' : pct(r.cutoffExposure.openShare),
        usd(r.cutoffExposure.conservativeNet),
        usd(r.cutoffExposure.mae.worst),
        Object.entries(r.holdings.development.byBook as Record<string, any>).map(([b, h]) => `${b}: ${h.lots}, ${h.medianDays} / ${h.p90Days} / ${h.maxDays}, ${usd(h.interest)}`).join('; '),
        Object.entries((r.holdings.full ?? r.holdings.development).openAt as Record<string, string[]>).map(([c, l]) => `${c}: ${l.length ? l.join(', ') : 'none'}`).join('; '),
        r.nextSlice2025 ? `${usd(r.nextSlice2025.sliceNet)} / ${usd(r.nextSlice2025.sliceDd)}` : null,
        r.nextSlice2025?.giveBack ? `${usd(r.nextSlice2025.giveBack.markAtCutoff)} → ${usd(r.nextSlice2025.giveBack.final)}` : 'none open',
        r.trainingNeighbourhoodOn2025 ? `${pct(r.trainingNeighbourhoodOn2025.breachShare)} [${r.trainingNeighbourhoodOn2025.wilson95.map((w: number) => pct(w)).join(', ')}]` : null
      ])
    )
  );
  write(
    'episodes',
    'The 2020 crash and the 2022 bear (development replays; report-only)',
    md(
      ['Finalist', 'Episode', 'Window DD', 'Trough', 'Exits by book (lots, net, losing)', 'Losing D1 entries', 'Exit reasons', 'Gaps through a stop (development)'],
      fin.rows.flatMap((r) =>
        Object.entries(r.episodes as Record<string, any>).map(([k, e]) => [
          r.label,
          k,
          usd(e.dd),
          e.trough,
          Object.entries(e.byBook as Record<string, any>).map(([b, x]) => `${b}: ${x.lots}, ${usd(x.net)}, ${x.losing}`).join('; '),
          e.losingD1Entries,
          Object.entries(e.exitReasons).map(([a, b]) => `${a} ${b}`).join('; '),
          (r.gapsThroughStop.development as any[]).length ? (r.gapsThroughStop.development as any[]).slice(0, 3).map((g) => `${g.book} ${g.exit} −${g.beyondStopPct}% beyond`).join('; ') : 'none'
        ])
      )
    )
  );
  write(
    'stresses',
    'Execution stresses (C24 development centre; FULL from the validation)',
    md(
      ['Finalist', ...Object.keys(v.rows[0]?.stresses ?? {}).map((k) => `${k}: dev net / DD`), ...Object.keys(v.rows[0]?.stresses ?? {}).map((k) => `${k}: full net / DD`)],
      v.rows.map((r) => {
        const e = ev.get(r.label);

        return [r.label, ...Object.keys(r.stresses).map((k) => (e?.stress[k] ? `${usd(e.stress[k]!.net)} / ${usd(e.stress[k]!.dd)}` : '—')), ...Object.entries(r.stresses).map(([, s]) => `${usd(s.net)} / ${usd(s.dd)}`)];
      })
    )
  );
  summary.validation = { newL0: v.newL0, qualifyingSuccessors: v.qualifyingSuccessors, successor: v.successor };
}

