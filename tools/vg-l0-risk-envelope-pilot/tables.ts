// The risk-envelope pilot's machine-readable summary and Markdown tables (PROTOCOL.md §15, §18), regenerated from the
// sealed records, the census and the diagnostics — read only, no evaluation. Written analysis and tables only (no visuals).
//   node --no-maglev --experimental-transform-types tools/vg-l0-risk-envelope-pilot/tables.ts
import fs from 'node:fs';
import path from 'node:path';
import { resultsDir } from '../../src/vg-l0-risk-envelope-pilot/context.ts';
import { bound } from '../../src/vg-l0-risk-envelope-pilot/budget.ts';
import { writeJson } from './common.ts';

type J = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
const rd = (f: string): J | null => (fs.existsSync(path.join(resultsDir, f)) ? (JSON.parse(fs.readFileSync(path.join(resultsDir, f), 'utf8')) as J) : null);
const cuts = ['C21', 'C24'] as const;
const arms = ['CTRL', 'EXP'] as const;
const usd = (x: number | null | undefined) => (x === null || x === undefined || !Number.isFinite(x) ? '—' : `${x < 0 ? '−' : ''}$${Math.abs(x).toLocaleString('en-US', { maximumFractionDigits: 0 })}`);
const usd2 = (x: number | null | undefined) => (x === null || x === undefined || !Number.isFinite(x) ? '—' : `${x < 0 ? '−' : ''}$${Math.abs(x).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`);
const pct = (x: number | null | undefined, d = 1) => (x === null || x === undefined || !Number.isFinite(x) ? '—' : `${(100 * x).toFixed(d)}%`);
const md: string[] = ['# Risk-envelope pilot — tables (generated by tools/vg-l0-risk-envelope-pilot/tables.ts from the sealed records)', ''];
const table = (title: string, head: string[], rows: (string | number)[][]) => {
  md.push(`## ${title}`, '', `| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`), '');
};
const summary: J = { kind: 'risk-envelope pilot summary (generated)', generated: new Date().toISOString() };

// ----- budget -----
const b = bound();
const search = Object.fromEntries(cuts.map((c) => [c, Object.fromEntries(arms.map((a) => [a, rd(`search/${c}/${a}.json`)]))]));
const qual = Object.fromEntries(cuts.map((c) => [c, rd(`qualification/${c}.json`)]));
const sel = Object.fromEntries(cuts.map((c) => [c, rd(`selection/${c}.json`)]));
const slices = { C21: rd('slices/C21-slice.json'), C24: rd('slices/C24-validation.json') } as Record<string, J | null>;
const requested = {
  search: Object.fromEntries(cuts.map((c) => [c, Object.fromEntries(arms.map((a) => [a, search[c]![a]?.requested ?? null]))])),
  qualification: Object.fromEntries(cuts.map((c) => [c, qual[c]?.requested ?? null])),
  intervals: Object.fromEntries(cuts.map((c) => [c, slices[c]?.requested ?? null]))
};
const sum = (o: J): number => Object.values(o).reduce((a: number, v) => a + (typeof v === 'number' ? v : v && typeof v === 'object' ? sum(v) : 0), 0);
const fresh = (r: J | null | undefined) => r?.phaseCompute?.fresh ?? null;
const hits = (r: J | null | undefined) => r?.phaseCompute?.archiveHits ?? null;

summary.budget = { bound: b, requested, totalRequested: sum(requested), ceiling: b.budgetCeiling };
table(
  'Budget: requested pilot research evaluations (archive hits included) against the bound and the ceiling',
  ['Stage', 'Cutoff', 'Arm', 'Requested', 'Fresh', 'Archive hits'],
  [
    ...cuts.flatMap((c) => arms.map((a) => ['search', c, a, search[c]![a]?.requested ?? '—', fresh(search[c]![a]) ?? '—', hits(search[c]![a]) ?? '—'])),
    ...cuts.map((c) => ['qualification (union)', c, 'both', qual[c]?.requested ?? '—', fresh(qual[c]) ?? '—', hits(qual[c]) ?? '—']),
    ...cuts.map((c) => [c === 'C21' ? 'next interval (D23)' : 'validation (FULL)', c, 'both', slices[c]?.requested ?? '—', fresh(slices[c]) ?? '—', hits(slices[c]) ?? '—']),
    ['**total**', '', '', `**${sum(requested).toLocaleString('en-US')}**`, '', ''],
    ['deterministic bound', '', '', b.total.toLocaleString('en-US'), '', ''],
    ['authorized ceiling', '', '', b.budgetCeiling.toLocaleString('en-US'), '', '']
  ]
);

// ----- search coverage -----
const laneRows: (string | number)[][] = [];

for (const c of cuts)
  for (const a of arms) {
    const r = search[c]![a];

    if (!r) continue;
    for (const l of r.lanes as J[]) {
      const best = (l.shortlist as J[])[0];

      laneRows.push([c, a, l.key.split('/').slice(2).join('/'), l.requested, l.islands.length, l.extension.stop.split(' (')[0], l.counts.screened, l.failure.screenPlausible, l.counts.r1Centres, l.counts.r1Feasible, (l.r3 as J[]).filter((x) => x.feasible).length, (l.shortlist as J[]).length, best ? usd(best.centre.net) : '—', best ? usd(best.centre.dd) : '—']);
    }
  }
summary.search = Object.fromEntries(cuts.map((c) => [c, Object.fromEntries(arms.map((a) => [a, search[c]![a] ? { requested: search[c]![a]!.requested, phaseCompute: search[c]![a]!.phaseCompute, minutes: search[c]![a]!.minutes, lanes: (search[c]![a]!.lanes as J[]).map((l) => ({ key: l.key, requested: l.requested, islands: l.islands.length, stop: l.extension.stop, counts: l.counts, screenPlausible: l.failure.screenPlausible, screenReasons: l.failure.screenReasons, r3Feasible: (l.r3 as J[]).filter((x) => x.feasible).length, shortlist: (l.shortlist as J[]).map((p) => ({ pick: p.pick, id: p.id, net: p.centre.net, dd: p.centre.dd, envelope: p.centre.envelope })) })) } : null]))]));
table('Search coverage per lane (screen 512 proposals; rung 1 = every fitted centre; feasibility under the lane’s own arm)', ['Cutoff', 'Arm', 'Lane', 'Requested', 'Islands', 'Stop', 'Screened', 'Screen plausible', 'Rung-1 centres', 'Rung-1 feasible', 'Rung-3 feasible', 'Shortlist', 'Best shortlisted net', 'its DD'], laneRows);

// screen reasons per arm
const reasonRows: (string | number)[][] = [];

for (const c of cuts)
  for (const a of arms) {
    const r = search[c]![a];

    if (!r) continue;

    const tot: Record<string, number> = {};

    for (const l of r.lanes as J[]) for (const [k, v] of Object.entries(l.failure.screenReasons as Record<string, number>)) tot[k] = (tot[k] ?? 0) + v;
    reasonRows.push([c, a, ...['plausible', 'net ≤ 0', 'a family unfunded', 'no funded lot', 'DD > ceiling', 'PL > limit', 'BD > limit', 'PL > limit & BD > limit', 'DD > ceiling & PL > limit', 'DD > ceiling & BD > limit', 'DD > ceiling & PL > limit & BD > limit'].map((k) => tot[k] ?? 0)]);
  }
table('Screen outcome by reason (4 lanes × 512 proposals per row; reasons under the row’s arm; identical proposals in both arms)', ['Cutoff', 'Arm', 'plausible', 'net ≤ 0', 'family unfunded', 'no lot', 'DD only', 'PL only', 'BD only', 'PL & BD', 'DD & PL', 'DD & BD', 'DD & PL & BD'], reasonRows);

// ----- census -----
for (const c of cuts) {
  const k = rd(`analysis/census-${c}.json`);

  if (!k) continue;
  summary[`census${c}`] = { replayEqualsSealed: k.replayEqualsSealed, disagreement: k.disagreement, crossSummary: k.crossSummary };

  const d = k.disagreement;
  const row = (name: string, x: J) => [name, x.centres, x.both, x['CTRL-only'], x['EXP-only'], x.neither, x.withRiskShape['CTRL-only'], x.withRiskShape['EXP-only']];

  table(`${c}: policy disagreement of evaluated centres (plausibility: net > 0, both families funded, the arm’s centre envelope)`, ['Set', 'Centres', 'Both pass', 'CTRL-only', 'EXP-only', 'Neither', 'CTRL-only (profitable, funded)', 'EXP-only (profitable, funded)'], [row('screen (identical proposals)', d.screen), row('all centres (both arms, union)', d.allCentres), row('centres CTRL requested', d.byArmSearched.CTRL), row('centres EXP requested', d.byArmSearched.EXP)]);
  table(`${c}: reasons of the disagreement (all centres)`, ['Reason', 'Centres'], Object.entries(d.allCentres.reasons as Record<string, number>).sort((p, q) => q[1] - p[1]).slice(0, 14).map(([r, n]) => [r, n]));
  table(`${c}: rung-3 fits, refinement endpoints and shortlists assessed under both arms (128-draw neighbourhoods)`, ['Searched by', 'Fits', 'Feasible (own arm)', 'Feasible under the other arm', 'Feasible under both'], arms.map((a) => [a, k.crossSummary[a].fits, k.crossSummary[a].feasibleOwn, k.crossSummary[a].feasibleUnderOther, k.crossSummary[a].feasibleBoth]));
}

// ----- qualification -----
const memberRows: (string | number)[][] = [];
const overlap: J = {};

for (const c of cuts) {
  const q = qual[c];

  if (!q) continue;

  const o = { both: 0, 'CTRL-only': 0, 'EXP-only': 0, neither: 0 } as Record<string, number>;

  for (const e of q.evidence as J[]) {
    const bench = (e.shortlistedBy as J[]).some((s) => s.arm === 'benchmark');
    const by = [...new Set((e.shortlistedBy as J[]).map((s) => s.arm))].join('+');
    const cq = e.arms.CTRL.qualified;
    const eq = e.arms.EXP.qualified;

    if (!bench) o[cq && eq ? 'both' : cq ? 'CTRL-only' : eq ? 'EXP-only' : 'neither']!++;
    memberRows.push([
      c,
      e.label.replace(/^(CTRL|EXP) /, '').replace('/broad/', ' '),
      by,
      usd(e.centre.net),
      usd(e.centre.dd),
      usd(e.envelope.centre.principalLossLiquidation),
      usd(e.envelope.centre.bankedDdLiquidation),
      usd(e.confirm.p90Dd),
      usd(e.envelope.confirm.principalLoss.liquidation.p90),
      usd(e.envelope.confirm.bankedDd.liquidation.p90),
      usd(e.confirm.p10),
      cq ? 'Q' : `✗ ${e.arms.CTRL.failed.join(',')}`,
      eq ? 'Q' : `✗ ${(e.arms.EXP.reasons as string[]).join('; ')}`
    ]);
  }
  overlap[c] = o;
}
summary.qualificationOverlap = overlap;
table('Qualification: every member under both arms (centre and confirmation 3 × 128 p90 of marked DD, trade PL and banked DD on the liquidation basis)', ['Cutoff', 'Member', 'Shortlisted by', 'Centre net', 'Centre DD', 'Centre PL (liq)', 'Centre BD (liq)', 'Conf p90 DD', 'Conf p90 PL', 'Conf p90 BD', 'Conf p10 net', 'CTRL', 'EXP'], memberRows);
table('Qualification overlap of the shortlisted members (benchmarks excluded)', ['Cutoff', 'Both qualify', 'CTRL-only', 'EXP-only', 'Neither'], cuts.filter((c) => overlap[c]).map((c) => [c, overlap[c].both, overlap[c]['CTRL-only'], overlap[c]['EXP-only'], overlap[c].neither]));

// ----- selection -----
const selRows: (string | number)[][] = [];
const prim: J = {};

for (const c of cuts) {
  const s = sel[c];

  if (!s) continue;
  prim[c] = {};
  for (const a of arms) {
    const x = s.arms[a];

    prim[c][a] = {};
    for (const [k, label] of Object.entries(x.primaries as Record<string, string | null>)) {
      const r = (x.rankings[k] as J[])[0];

      prim[c][a][k] = r ? { label, centreNet: r.centreNet, centreDd: r.centreDd, pl: r.principalLossLiquidation, bd: r.bankedDdLiquidation, conservativeNet: r.conservativeNet, occupancy: r.occupancy, selectRobust: r.selectRobust, selectP90Dd: r.selectP90Dd, worst10: r.selectWorst10MeanDd, failedScreens: r.failedScreens, id: r.id } : null;
      selRows.push([c, a, k, label ? label.replace(/^(CTRL|EXP) /, '') : 'none (no qualified member)', r ? usd(r.centreNet) : '—', r ? usd(r.centreDd) : '—', r ? usd(r.principalLossLiquidation) : '—', r ? usd(r.bankedDdLiquidation) : '—', r ? usd(r.selectRobust) : '—', r ? usd(r.selectP90Dd) : '—', r ? usd(r.selectWorst10MeanDd) : '—', r ? pct(r.occupancy) : '—', r?.failedScreens ? r.failedScreens.join(',') || 'none' : '—']);
    }
    selRows.push([c, a, 'population', `${x.members} members, ${x.qualified} qualified`, '', '', '', '', '', '', '', '', a === 'EXP' ? `RA1 original = adapted: ${x.ra1OriginalEqualsAdapted}` : '']);
  }
}
summary.primaries = prim;
table('Selection per (cutoff, arm): P0, RA1-original (S4 ≤ 35 % of C0) and RA1-adapted (S4 ≤ 40 %, EXP only) on identical populations', ['Cutoff', 'Arm', 'Selector', 'Primary', 'Centre net', 'Centre DD', 'PL (liq)', 'BD (liq)', 'Sel. robust', 'Sel. p90 DD', 'Sel. worst-10% DD', 'Occupancy', 'Failed RA1 screens'], selRows);

// ----- intervals -----
const intRows: (string | number)[][] = [];

for (const c of cuts) {
  const s = slices[c];

  if (!s) continue;
  for (const r of s.rows as J[])
    intRows.push([
      c,
      r.label.replace(/^(CTRL|EXP) /, ''),
      r.kind === 'benchmark' ? 'benchmark' : (r.roles as J[]).map((x) => `${x.arm} ${x.selector}`).join(', '),
      usd(r.sliceNet),
      usd(r.sliceDd),
      usd(r.nextInterval.maxPrincipalLossMarked),
      usd(r.wholeNet),
      usd(r.wholeDd),
      `${r.neighbourhood.above35pctC0.breaches}/${r.neighbourhood.draws} (${pct(r.neighbourhood.above35pctC0.share)})`,
      `${r.neighbourhood.above40pctC0.breaches}/${r.neighbourhood.draws}`,
      usd(r.neighbourhood.medianSliceDd),
      usd(r.neighbourhood.worstSliceDd),
      usd(r.stresses['cost 20 bps']?.sliceNet)
    ]);
}
summary.intervals = Object.fromEntries(cuts.map((c) => [c, slices[c]?.rows ?? null]));
table('Next intervals (retrospective, previously inspected history): C21 → 2022-01-03 … 2023-12-29 (D23); C24 → 2025-01-02 … 2026-10-30 (FULL, once). Interval DD reset at the cutoff close', ['Cutoff', 'Subject', 'Selected by', 'Interval net', 'Interval DD', 'New-lot max PL (marked)', 'Whole-run net', 'Whole-run DD', 'Nbhd draws DD > 35% C0', 'DD > 40% C0', 'Nbhd median DD', 'Nbhd worst DD', 'Interval net at 20 bps'], intRows);

// ----- hypotheses and the outcome label (PROTOCOL §1, §15) -----
const p0 = (c: string, a: string) => prim[c]?.[a]?.P0 ?? null;
const delta = (c: string) => (p0(c, 'EXP') && p0(c, 'CTRL') ? p0(c, 'EXP').centreNet - p0(c, 'CTRL').centreNet : null);
const intervalDd = (c: string, id: string | undefined) => (slices[c]?.rows as J[] | undefined)?.find((r) => r.id === id)?.sliceDd ?? null;
const d21 = delta('C21');
const d24 = delta('C24');
const h3 = p0('C21', 'EXP') && p0('C21', 'CTRL') && slices.C21 ? { exp: intervalDd('C21', p0('C21', 'EXP').id), ctrl: intervalDd('C21', p0('C21', 'CTRL').id) } : null;
const h3holds = h3 && h3.exp !== null && h3.ctrl !== null ? h3.exp <= h3.ctrl + 5000 : null;
const label = (() => {
  if (d21 === null || d24 === null || h3holds === null) return 'inconclusive (a missing primary or an incomplete stage)';
  const up = d21 > 2500 || d24 > 2500;
  const down = d21 < -2500 || d24 < -2500;

  if (up && !down && h3holds) return 'experimental improvement';
  if (Math.abs(d21) <= 2500 && Math.abs(d24) <= 2500) return 'approximately equivalent';
  if ((down && !up) || (!h3holds && !up)) return 'worse';
  return 'inconclusive';
})();
const h2 = (() => {
  const pop = rd('diagnostics/population-C21.json');
  const pop24 = rd('diagnostics/population-C24.json');
  const rows = [...((pop?.rows as J[]) ?? []), ...((pop24?.rows as J[]) ?? [])];
  const expQ = cuts.flatMap((c) => ((qual[c]?.evidence as J[]) ?? []).filter((e) => (e.shortlistedBy as J[]).some((s) => s.arm === 'EXP') && e.arms.EXP.qualified).map((e) => ({ c, e })));
  const hits = expQ.filter(({ e }) => e.centre.dd > 35000 && rows.find((r) => r.id === e.id)?.givebackDominated === true);

  return { expQualified: expQ.length, allSatisfyEnvelope: expQ.every(({ e }) => e.arms.EXP.gates.Q2), withDdAbove35AndGivebackDominated: hits.map(({ c, e }) => ({ cutoff: c, label: e.label, dd: e.centre.dd })), holds: expQ.length > 0 && expQ.every(({ e }) => e.arms.EXP.gates.Q2) && hits.length > 0, computable: rows.length > 0 };
})();

summary.hypotheses = { H1: { delta: d21, holds: d21 === null ? null : d21 > 2500 }, 'H1′': { delta: d24, holds: d24 === null ? null : d24 > 2500 }, H2: h2, H3: { ...h3, holds: h3holds, margin: 5000 }, label };
table('Precommitted hypotheses and the outcome label (PROTOCOL §1, §15)', ['Item', 'Value', 'Holds'], [
  ['H1: Δ21 = EXP P0 − CTRL P0 centre net (C21) > $2,500', usd2(d21), String(summary.hypotheses.H1.holds)],
  ['H1′: Δ24 (C24) > $2,500', usd2(d24), String(summary.hypotheses['H1′'].holds)],
  ['H2: ≥ 1 EXP-qualified member with DD > 35 % C0 and giveback-dominated (D3 U ≥ ½ DD)', `${h2.withDdAbove35AndGivebackDominated.length} of ${h2.expQualified} EXP-qualified`, h2.computable ? String(h2.holds) : 'diagnostics pending'],
  ['H3: C21 interval DD of EXP P0 ≤ CTRL P0’s + $5,000', h3 ? `${usd2(h3.exp)} vs ${usd2(h3.ctrl)}` : '—', String(h3holds)],
  ['**Outcome label**', `**${label}**`, '']
]);

// ----- diagnostics summaries -----
for (const c of cuts) {
  const pop = rd(`diagnostics/population-${c}.json`);

  if (!pop) continue;

  const rows = pop.rows as J[];
  const by = (pred: (r: J) => boolean) => rows.filter(pred).length;

  summary[`diagnostics${c}`] = {
    subjects: rows.length,
    cpuPolicy: { both: by((r) => r.policies.CTRL && r.policies.EXP), ctrlOnly: by((r) => r.policies.CTRL && !r.policies.EXP), expOnly: by((r) => !r.policies.CTRL && r.policies.EXP), neither: by((r) => !r.policies.CTRL && !r.policies.EXP) },
    D1at40: by((r) => r.views.marked.D1.illustrativePassAt40),
    D2pass: by((r) => r.views.marked.D2.illustrativePass),
    D3illustrative: by((r) => r.d3Illustrative),
    givebackDominated: by((r) => r.givebackDominated),
    excludedButPromising: rows
      .filter((r) => !r.policies.CTRL && !r.policies.EXP && r.net > 0 && (r.views.marked.D2.illustrativePass || r.d3Illustrative))
      .sort((p, q) => q.net - p.net)
      .slice(0, 10)
      .map((r) => ({ id: r.id, cell: r.cell, net: r.net, dd: r.dd, pl: r.envelope.principalLossLiquidation, bd: r.envelope.bankedDdLiquidation, D1: r.views.marked.D1.pct, D2: r.views.marked.D2.utilization, D3U: r.unbankedGivebackShare, sources: r.sources }))
  };
  table(`${c}: nonbinding diagnostics of the recorded populations (${rows.length} distinct centres of both arms; CPU replays)`, ['View (illustrative coefficients; never thresholds)', 'Pass / admitted'], [
    ['CTRL policy (DD ≤ 35 % C0)', by((r) => r.policies.CTRL)],
    ['EXP policy (40 / 25 / 25)', by((r) => r.policies.EXP)],
    ['D1 peak-equity DD ≤ 40 %', summary[`diagnostics${c}`].D1at40],
    ['D2 capped hybrid utilization ≤ 1 (40 / 30 / 60)', summary[`diagnostics${c}`].D2pass],
    ['D3 illustrative (DD ≤ 60 % C0 ∧ BD ≤ 25 % ∧ PL ≤ 25 %)', summary[`diagnostics${c}`].D3illustrative],
    ['giveback-dominated (D3 U ≥ ½ DD)', summary[`diagnostics${c}`].givebackDominated],
    ['excluded by both arms but net > 0 and admitted by D2 or D3', summary[`diagnostics${c}`].excludedButPromising.length]
  ]);
}

fs.mkdirSync(path.join(resultsDir, 'tables'), { recursive: true });
fs.writeFileSync(path.join(resultsDir, 'tables', 'TABLES.md'), `${md.join('\n')}\n`);
writeJson(path.join(resultsDir, 'tables', 'summary.json'), summary);
console.log(JSON.stringify({ totalRequested: summary.budget.totalRequested, hypotheses: { H1: summary.hypotheses.H1, H1p: summary.hypotheses['H1′'], H3: summary.hypotheses.H3, label } }));
